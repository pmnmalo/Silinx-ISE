#!/usr/bin/env node
// The 7-series' examples through the Silinx toolchain against AMD Vivado (#3760, part of #3145): each example (gates …
// micro80) on the Basys 3 (xc7a35tcpg236-1) and the Nexys A7 (xc7a100tcsg324-1) built three ways:
//   - silinx: the open flow, here, as the application runs it (Yosys's synth_xilinx, nextpnr-himbaechel-xc7, the .bit):
//     its LUTs (the LUT sites with logic, Vivado's way) and nextpnr's feed-throughs (#3160), registers, slices, Fmax
//     (nextpnr's estimate), warnings;
//   - vivado: Vivado's own flow from the HDL, as the application's Vivado flow runs it (server/vivado.js's run.tcl:
//     synth_design, opt_design, place_design, route_design, the timing, write_bitstream): its warnings, utilisation,
//     Fmax, DRC;
//   - netlist: Silinx's netlist (the open flow's synthesis, written as an EDIF by the same Yosys) placed and routed by
//     Vivado (link_design, no opt_design: the same netlist) and written as a bitstream: Vivado's DRC on Silinx's
//     synthesis, its LUTs counted Vivado's way (a LUT site once, no feed-throughs: so Silinx's synthesis and Vivado's
//     compare apart from nextpnr's packing), its Fmax on the same netlist.
// Vivado runs on the ISE runner's machine (its Docker image with Vivado ML Standard, scripts/vitis-hls-image/), alone,
// one design after another in one container.
//
//   node scripts/xc7-vivado-compare.mjs [--boards basys3,nexys-a7] [--filter '^(blinky|pong)$'] [--update]
//   --dry: the builds written in a work folder (kept, its path printed), Vivado not run
//   node scripts/xc7-vivado-compare.mjs --detach [--boards …] [--filter …]   Vivado started on the host in the
//     background (it does not depend on this machine staying awake); it prints the run's name
//   node scripts/xc7-vivado-compare.mjs --collect <run> [--update]   its results once it is done (else its progress);
//     the run's folder on the host deleted only once --update has saved them
//     --update: the results merged into test/xc7-vivado-comparison.json and its table written in docs/TOOLCHAIN.md
//     (test/xc7-vivado-comparison.test.js checks both)
//   SILINX_ISE_HOST=user@host (else ~/.silinx/config.json's ssh user and host, read here, never written in a file),
//   SILINX_ISE_HOST=local: the image on this machine; SILINX_VIVADO_IMAGE (default xilinx/vitis-hls:2025.2);
//   SILINX_VIVADO_TIMEOUT (a build's, s, default 3600).
// Vivado's own files (its checkpoints, bitstreams, logs, reports) stay in a temporary folder on the host and here,
// deleted after the run: only numbers and Vivado's message lines are written (never commit Xilinx files).
