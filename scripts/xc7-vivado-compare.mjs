/** net.tcl: Silinx's netlist (netlist.edf, its constraints netlist.xdc, the board's configuration props.tcl) placed and
 *  routed by Vivado with no optimisation, its reports written under the names server/vivado.js's run.tcl gives them,
 *  then written as a bitstream (write_bitstream's own DRC). */
export function netTcl() {
  return `# Generated by Silinx (#3760, scripts/xc7-vivado-compare.mjs): Silinx's netlist placed and routed by Vivado.
#   vivado -mode batch -source net.tcl -tclargs <folder> <top> <part>
lassign $argv dir top part
cd $dir
set_param general.maxThreads 2
# with -top, link_design looks for an EDIF named after the top module (#3738)
file copy -force netlist.edf $top.edf
read_edif $top.edf
read_xdc netlist.xdc
link_design -top $top -part $part
source props.tcl
place_design
route_design
report_route_status -file \${top}_route.rpt
report_drc -file \${top}_drc.rpt
report_utilization -file \${top}_util.rpt
report_timing_summary -max_paths 10 -report_unconstrained -file \${top}_timing.rpt
write_bitstream -force \${top}.bit
puts "=== SILINX DONE ==="
`;
}

/** run.sh: in the Vivado image, each design of <work>/designs.txt ("<id> <top>  <part>" a line): its HDL through the
 *  application's run.tcl (designs/<id>/hdl), then its netlist through net.tcl (designs/<id>/net); each one's exit code
 *  in results/<id>/status.txt, its reports and log moved to results/<id>/{hdl,net}/, the rest (checkpoints, .Xil)
 *  deleted; at the end, <work>/done (for --collect). */
export function runSh() {
  return `#!/bin/bash
# Generated by Silinx (#3760, scripts/xc7-vivado-compare.mjs).   bash run.sh <work folder>
set -u
W=\${1:?usage: run.sh <work folder>}
T=\${SILINX_VIVADO_TIMEOUT:-3600}
S=\${VIVADO_SETTINGS:-$(ls -d ${SETTINGS.join(' ')} 2>/dev/null | head -1)}
[ -n "$S" ] || { echo "no Vivado settings64.sh found (set VIVADO_SETTINGS)"; exit 2; }
# shellcheck disable=SC1090
. "$S" >/dev/null
[ -n "\${HOME:-}" ] && [ -w "$HOME" ] || export HOME=/tmp
keep() { for f in vivado.log "$2"_synth_util.rpt "$2"_util.rpt "$2"_route.rpt "$2"_drc.rpt "$2"_timing.rpt "$2".bit; do [ -f "$1/$f" ] && mv "$1/$f" "$3/"; done; rm -rf "$1/.Xil" "$1"/*.dcp; }
while read -r id top part; do
  [ -n "$id" ] || continue
  D="$W/designs/$id"; R="$W/results/$id"
  mkdir -p "$R/hdl" "$R/net"
  ( cd "$D/hdl" && timeout "$T" bash run.sh synth translate map par trce bitgen >/dev/null 2>&1 ); echo "hdl $?" >"$R/status.txt"
  keep "$D/hdl" "$top" "$R/hdl"
  ( cd "$D/net" && timeout "$T" vivado -mode batch -nojournal -notrace -log vivado.log -source "$W/net.tcl" -tclargs "$D/net" "$top" "$part" >/dev/null 2>&1 ); echo "net $?" >>"$R/status.txt"
  keep "$D/net" "$top" "$R/net"
  echo "$id: $(xargs <"$R/status.txt")"
done <"$W/designs.txt"
touch "$W/done"
`;
}

/** Vivado's warnings of a log's lines (CRITICAL WARNING and WARNING, its own: "[Synth 8-3917] …"), once each, sorted;
 *  the build's folder in them written /work/, as the application's builds have it (/…/designs/<id>/hdl/ -> /work/). */
export const logWarnings = (text) => [...new Set(String(text).split(/\r?\n/).filter((l) => /^(CRITICAL WARNING|WARNING): \[/.test(l))
  .map((l) => l.replace(/\s+/g, ' ').trim().replace(/\/\S*?\/designs\/[\w-]+\/(?:hdl|net)\//g, '/work/')))].sort();

/** A Vivado build's numbers of its reports (collectVivadoReports's) and its log: { ok, routed, luts, regs, slices,
 *  bram, dsp, fmaxMHz, met, drc: [[rule, severity, checks]], drcErrors, warnings: [lines], bit: the .bit's size or
 *  null }, or { ok: false, error } when Vivado failed. */
export function buildNumbers(status, reports, log) {
  if (status !== '0') return { ok: false, error: `Vivado ${status == null ? 'did not run' : `exited with ${status}`}`, warnings: logWarnings(log) };
  const u = reports.map?.summary || {};
  const t = reports.timing || {};
  return {
    ok: true,
    routed: reports.par?.routed ?? null,
    luts: u.luts?.used ?? 0, regs: u.ffs?.used ?? 0, slices: u.slices?.used ?? 0, bram: u.bram?.used ?? 0, dsp: u.dsp?.used ?? 0,
    fmaxMHz: t.noConstraints ? null : (t.maxFreqMHz ?? null),
    met: t.noConstraints ? null : (t.met ?? null),
    drc: (reports.drc?.rules || []).map((r) => [r.rule, r.severity, r.checks]),
    drcErrors: (reports.drc?.errors ?? 0) + (reports.drc?.criticalWarnings ?? 0),
    warnings: logWarnings(log),
    bit: reports.bit?.size ?? null,
  };
}

/** The open flow's numbers of its reports and log (runOpenImplementation's): { luts (the LUT sites with logic: the count
 *  Vivado's way), feedthroughs (the sites nextpnr's packer made feed-throughs, #3160), lutSites (both), regs, slices,
 *  carry4, bram, dsp, fmaxMHz, met, warnings, bit }. */
export function silinxNumbers(reports, lines) {
  const row = (re) => reports.map?.utilization?.find((u) => re.test(u.name))?.used ?? 0;
  const luts = row(/^Number of Slice LUTs$/), feedthroughs = row(/^LUTs as feed-throughs/);
  return {
    luts, feedthroughs, lutSites: luts + feedthroughs, regs: row(/^Number of Slice Registers$/), slices: row(/^Number of occupied Slices$/),
    carry4: row(/^CARRY4$/), bram: row(/^RAMB(18|36)/), dsp: row(/^DSPs$/),
    fmaxMHz: reports.timing?.maxFreqMHz ?? null, met: reports.timing?.met ?? null,
    warnings: lines.filter((l) => /WARNING|ERROR/.test(l)), bit: reports.bit?.size ?? null,
  };
}

/** The results file's content with a run's designs ({ id: { board, name, silinx, vivado, netlist } }) put in (each
 *  board's examples in the examples' order; a design measured again replaced). */
export function mergeResults(old, designs, { image, examples }) {
  const all = structuredClone(old?.boards || {});
  for (const d of Object.values(designs)) (all[d.board] ||= {})[d.name] = { silinx: d.silinx, vivado: d.vivado, netlist: d.netlist };
  const order = (b) => Object.keys(all[b]).sort((x, y) => examples.indexOf(x) - examples.indexOf(y));
  const boards = Object.fromEntries(Object.keys(BOARDS).filter((b) => all[b]).map((b) => [b, Object.fromEntries(order(b).map((n) => [n, all[b][n]]))]));
  return { issue: 3760, vivado: '2025.2', image, parts: BOARDS, units: { fmax: 'MHz' }, boards };
}

/** The board's XDC as Silinx's netlist names its ports: a port of one bit (a VHDL std_logic_vector(0 downto 0), a Verilog
 *  [0:0]) is a scalar in Yosys's JSON and in the EDIF written of it, so its pin's get_ports {btn[0]} becomes {btn} (else
 *  Vivado finds no port, and its DRC stops the bitstream on the unplaced one). ports: the top module's JSON ports. */
export function netlistXdc(xdc, ports) {
  const one = new Set(Object.entries(ports).filter(([, p]) => p.bits.length === 1).map(([n]) => n));
  return String(xdc).replace(/\[get_ports \{([A-Za-z_]\w*)\[\d+\]\}\]/g, (m, n) => (one.has(n) ? `[get_ports {${n}}]` : m));
}

const BOARD_NAMES = { basys3: 'Basys 3', 'nexys-a7': 'Nexys A7' };
const mhz = (x) => (x == null ? '–' : x.toFixed(0));
const ratio = (a, b) => (a == null || !b ? '–' : (a / b).toFixed(2));

/** The table docs/TOOLCHAIN.md shows of the results (Markdown): a row per board and example. */
export function comparisonTable(results) {
  const rows = ['| Board | Example | LUTs: Silinx (+ feed-throughs) | LUTs: Silinx\'s netlist in Vivado | LUTs: Vivado | Registers: Silinx / Vivado | Slices: Silinx / Vivado | MHz: Silinx | MHz: Silinx\'s netlist in Vivado | MHz: Vivado | Vivado\'s DRC on Silinx\'s netlist |',
    '|---|---|---|---|---|---|---|---|---|---|---|'];
  for (const [b, ex] of Object.entries(results.boards)) {
    for (const [n, { silinx: s, vivado: v, netlist: x }] of Object.entries(ex)) {
      const drc = !x.ok ? 'failed' : x.drcErrors ? `${x.drcErrors} errors` : x.drc.length ? x.drc.map(([r]) => r).join(', ') : 'clean';
      rows.push(`| ${BOARD_NAMES[b]} | ${n} | ${s.luts} (+${s.feedthroughs}) | ${x.luts ?? '–'} | ${v.luts ?? '–'} | ${s.regs} / ${v.regs ?? '–'} | ${s.slices} / ${v.slices ?? '–'} | ${mhz(s.fmaxMHz)} | ${mhz(x.fmaxMHz)} | ${mhz(v.fmaxMHz)} | ${drc} |`);
    }
  }
  return rows.join('\n');
}

/** The sums of a board's examples (those with a clock for the frequencies): Silinx's LUTs, its LUT sites, its
 *  netlist's LUTs in Vivado, Vivado's; the frequencies' geometric means' ratio. */
export function boardSummary(examples) {
  const e = Object.values(examples);
  const sum = (f) => e.reduce((a, x) => a + (f(x) ?? 0), 0);
  const timed = e.filter((x) => x.silinx.fmaxMHz && x.vivado.fmaxMHz);
  const geo = (f) => Math.exp(timed.reduce((a, x) => a + Math.log(f(x)), 0) / timed.length);
  return {
    luts: sum((x) => x.silinx.luts), lutSites: sum((x) => x.silinx.lutSites), netlistLuts: sum((x) => x.netlist.luts), vivadoLuts: sum((x) => x.vivado.luts),
    fmaxRatio: +(geo((x) => x.silinx.fmaxMHz) / geo((x) => x.vivado.fmaxMHz)).toFixed(3),
  };
}

const MARK = ['<!-- xc7-vivado-comparison: begin (scripts/xc7-vivado-compare.mjs --update) -->', '<!-- xc7-vivado-comparison: end -->'];
/** docs/TOOLCHAIN.md's text with the table between its markers replaced by results'. */
export function withTable(doc, results) {
  const [a, b] = [doc.indexOf(MARK[0]), doc.indexOf(MARK[1])];
  if (a < 0 || b < a) throw new Error(`docs/TOOLCHAIN.md: no ${MARK[0]} … ${MARK[1]}`);
  return `${doc.slice(0, a + MARK[0].length)}\n${comparisonTable(results)}\n${doc.slice(b)}`;
}
export const tableOf = (doc) => doc.slice(doc.indexOf(MARK[0]) + MARK[0].length, doc.indexOf(MARK[1])).trim();

// an example on a board through the open flow (here): its numbers, its netlist as an EDIF and its XDC in folder net/,
// and its Vivado build folder (the application's run.tcl, run.sh, sources, XDC) in hdl/
async function prepareDesign(d, into, D) {
  const { exampleProject } = await import('../test/examples-lib.mjs');
  const { runOpenImplementation } = await import('../server/open-flow.js');
  const { generateVivadoBuild, configProperties } = await import('../server/vivado.js');
  const { resolveBoard } = await import('../server/devices.js');
  const { yosysNode } = await import('../packages/silinx-fpga/src/node.js');
  const lines = [];
  const job = { log: (l) => lines.push(l), result: null, cancelled: false, procs: new Set() };
  const o = exampleProject(d.name, { board: d.board }, path.join(into, 'open'));
  const r = await runOpenImplementation(job, { project: o.project, projectDir: o.dir, steps: ['synth', 'translate', 'par', 'trce', 'bitgen'] });
  const netlist = fs.readFileSync(path.join(o.dir, r.reports.files.netlist), 'utf8');
  const top = Object.entries(JSON.parse(netlist).modules).find(([, m]) => m.attributes?.top)?.[0] || o.project.top;
  const out = await yosysNode(['-q', '-p', edifScript(top)], { 'netlist.json': netlist });
  const board = resolveBoard(o.project.board).board;
  fs.mkdirSync(path.join(D, 'net'), { recursive: true });
  fs.writeFileSync(path.join(D, 'net', 'netlist.edf'), out['netlist.edf']);
  const ports = JSON.parse(netlist).modules[top].ports;
  fs.writeFileSync(path.join(D, 'net', 'netlist.xdc'), netlistXdc(fs.readFileSync(path.join(o.dir, o.project.constraints), 'utf8'), ports));
  fs.writeFileSync(path.join(D, 'net', 'props.tcl'), `${configProperties(board).map(([p, v]) => `set_property ${p} ${v} [current_design]`).join('\n')}\n`);
  const v = exampleProject(d.name, { board: d.board }, path.join(into, 'vivado'));
  const gen = await generateVivadoBuild(v.project, v.dir, { board });
  fs.cpSync(gen.buildDir, path.join(D, 'hdl'), { recursive: true });
  return { top, vivadoTop: gen.top, silinx: silinxNumbers(r.reports, lines) };
}

/** The command line's options, checked: { flags, values } or an error (an unknown option, a missing value) — never a
 *  Vivado run started on a mistyped one (--help: the usage). */
export function parseArgs(argv) {
  const FLAGS = ['--update', '--detach', '--dry'], VALUES = ['--boards', '--filter', '--collect'];
  const out = { flags: new Set(), values: {} };
  for (let i = 0; i < argv.length; i++) {
    if (FLAGS.includes(argv[i])) out.flags.add(argv[i]);
    else if (VALUES.includes(argv[i]) && argv[i + 1] != null && !argv[i + 1].startsWith('--')) out.values[argv[i]] = argv[++i];
    else return { error: VALUES.includes(argv[i]) ? `${argv[i]}: a value is missing` : `unknown option ${argv[i]}` };
  }
  if (out.values['--collect'] && (out.flags.has('--detach') || out.flags.has('--dry'))) return { error: '--collect: no --detach nor --dry' };
  return out;
}
const USAGE = `usage: node scripts/xc7-vivado-compare.mjs [--boards basys3,nexys-a7] [--filter '^(blinky|pong)$'] [--detach | --dry] [--update]
       node scripts/xc7-vivado-compare.mjs --collect silinx-xc7v-… [--update]`;

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.error) { console.error(`${process.argv.includes('--help') ? '' : `${args.error}\n`}${USAGE}`); process.exit(2); }
  const { iseWorkBase, configPath } = await import('../server/toolchain.js');
  const { DOCKER_ISOLATION } = await import('../server/ise.js');
  const { VIVADO_DOCKER_ARGS, collectVivadoReports } = await import('../server/vivado.js');
  const { EXAMPLES } = await import('../test/examples-lib.mjs');
  const a = [...args.flags];
  const opt = (k) => args.values[k] ?? null;
  const IMAGE = process.env.SILINX_VIVADO_IMAGE || 'xilinx/vitis-hls:2025.2';
  let HOST = process.env.SILINX_ISE_HOST;
  if (!HOST) try { const s = JSON.parse(fs.readFileSync(configPath(), 'utf8')).ssh; if (s?.host) HOST = s.user ? `${s.user}@${s.host}` : s.host; } catch { /* no config */ }
  if (!HOST) { console.error('set SILINX_ISE_HOST=user@host (the machine with the Vivado image, reached by ssh with a key), or SILINX_ISE_HOST=local'); process.exit(2); }
  const collect = opt('--collect');
  if (collect && !/^silinx-xc7v-[\w]+$/.test(collect)) { console.error(`--collect: not a run's name: ${collect}`); process.exit(2); }
  const run = (cmd, args) => execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], maxBuffer: 256 << 20 });
  const SSH = ['-o', 'BatchMode=yes', '-o', 'ServerAliveInterval=30', '-o', 'ServerAliveCountMax=4', '-o', 'ConnectTimeout=30'];
  const ssh = (cmd) => run('ssh', [...SSH, '--', HOST, `export PATH="$PATH:/usr/local/bin"; ${cmd}`]);
  const rsync = (...args) => run('rsync', ['-a', '-e', `ssh ${SSH.join(' ')}`, ...args]);
  const remoteOf = (name) => `${iseWorkBase('silinx-xc7v')}/${name}`;
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'silinx-xc7v-'));
  const name = collect || path.basename(work);
  const local = HOST === 'local';
  const docker = ['run', '--rm', ...DOCKER_ISOLATION, ...VIVADO_DOCKER_ARGS, '--platform', 'linux/amd64', '-e', `SILINX_VIVADO_TIMEOUT=${Number(process.env.SILINX_VIVADO_TIMEOUT) || 3600}`];
  try {
    let meta;
    if (collect) {
      // a detached run: its progress, or its results once its last design is done
      const remote = remoteOf(collect);
      const state = ssh(`cd ${remote} && wc -l < designs.txt && (ls results 2>/dev/null | wc -l) && (ls done 2>/dev/null || docker ps -q -f name=${collect} | sed 's/.*/running/')`).trim().split(/\s+/);
      if (state[2] !== 'done') {
        console.log(`${collect}: ${state[1]} of ${state[0]} designs started, ${state[2] === 'running' ? 'still running' : 'STOPPED before its end (its container is gone): run it again'}`);
        process.exitCode = 3;
        return;
      }
      rsync(`${HOST}:${remote}/silinx.json`, `${HOST}:${remote}/results`, `${work}/`);
      meta = JSON.parse(fs.readFileSync(path.join(work, 'silinx.json'), 'utf8'));
    } else {
      const designs = selectDesigns(EXAMPLES, (opt('--boards') || 'basys3,nexys-a7').split(','), opt('--filter'));
      if (!designs.length) { console.error('no design selected (--boards, --filter)'); process.exit(2); }
      const busy = local ? [] : jobContainers(ssh("docker ps --format '{{.Image}}\t{{.Names}}'"), IMAGE);
      if (busy.length) { console.error(`another job is running on the host (${busy.join(', ')}): Vivado runs alone there, wait for it`); process.exit(4); }
      const list = [];
      for (const d of designs) {
        Object.assign(d, await prepareDesign(d, path.join(work, 'projects', d.id), path.join(work, 'designs', d.id)));
        if (d.top !== d.vivadoTop) throw new Error(`${d.id}: the netlist's top <${d.top}> is not the project's <${d.vivadoTop}>`);
        list.push(`${d.id} ${d.top} ${d.part}`);
        console.log(`${d.id}: Silinx ${d.silinx.luts} LUTs, ${d.silinx.regs} registers, ${d.silinx.fmaxMHz ?? '-'} MHz; Vivado's builds written`);
      }
      meta = { image: IMAGE, designs: Object.fromEntries(designs.map((d) => [d.id, d])) };
      fs.writeFileSync(path.join(work, 'designs.txt'), `${list.join('\n')}\n`);
      fs.writeFileSync(path.join(work, 'silinx.json'), JSON.stringify(meta, null, 2));
      fs.writeFileSync(path.join(work, 'net.tcl'), netTcl());
      fs.writeFileSync(path.join(work, 'run.sh'), runSh());
      fs.rmSync(path.join(work, 'projects'), { recursive: true, force: true });
      if (a.includes('--dry')) { console.log(`--dry: Vivado's builds written in ${work}, not run`); process.env.SILINX_KEEP = '1'; return; }
      if (local) run('docker', [...docker, '-v', `${work}:/w`, IMAGE, 'bash', '/w/run.sh', '/w']);
      else {
        const remote = remoteOf(name), mount = remote.startsWith('/') ? remote : `$HOME/${remote}`;
        ssh(`rm -rf ${remote} && mkdir -p ${remote}`);
        rsync(`${work}/`, `${HOST}:${remote}/`);
        if (a.includes('--detach')) {
          // (the container named as the run: --collect finds it)
          ssh(`docker run -d --name ${name} ${docker.slice(1).join(' ')} -v "${mount}":/w ${IMAGE} bash /w/run.sh /w`);
          console.log(`${name}: ${designs.length} designs started on the host`);
          console.log(`collect with: node scripts/xc7-vivado-compare.mjs --collect ${name} --update`);
          return;
        }
        try {
          process.stdout.write(ssh(`docker run ${docker.slice(1).join(' ')} -v "${mount}":/w ${IMAGE} bash /w/run.sh /w`));
          rsync(`${HOST}:${remote}/results/`, `${work}/results/`);
        } finally { ssh(`rm -rf ${remote}`); }
      }
    }

    // Vivado's numbers (its reports read as the application reads them) beside Silinx's
    const results = {};
    for (const d of Object.values(meta.designs)) {
      const R = path.join(work, 'results', d.id);
      const status = Object.fromEntries((fs.existsSync(path.join(R, 'status.txt')) ? fs.readFileSync(path.join(R, 'status.txt'), 'utf8') : '').trim().split('\n').filter(Boolean).map((l) => l.split(' ')));
      const numbers = async (k) => {
        const dir = path.join(R, k), log = fs.existsSync(path.join(dir, 'vivado.log')) ? fs.readFileSync(path.join(dir, 'vivado.log'), 'utf8') : '';
        return buildNumbers(status[k], fs.existsSync(dir) ? await collectVivadoReports(dir, d.top, d.part) : {}, log);
      };
      results[d.id] = { board: d.board, name: d.name, silinx: d.silinx, vivado: await numbers('hdl'), netlist: await numbers('net') };
      const r = results[d.id], s = (x) => (x.ok ? `${x.luts} LUTs, ${x.fmaxMHz ?? '-'} MHz, ${x.warnings.length} warnings, DRC ${x.drcErrors} errors` : x.error);
      console.log(`${d.id.padEnd(20)} Silinx ${r.silinx.luts} LUTs, ${r.silinx.fmaxMHz ?? '-'} MHz | Vivado ${s(r.vivado)} | Silinx's netlist in Vivado ${s(r.netlist)}`);
    }
    if (a.includes('--update')) {
      const old = fs.existsSync(RESULTS) ? JSON.parse(fs.readFileSync(RESULTS, 'utf8')) : null;
      const m = mergeResults(old, results, { image: meta.image, examples: EXAMPLES });
      fs.writeFileSync(RESULTS, `${JSON.stringify(m, null, 1)}\n`);
      fs.writeFileSync(DOC, withTable(fs.readFileSync(DOC, 'utf8'), m));
      console.log(`${path.relative(ROOT, RESULTS)} and ${path.relative(ROOT, DOC)}'s table updated (${Object.keys(results).length} designs)`);
    }
    if (collect) {
      if (keepsRun(a)) console.log(`${collect}: its results kept on the host; save them with: node scripts/xc7-vivado-compare.mjs --collect ${collect} --update`);
      else ssh(`rm -rf ${remoteOf(collect)}`);
    }
  } finally { if (!process.env.SILINX_KEEP) fs.rmSync(work, { recursive: true, force: true }); }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main().catch((e) => { console.error(e.message); process.exit(1); });
