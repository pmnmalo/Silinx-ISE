#!/usr/bin/env node
// The 7-series' BSCANE2 measured with AMD Vivado (#3767): which bits its corner PIPs and its chain set. nextpnr routes the
// BSCAN's pins through CFG_CENTER_MID's PIPs (CFG_CENTER_BSCAN<n>_DRCK -> CFG_CENTER_LOGIC_OUTS_…, CFG_CENTER_IMUX… ->
// CFG_CENTER_BSCAN<n>_TDO), which Project X-Ray's database does not have (one PIP per pin, 44 in all); its
// CFG_CENTER_MID.BSCAN.JTAG_CHAIN_<n> bits it has. Blinky with Silinx's logic analyzer on the Basys 3 (the open flow's
// netlist, its BSCANE2 on the JTAG chains 1 … 4), the same with the chain 1 on the site BSCAN_X0Y3 (LOC), and blinky
// alone, each placed and routed by Vivado and written as a bitstream (on the ISE runner's machine, its Docker image with
// Vivado: scripts/vitis-hls-image/); then each .bit read back here (fpga/xc7/readback.js, bit2fasm): the CFG_CENTER_MID
// tile's features and its bits no feature names, against blinky's alone; Vivado's site of the BSCAN and its PIPs.
//
//   node scripts/xc7-bscan-vivado.mjs [--keep] [--dry]   --keep: the work folder (Vivado's files) left, its path printed;
//     --dry: the designs made here, Vivado not run; --read <kept work folder>: a kept run's bitstreams read back again
//   SILINX_ISE_HOST=user@host (else ~/.silinx/config.json's ssh user and host, never written in a file), or local;
//   SILINX_VIVADO_IMAGE (default xilinx/vitis-hls:2025.2).
// Vivado's files (its bitstreams, logs) stay in a temporary folder, deleted after the run: only what the readback finds is
// printed (never commit Xilinx files).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import zlib from 'node:zlib';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { edifScript, jobContainers } from './xc7-timing-vivado.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const PART = 'xc7a35tcpg236-1';
const CAPTURE = { clock: 'clk', probes: ['u_knight.count', 'u_knight.dir'], depth: 1024, pre: 64, trigger: { combine: 'and', conditions: [{ probe: 'u_knight.dir', op: 'rise' }] } };
// the designs: [id, JTAG_CHAIN (none: no capture), the BSCAN's LOC]
export const DESIGNS = [['none', null, null], ['c1', 1, null], ['c2', 2, null], ['c3', 3, null], ['c4', 4, null], ['c1-x0y3', 1, 'BSCAN_X0Y3']];

/** bscan.tcl: a design placed, routed and written as a bitstream by Vivado; bscan.txt: the BSCAN's site and the PIPs of
 *  its pins' nets in the CFG_CENTER tiles. */
export function bscanTcl() {
  return `# Generated by Silinx (#3767, scripts/xc7-bscan-vivado.mjs).   vivado -mode batch -source bscan.tcl -tclargs <folder> <top> <part>
lassign $argv dir top part
cd $dir
set_param general.maxThreads 2
file copy -force netlist.edf $top.edf
read_edif $top.edf
read_xdc netlist.xdc
link_design -top $top -part $part
set_property CFGBVS VCCO [current_design]
set_property CONFIG_VOLTAGE 3.3 [current_design]
place_design
route_design
set f [open bscan.txt w]
foreach c [get_cells -quiet -hierarchical -filter {REF_NAME == BSCANE2}] {
  puts $f "CELL\\t$c\\t[get_property LOC $c]\\t[get_property JTAG_CHAIN $c]"
  foreach net [get_nets -quiet -of_objects [get_pins -of_objects $c]] {
    foreach pip [get_pips -quiet -of_objects $net -filter {NAME =~ CFG_CENTER*}] { puts $f "PIP\\t$net\\t$pip" }
  }
}
close $f
write_bitstream -force design.bit
puts "=== SILINX DONE ==="
`;
}

/** The CFG_CENTER_MID tile of a .bit read back: { features: ['BSCAN.JTAG_CHAIN_1', …], unknown: [bitKey…] (its windows'
 *  bits no feature names) }. index: readback.js bitIndexXc7's. */
export function cfgCenterBits(bytes, index, { readBitFramesXc7, framesToFeatures, keyFrame, keyBit }) {
  const { features, unknown } = framesToFeatures(readBitFramesXc7(bytes, index).frames, index);
  const [name, tile] = [...index.tiles].find(([, t]) => t.type === 'CFG_CENTER_MID');
  const inTile = k => tile.windows.some(w => keyFrame(k) >= w.base && keyFrame(k) < w.base + w.frames && (keyBit(k) >> 5) >= w.offset && (keyBit(k) >> 5) < w.offset + w.words);
  return { tile: name, features: features.filter(f => f.tile === name && !f.zero).map(f => f.key).sort(), unknown: unknown.filter(inTile).sort((a, b) => a - b) };
}

async function main() {
  const { iseWorkBase, configPath } = await import('../server/toolchain.js');
  const { DOCKER_ISOLATION } = await import('../server/ise.js');
  const { VIVADO_DOCKER_ARGS } = await import('../server/vivado.js');
  const { exampleProject } = await import('../test/examples-lib.mjs');
  const { runOpenImplementation } = await import('../server/open-flow.js');
  const { yosysNode } = await import('../packages/silinx-fpga/src/node.js');
  const RB = await import('../packages/silinx-fpga/src/fpga/xc7/readback.js');
  const IMAGE = process.env.SILINX_VIVADO_IMAGE || 'xilinx/vitis-hls:2025.2';
  let HOST = process.env.SILINX_ISE_HOST;
  if (!HOST) try { const s = JSON.parse(fs.readFileSync(configPath(), 'utf8')).ssh; if (s?.host) HOST = s.user ? `${s.user}@${s.host}` : s.host; } catch { /* no config */ }
  if (!HOST) { console.error('set SILINX_ISE_HOST=user@host (the machine with the Vivado image), or SILINX_ISE_HOST=local'); process.exit(2); }
  const run = (cmd, args) => execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], maxBuffer: 256 << 20 });
  const SSH = ['-o', 'BatchMode=yes', '-o', 'ServerAliveInterval=30', '-o', 'ConnectTimeout=30'];
  const ssh = cmd => run('ssh', [...SSH, '--', HOST, `export PATH="$PATH:/usr/local/bin"; ${cmd}`]);
  const rsync = (...args) => run('rsync', ['-a', '-e', `ssh ${SSH.join(' ')}`, ...args]);
  const local = HOST === 'local';
  const reread = process.argv.includes('--read') ? process.argv[process.argv.indexOf('--read') + 1] : null;
  const work = reread || fs.mkdtempSync(path.join(os.tmpdir(), 'silinx-xc7b-'));
  const docker = ['run', '--rm', ...DOCKER_ISOLATION, ...VIVADO_DOCKER_ARGS, '--platform', 'linux/amd64'];
  try {
    if (!reread && !(await runDesigns())) return;
    // the bitstreams read back
    const index = RB.bitIndexXc7(JSON.parse(zlib.gunzipSync(fs.readFileSync(path.join(ROOT, 'packages/silinx-fpga/bitdb/xc7', `${PART}.json.gz`)))));
    const results = {};
    for (const [id] of DESIGNS) {
      const D = path.join(work, 'designs', id), bit = path.join(D, 'design.bit');
      if (!fs.existsSync(bit)) { results[id] = { error: (fs.existsSync(path.join(D, 'vivado.log')) ? fs.readFileSync(path.join(D, 'vivado.log'), 'utf8').split('\n').filter(l => /^(ERROR|CRITICAL WARNING)/.test(l)).slice(0, 5) : ['no log']) }; continue; }
      const t = fs.existsSync(path.join(D, 'bscan.txt')) ? fs.readFileSync(path.join(D, 'bscan.txt'), 'utf8').trim().split('\n').filter(Boolean).map(l => l.split('\t')) : [];
      results[id] = { ...cfgCenterBits(fs.readFileSync(bit), index, RB), cell: t.filter(x => x[0] === 'CELL').map(x => x.slice(1)), pips: t.filter(x => x[0] === 'PIP').map(x => x[2]).sort() };
    }
    console.log(JSON.stringify(results, null, 2));
  } finally {
    if (process.argv.includes('--keep') || reread) console.error(`work folder kept: ${work}`);
    else fs.rmSync(work, { recursive: true, force: true });
  }

  async function runDesigns() {
    // the netlists: the open flow's synthesis of blinky on the Basys 3, with and without the capture
    const netlistOf = async capture => {
      const { dir, project } = exampleProject('blinky', { board: 'basys3' }, path.join(work, 'projects'));
      const job = { log: () => {}, result: null, cancelled: false, procs: new Set() };
      const r = await runOpenImplementation(job, { project: { ...project, ...(capture && { capture }) }, projectDir: dir, steps: ['synth', 'translate'] });
      const text = fs.readFileSync(path.join(dir, r.reports.files.netlist), 'utf8');
      return { text, top: Object.entries(JSON.parse(text).modules).find(([, m]) => m.attributes?.top)[0], xdc: fs.readFileSync(path.join(dir, project.constraints), 'utf8') };
    };
    const base = await netlistOf(null), cap = await netlistOf(CAPTURE);
    for (const [id, chain, loc] of DESIGNS) {
      const n = chain ? cap : base, j = JSON.parse(n.text);
      for (const m of Object.values(j.modules)) for (const c of Object.values(m.cells || {})) if (c.type === 'BSCANE2') c.parameters.JTAG_CHAIN = chain.toString(2).padStart(32, '0');
      const out = await yosysNode(['-q', '-p', edifScript(n.top)], { 'netlist.json': JSON.stringify(j) });
      const D = path.join(work, 'designs', id);
      fs.mkdirSync(D, { recursive: true });
      fs.writeFileSync(path.join(D, 'netlist.edf'), out['netlist.edf']);
      // (the board's XDC compresses its bitstream: not here, the readback reads plain frames)
      fs.writeFileSync(path.join(D, 'netlist.xdc'), n.xdc.replace(/^.*BITSTREAM\.GENERAL\.COMPRESS.*\n/m, '') + (loc ? `\nset_property LOC ${loc} [get_cells silinx_bscan]\n` : ''));
      fs.writeFileSync(path.join(D, 'top.txt'), n.top);
    }
    fs.writeFileSync(path.join(work, 'bscan.tcl'), bscanTcl());
    if (process.argv.includes('--dry')) {
      for (const [id] of DESIGNS) console.log(id, fs.statSync(path.join(work, 'designs', id, 'netlist.edf')).size, 'bytes of EDIF;', (fs.readFileSync(path.join(work, 'designs', id, 'netlist.edf'), 'utf8').match(/BSCANE2/g) || []).length, 'BSCANE2 mention(s)');
      return false;
    }
    fs.writeFileSync(path.join(work, 'run.sh'), `#!/bin/bash
set -u
W=$1
S=$(ls -d /tools/Xilinx/*/Vivado/settings64.sh /tools/Xilinx/Vivado/*/settings64.sh /opt/Xilinx/*/Vivado/settings64.sh 2>/dev/null | head -1)
. "$S" >/dev/null
[ -w "\${HOME:-/nonexistent}" ] || export HOME=/tmp
for D in "$W"/designs/*; do
  ( cd "$D" && timeout 3600 vivado -mode batch -nojournal -notrace -log vivado.log -source "$W/bscan.tcl" -tclargs "$D" "$(cat top.txt)" ${PART} >/dev/null 2>&1 ); echo "$(basename "$D"): vivado $?"
  rm -rf "$D/.Xil"
done
`);
    if (local) process.stdout.write(run('docker', [...docker, '-v', `${work}:/w`, IMAGE, 'bash', '/w/run.sh', '/w']));
    else {
      const busy = jobContainers(ssh("docker ps --format '{{.Image}}\t{{.Names}}'"), IMAGE);
      if (busy.length) { console.error(`the host is busy: ${busy.length} Xilinx job(s) running`); process.exit(3); }
      const remote = `${iseWorkBase('silinx-xc7b')}/${path.basename(work)}`;
      ssh(`rm -rf ${remote} && mkdir -p ${remote}`);
      rsync(`${work}/designs`, `${work}/bscan.tcl`, `${work}/run.sh`, `${HOST}:${remote}/`);
      try {
        process.stdout.write(ssh(`docker run ${docker.slice(1).join(' ')} -v "${remote}":/w ${IMAGE} bash /w/run.sh /w`));
        rsync(`${HOST}:${remote}/designs/`, `${work}/designs/`);
      } finally { ssh(`rm -rf ${remote}`); }
    }
    return true;
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) await main();
