// Silinx HLS (#1526): the VHDL and the Verilog of a sequential C function's machine (core/c-fsmd.js): its registers and
// its state (ap_CS_fsm, as Vitis HLS names it) in one clocked process, the operations of its states one signal each
// (core/c-hdl.js), Vitis HLS's ports (ap_clk, ap_rst, ap_start, ap_done, ap_idle, ap_ready, the arguments, ap_return;
// with ap_ctrl_none ap_start, ap_done, ap_idle and ap_ready signals inside it, #1900).
// Isomorphic ES module: no DOM and no Node APIs.
import { bin, sig, vhdlNodes, verilogNodes, innerSignals } from './c-hdl.js';
import { hdlName } from './c-graph.js';

const rname = (r) => `ap_r_${hdlName(r.name)}`;

/** The nodes the machine needs: its updates, its next states, its latches. */
function nodesOf(m) {
  const roots = [];
  for (const st of m.states) { roots.push(st.next, ...st.updates.values()); }
  for (const r of m.regs) if (r.latch != null) roots.push(r.latch);
  for (const o of m.outputs.values()) if (o.node != null) roots.push(o.node);
  for (const x of m.mems || []) roots.push(...[x.addr, x.ce, x.we, x.d].filter((id) => id != null));
  return m.graph.needed(roots);
}
// (a memory inside the module: 2^aw words, its initial values, the rest 0)
const depth = (x) => 2 ** x.aw;
const words = (x) => Array.from({ length: depth(x) }, (_, k) => x.init?.[k] ?? 0n);

export function vhdlSeq(name, src, ports, m, agg) {
  const g = m.graph, nodes = nodesOf(m), SW = m.stateT.w;
  const S = (k) => `"${bin(k, SW)}"`;
  const regs = m.regs.map((r) => ({ ...r, sig: rname(r) }));
  const byName = new Map(regs.map((r) => [r.name, r]));
  const ce = ports.some((p) => p.name === 'ap_ce');
  const L = [`-- Generated by Silinx from ${src} (Silinx HLS, compatible with Vitis HLS): edit the C source`,
    'library ieee;', 'use ieee.std_logic_1164.all;', 'use ieee.numeric_std.all;', '', `entity ${name} is`, '  port ('];
  ports.forEach((p, k) => L.push(`    ${p.name} : ${p.dir} ${p.w === 1 ? 'std_logic' : `std_logic_vector(${p.w - 1} downto 0)`}${k < ports.length - 1 ? ';' : ''}`));
  L.push('  );', `end ${name};`, '', `architecture behav of ${name} is`);
  const ty = (n) => `${n.s ? 'signed' : 'unsigned'}(${n.w - 1} downto 0)`;
  L.push(`  signal ap_CS_fsm : unsigned(${SW - 1} downto 0);`);
  for (const r of regs) L.push(`  signal ${r.sig} : ${ty(r)};`);
  for (const n of nodes) L.push(`  signal ${sig(n)} : ${ty(n)};`);
  for (const x of m.mems || []) {
    L.push(`  type ap_m_${hdlName(x.name)}_t is array (0 to ${depth(x) - 1}) of std_logic_vector(${x.t.w - 1} downto 0);`);
    const init = x.init ? ` := (${words(x).map((v, k) => `${k} => "${bin(v, x.t.w)}"`).join(', ')})` : '';
    L.push(`  signal ap_m_${hdlName(x.name)} : ap_m_${hdlName(x.name)}_t${init};`, `  signal ap_m_${hdlName(x.name)}_q0 : ${ty(x.t)};`);
  }
  innerSignals(agg, 'vhdl', L);
  // (ap_ctrl_none, #1900: the block protocol's signals inside the module, ap_start 1: a call after the other)
  if (!ports.some((p) => p.name === 'ap_start')) L.push("  signal ap_start : std_logic := '1';", '  signal ap_done, ap_idle, ap_ready : std_logic;');
  L.push('begin');
  vhdlNodes(nodes, g, L);
  L.push(...(agg?.vhdl || []));
  for (const x of m.mems || []) {
    // (a block RAM's port: written when we, read the cycle after the address)
    const a = `to_integer(${sig(g.get(x.addr))})`;
    L.push('  process (ap_clk)', '  begin', '    if rising_edge(ap_clk) then', `      if ${sig(g.get(x.ce))} = "1"${ce ? " and ap_ce = '1'" : ''} then`);
    if (x.we != null) L.push(`        if ${sig(g.get(x.we))} = "1" then`, `          ap_m_${hdlName(x.name)}(${a}) <= std_logic_vector(${sig(g.get(x.d))});`, '        end if;');
    L.push(`        ap_m_${hdlName(x.name)}_q0 <= ${x.t.s ? 'signed' : 'unsigned'}(ap_m_${hdlName(x.name)}(${a}));`, '      end if;', '    end if;', '  end process;');
  }
  L.push('  process (ap_clk)', '  begin', '    if rising_edge(ap_clk) then', "      if ap_rst = '1' then", `        ap_CS_fsm <= ${S(m.idle)};`);
  for (const r of regs) L.push(`        ${r.sig} <= "${bin(r.reset, r.w)}";`);
  L.push(ce ? "      elsif ap_ce = '1' then" : '      else');
  for (const r of regs) if (/_vld_reg$/.test(r.name)) L.push(`        ${r.sig} <= "0";`);
  L.push(`        if ap_CS_fsm = ${S(m.idle)} then`, "          if ap_start = '1' then");
  for (const r of regs) if (r.latch != null) L.push(`            ${r.sig} <= ${sig(g.get(r.latch))};`);
  L.push(`            ap_CS_fsm <= ${S(m.entry)};`, '          end if;');
  for (const st of m.states) {
    L.push(`        elsif ap_CS_fsm = ${S(st.id)} then${st.line ? `   -- line ${st.line}` : ''}`);
    for (const [r, id] of st.updates) L.push(`          ${byName.get(r).sig} <= ${sig(g.get(id))};`);
    L.push(`          ap_CS_fsm <= ${sig(g.get(st.next))};`);
  }
  L.push('        else', `          ap_CS_fsm <= ${S(m.idle)};`, '        end if;', '      end if;', '    end if;', '  end process;');
  L.push(`  ap_done <= '1' when ap_CS_fsm = ${S(m.done)} else '0';`, `  ap_ready <= '1' when ap_CS_fsm = ${S(m.done)} else '0';`, `  ap_idle <= '1' when ap_CS_fsm = ${S(m.idle)} else '0';`);
  for (const [p, o] of m.outputs) {
    if (o.wire) { L.push(`  ${p} <= ${o.wire};`); continue; }   // (a BRAM's clock and reset, core/c-mem.js)
    const v = o.node != null ? sig(g.get(o.node)) : byName.get(o.reg).sig, port = [...ports, ...(agg?.inner || [])].find((x) => x.name === p);
    L.push(`  ${p} <= ${port.w === 1 ? `${v}(0)` : `std_logic_vector(${v})`};`);
  }
  L.push('end behav;', '');
  return L.join('\n');
}

export function verilogSeq(name, src, ports, m, agg) {
  const g = m.graph, nodes = nodesOf(m), SW = m.stateT.w;
  const S = (k) => `${SW}'b${bin(k, SW)}`;
  const regs = m.regs.map((r) => ({ ...r, sig: rname(r) }));
  const byName = new Map(regs.map((r) => [r.name, r]));
  const ce = ports.some((p) => p.name === 'ap_ce');
  const L = [`// Generated by Silinx from ${src} (Silinx HLS, compatible with Vitis HLS): edit the C source`, `module ${name} (`];
  ports.forEach((p, k) => L.push(`  ${p.dir === 'in' ? 'input ' : 'output'} wire ${p.w > 1 ? `[${p.w - 1}:0] ` : ''}${p.name}${k < ports.length - 1 ? ',' : ''}`));
  L.push(');', `  reg [${SW - 1}:0] ap_CS_fsm;`);
  for (const r of regs) L.push(`  reg ${r.s ? 'signed ' : ''}[${r.w - 1}:0] ${r.sig};`);
  for (const n of nodes) L.push(`  wire ${n.s ? 'signed ' : ''}[${n.w - 1}:0] ${sig(n)};`);
  innerSignals(agg, 'verilog', L);
  if (!ports.some((p) => p.name === 'ap_start')) L.push("  wire ap_start = 1'b1;", '  wire ap_done, ap_idle, ap_ready;');
  for (const x of m.mems || []) {
    L.push(`  reg [${x.t.w - 1}:0] ap_m_${hdlName(x.name)} [0:${depth(x) - 1}];`, `  reg ${x.t.s ? 'signed ' : ''}[${x.t.w - 1}:0] ap_m_${hdlName(x.name)}_q0;`);
    if (x.init) L.push('  initial begin', ...words(x).map((v, k) => `    ap_m_${hdlName(x.name)}[${k}] = ${x.t.w}'b${bin(v, x.t.w)};`), '  end');
  }
  verilogNodes(nodes, g, L);
  L.push(...(agg?.verilog || []));
  for (const x of m.mems || []) {
    const a = sig(g.get(x.addr));
    L.push(`  always @(posedge ap_clk) if (${sig(g.get(x.ce))}${ce ? ' && ap_ce' : ''}) begin`);
    if (x.we != null) L.push(`    if (${sig(g.get(x.we))}) ap_m_${hdlName(x.name)}[${a}] <= ${sig(g.get(x.d))};`);
    L.push(`    ap_m_${hdlName(x.name)}_q0 <= ap_m_${hdlName(x.name)}[${a}];`, '  end');
  }
  L.push('  always @(posedge ap_clk) begin', '    if (ap_rst) begin', `      ap_CS_fsm <= ${S(m.idle)};`);
  for (const r of regs) L.push(`      ${r.sig} <= ${r.w}'b${bin(r.reset, r.w)};`);
  L.push(ce ? '    end else if (ap_ce) begin' : '    end else begin');
  for (const r of regs) if (/_vld_reg$/.test(r.name)) L.push(`      ${r.sig} <= 1'b0;`);
  L.push('      case (ap_CS_fsm)', `        ${S(m.idle)}: if (ap_start) begin`);
  for (const r of regs) if (r.latch != null) L.push(`          ${r.sig} <= ${sig(g.get(r.latch))};`);
  L.push(`          ap_CS_fsm <= ${S(m.entry)};`, '        end');
  for (const st of m.states) {
    L.push(`        ${S(st.id)}: begin${st.line ? `   // line ${st.line}` : ''}`);
    for (const [r, id] of st.updates) L.push(`          ${byName.get(r).sig} <= ${sig(g.get(id))};`);
    L.push(`          ap_CS_fsm <= ${sig(g.get(st.next))};`, '        end');
  }
  L.push(`        default: ap_CS_fsm <= ${S(m.idle)};`, '      endcase', '    end', '  end');
  L.push(`  assign ap_done = ap_CS_fsm == ${S(m.done)};`, `  assign ap_ready = ap_CS_fsm == ${S(m.done)};`, `  assign ap_idle = ap_CS_fsm == ${S(m.idle)};`);
  for (const [p, o] of m.outputs) L.push(`  assign ${p} = ${o.wire ?? (o.node != null ? sig(g.get(o.node)) : byName.get(o.reg).sig)};`);
  L.push('endmodule', '');
  return L.join('\n');
}
