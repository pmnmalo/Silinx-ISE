// Silinx HLS (#1893): a small module written once, in VHDL and in Verilog: registers and the nodes of core/c-graph.js
// (written by core/c-hdl.js's vhdlNodes and verilogNodes) around one instance, the AXI adapters' (core/c-axi.js).
// Isomorphic ES module: no DOM and no Node APIs.
//
//   new Rtl(): in(name, w), reg(name, w, reset?), next(reg, node), out(name, w, node), const(k, w), and, or, not, mux,
//     is(node, k), slice(node, hi, lo), ext(node, w), shl(node, n), cat(hi, lo)
//   rtl.write(lang, { name, src, ports, instance: { module, map: [[its port, the net]] }, nets: [{ name, w }] }) -> text
import { Graph, hdlName } from './c-graph.js';
import { vhdlNodes, verilogNodes, sig, bin } from './c-hdl.js';

const U = (w) => ({ w, s: false });
const BIT = U(1), T = (w) => (w === 1 ? 'std_logic' : `std_logic_vector(${w - 1} downto 0)`);

export class Rtl {
  constructor() { this.g = new Graph(); this.regs = new Map(); this.outs = []; }
  in(name, w) { return this.g.add('in', [], U(w), { port: { key: name, name } }); }
  reg(name, w, reset = 0n) {
    const sg = `ap_r_${hdlName(name)}`;
    const id = this.g.add('reg', [], U(w), { port: { key: `reg:${name}`, name: sg } });
    this.regs.set(id, { sg, w, reset: BigInt(reset), next: id });
    return id;
  }
  next(reg, node) { this.regs.get(reg).next = node; }
  out(name, w, node) { this.outs.push({ name, w, node }); }
  const(k, w) { return this.g.const(BigInt(k), U(w)); }
  and(...a) { return a.reduce((x, y) => this.g.add('and', [x, y], BIT)); }
  or(...a) { return a.reduce((x, y) => this.g.add('or', [x, y], BIT)); }
  not(a) { return this.g.add('not', [a], BIT); }
  /** c ? a : b, of the width of a. */
  mux(c, a, b) { return this.g.add('mux', [c, a, b], U(this.g.get(a).w)); }
  is(a, k) { return this.g.add('eq', [a, this.const(k, this.g.get(a).w)], BIT); }
  slice(a, hi, lo) { return this.g.add('slice', [a], U(hi - lo + 1), { hi, lo }); }
  ext(a, w) { return this.g.get(a).w === w ? a : this.g.add('ext', [a], U(w)); }
  shl(a, n) { return n ? this.g.add('shl', [a, this.g.const(BigInt(n), { w: 32, s: true })], U(this.g.get(a).w)) : a; }
  /** The bits of hi above those of lo. */
  cat(hi, lo) {
    const a = this.g.get(hi).w, b = this.g.get(lo).w;
    return this.g.add('or', [this.shl(this.ext(hi, a + b), b), this.ext(lo, a + b)], U(a + b));
  }
  write(lang, m) { return lang === 'vhdl' ? this.vhdl(m) : this.verilog(m); }
  nodes() { return this.g.needed([...[...this.regs.values()].map((r) => r.next), ...this.outs.map((o) => o.node)]); }
  vhdl({ name, src, ports, instance, nets }) {
    const nodes = this.nodes(), regs = [...this.regs.values()], g = this.g;
    const L = [`-- Generated by Silinx from ${src} (Silinx HLS, compatible with Vitis HLS): edit the C source`, '-- (the AXI interfaces around the function)',
      'library ieee;', 'use ieee.std_logic_1164.all;', 'use ieee.numeric_std.all;', '', `entity ${name} is`, '  port ('];
    ports.forEach((p, k) => L.push(`    ${p.name} : ${p.dir} ${T(p.w)}${k < ports.length - 1 ? ';' : ''}`));
    L.push('  );', `end ${name};`, '', `architecture behav of ${name} is`);
    for (const r of regs) L.push(`  signal ${r.sg} : unsigned(${r.w - 1} downto 0);`);
    for (const n of nodes) L.push(`  signal ${sig(n)} : unsigned(${n.w - 1} downto 0);`);
    for (const n of nets) L.push(`  signal ${n.name} : ${T(n.w)};`);
    L.push('begin');
    vhdlNodes(nodes, g, L);
    L.push(`  ap_core : entity work.${instance.module} port map (${instance.map.map(([p, n]) => `${p} => ${n}`).join(', ')});`);
    for (const o of this.outs) L.push(`  ${o.name} <= ${o.w === 1 ? `${sig(g.get(o.node))}(0)` : `std_logic_vector(${sig(g.get(o.node))})`};`);
    L.push('  process (ap_clk)', '  begin', '    if rising_edge(ap_clk) then', "      if ap_rst_n = '0' then");
    for (const r of regs) L.push(`        ${r.sg} <= "${bin(r.reset, r.w)}";`);
    L.push('      else');
    for (const r of regs) L.push(`        ${r.sg} <= ${sig(g.get(r.next))};`);
    L.push('      end if;', '    end if;', '  end process;', 'end behav;', '');
    return L.join('\n');
  }
  verilog({ name, src, ports, instance, nets }) {
    const nodes = this.nodes(), regs = [...this.regs.values()], g = this.g;
    const W = (w) => (w > 1 ? `[${w - 1}:0] ` : '');
    const L = [`// Generated by Silinx from ${src} (Silinx HLS, compatible with Vitis HLS): edit the C source`, '// (the AXI interfaces around the function)', `module ${name} (`];
    ports.forEach((p, k) => L.push(`  ${p.dir === 'in' ? 'input ' : 'output'} wire ${W(p.w)}${p.name}${k < ports.length - 1 ? ',' : ''}`));
    L.push(');');
    for (const r of regs) L.push(`  reg [${r.w - 1}:0] ${r.sg};`);
    for (const n of nodes) L.push(`  wire [${n.w - 1}:0] ${sig(n)};`);
    for (const n of nets) L.push(`  wire ${W(n.w)}${n.name};`);
    verilogNodes(nodes, g, L);
    L.push(`  ${instance.module} ap_core (${instance.map.map(([p, n]) => `.${p}(${n})`).join(', ')});`);
    for (const o of this.outs) L.push(`  assign ${o.name} = ${sig(g.get(o.node))};`);
    L.push('  always @(posedge ap_clk) begin', '    if (!ap_rst_n) begin');
    for (const r of regs) L.push(`      ${r.sg} <= ${r.w}'b${bin(r.reset, r.w)};`);
    L.push('    end else begin');
    for (const r of regs) L.push(`      ${r.sg} <= ${sig(g.get(r.next))};`);
    L.push('    end', '  end', 'endmodule', '');
    return L.join('\n');
  }
}
