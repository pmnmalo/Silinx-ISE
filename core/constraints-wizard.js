// Silinx - the Constraints Wizard's file (#2082, #2296), the interface's (web/js/ucf-wizard.js) and the MCP server's
// (constraints_wizard): a module's port bits on pins, in the device's format (UCF, PCF, LPF, CST, XDC: the UCF Wizard, the
// PCF Wizard…), with the attributes the format writes (core/constraints-check.js PIN_ATTRS), and its checks: a pin given
// twice; in a PCF, an LPF or a CST, a pin that is no pin of the package and an I/O standard at another voltage than its
// bank's on the board (Check Constraints' errors).
import { boardConstraintsText, constraintsFormatOf } from '../packages/silinx-fpga/src/parts.js';
import { PIN_ATTRS, constraintsDiagnostics } from './constraints-check.js';

// a format's article: an LPF, an XDC, a PCF
export const article = F => (/^[LX]/.test(F) ? 'an' : 'a');

/** The wizard's name: 'UCF Wizard', 'PCF Wizard', 'LPF Wizard', 'CST Wizard', 'XDC Wizard'. */
export const wizardTitle = device => `${constraintsFormatOf(device).toUpperCase()} Wizard`;

/** The file's text: boardConstraintsText's, its header the wizard's. board: { name, resources } or null. */
export function wizardText({ device, board = null, ports, assignments, clocks = [], top }) {
  const F = constraintsFormatOf(device).toUpperCase();
  return boardConstraintsText({ device, board, ports, assignments, clocks,
    header: `${F} generated by the Silinx ${F} Wizard for '${top}' (${device.part}${device.speed || ''}-${device.package}${board ? `, ${board.name}` : ''})` });
}

/** The error that stops the wizard, or null: a pin given twice, then the text's first error (PCF, LPF, CST). */
export function wizardError({ device, board = null, assignments, text }) {
  const used = new Map();
  for (const [net, a] of Object.entries(assignments)) {
    const k = String(a.loc).toUpperCase();
    if (used.has(k)) return `The pin ${a.loc} is given to ${used.get(k)} and ${net}.`;
    used.set(k, net);
  }
  const format = constraintsFormatOf(device);
  if (!['pcf', 'lpf', 'cst'].includes(format)) return null;
  const e = constraintsDiagnostics(format, text, { device, board }).find(d => d.severity === 'error');
  return e ? `${e.message}.` : null;
}

/** The attributes given to the nets ({ net: { iostandard, pull, drive, slew } }, '' or 'none' takes one off) put into the
 *  assignments; throws the first one the format has not. */
export function applyAttributes(device, assignments, attributes = {}) {
  const format = constraintsFormatOf(device), F = format.toUpperCase(), can = PIN_ATTRS[format];
  for (const [net, attrs] of Object.entries(attributes)) {
    const a = assignments[net];
    if (!a) throw new Error(`attributes: ${net} has no pin`);
    for (const [k, v0] of Object.entries(attrs || {})) {
      if (!['iostandard', 'pull', 'drive', 'slew'].includes(k)) throw new Error(`attributes: ${k} is not an attribute (iostandard, pull, drive, slew)`);
      if (!can[k]) throw new Error(`attributes: ${article(F)} ${F} has no ${k === 'iostandard' ? 'I/O standard' : k}`);
      const v = String(v0 ?? '').trim();
      if (!v || v.toLowerCase() === 'none') { delete a[k]; if (k === 'pull') a.pull = null; continue; }
      if (k === 'iostandard') { a.iostandard = v.toUpperCase(); continue; }
      const val = v.toLowerCase();
      if (!can[k].includes(val)) throw new Error(`attributes: ${k} ${v} of ${net}: ${can[k].join(', ')}${k === 'pull' ? ' or none' : ''}`);
      a[k] = val;
    }
  }
  return assignments;
}
