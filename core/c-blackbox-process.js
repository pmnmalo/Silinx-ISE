// Silinx HLS (#2340): an RTL blackbox (syn.blackbox, core/c-blackbox.js, #1903) called in a DATAFLOW region, a process of
// its own (core/c-processes.js): a module made for it, its ports a process's as Vitis HLS names them (ap_clk, ap_rst,
// ap_start / ap_done / ap_idle / ap_ready; a stream's _dout _empty_n _read or _din _full_n _write; a memory's _address0
// _ce0 _we0 _d0 _q0; an input), the RTL module inside it: started once a call (ap_start taken when it is idle), done
// with its ap_done (or its latency), ap_ce and ap_continue held at 1, as in a sequential machine. Its channels are the
// region's: streams, arrays, the top's arguments and constants for its inputs; an output or a result is refused (as Vitis
// HLS refuses an output pointer in a DATAFLOW region).
// Isomorphic ES module: no DOM and no Node APIs.
//
//   blackboxProcess(fn, { lang, module, file }) -> a process's module, as cToHdl's result
import { portOf } from './c-names.js';
import { blackboxHdl } from './c-blackbox.js';

const clog2 = (n) => Math.max(1, (n - 1).toString(2).length);
const T = (w) => (w === 1 ? 'std_logic' : `std_logic_vector(${w - 1} downto 0)`);
const V = (w) => (w > 1 ? `[${w - 1}:0] ` : '');
const CTRL = [['ap_clk', 'in'], ['ap_rst', 'in'], ['ap_start', 'in'], ['ap_done', 'out'], ['ap_idle', 'out'], ['ap_ready', 'out']];

/** fn: the C function the blackbox replaces (applyBlackboxes made it: fn.blackbox); module: the process's module's name. */
export function blackboxProcess(fn, { lang = 'vhdl', module, file = 'input.c' }) {
  const d = fn.blackbox, P = 'ap_bb0';
  const bad = (message) => ({ ok: false, hdl: '', top: module, ports: [], diagnostics: [{ file: d.file, line: 1, col: 1, message: `syn.blackbox: ${d.file.split('/').pop()}: ${message}`, severity: 'error' }] });
  if (d.ret) return bad(`'${d.name}' is called in a DATAFLOW region: its result is not supported there (a stream or an array)`);
  const ports = CTRL.map(([name, dir]) => ({ name, dir, w: 1 }));
  const ins = [], bbPorts = [], memories = [], fifos = [];
  // (the process's port <- the instance's signal, or the instance's <- the port: [dst, dw, src, sw])
  const ties = [];
  for (const pa of fn.params) {
    const X = d.params.get(pa.name), t = d.types.get(pa.name), R = portOf(pa.name);
    const port = (sfx, dir, w, role) => ports.push({ name: `${R}${sfx}`, dir, w, role, param: pa.name });
    const N = `${P}_${pa.name}`;
    if (X.kind === 'mem') {
      const n = Number(pa.type.length), aw = clog2(n), raw = d.aw.get(pa.name);
      bbPorts.push({ P: X, name: pa.name, w: t.w, aw: raw });
      port('_address0', 'out', aw, 'mem'); ties.push([`${R}_address0`, aw, `${N}_address0`, raw]);
      port('_ce0', 'out', 1, 'mem'); ties.push([`${R}_ce0`, 1, `${N}_ce0`, 1]);
      if (X.we) { port('_we0', 'out', 1, 'mem'); port('_d0', 'out', t.w, 'mem'); ties.push([`${R}_we0`, 1, `${N}_we0`, 1], [`${R}_d0`, t.w, `${N}_d0`, t.w]); }
      if (X.q) { port('_q0', 'in', t.w, 'mem'); ties.push([`${N}_q0`, t.w, `${R}_q0`, t.w]); }
      memories.push({ name: pa.name, n, w: t.w, s: t.s, aw, read: !!X.q, written: !!X.we });
      continue;
    }
    if (X.kind === 'fifo') {
      bbPorts.push({ P: X, name: pa.name, w: t.w });
      const sides = X.dir === 'in' ? [['_dout', 'in', t.w], ['_empty_n', 'in', 1], ['_read', 'out', 1]] : [['_din', 'out', t.w], ['_full_n', 'in', 1], ['_write', 'out', 1]];
      for (const [sfx, dir, w] of sides) { port(sfx, dir, w, 'fifo'); ties.push(dir === 'in' ? [`${N}${sfx}`, w, `${R}${sfx}`, w] : [`${R}${sfx}`, w, `${N}${sfx}`, w]); }
      fifos.push({ name: pa.name, dir: X.dir, t, w: t.w, s: t.s, used: true, polled: false });
      continue;
    }
    if (X.dir !== 'in') return bad(`'${d.name}' is called in a DATAFLOW region: its argument '${pa.name}' is an output, not supported there (a stream or an array)`);
    port('', 'in', t.w, 'arg');
    ins.push({ rtl: X.in, name: `${N}_i`, w: t.w });
    ties.push([`${N}_i_w`, t.w, R, t.w]);
  }
  const bb = blackboxHdl([{ i: 0, d, ins, outs: [], ports: bbPorts }]);
  const src = file.split('/').pop();
  const head = `Generated by Silinx from ${src} (Silinx HLS, compatible with Vitis HLS): the RTL blackbox '${d.name}' (${d.module}), a process of a DATAFLOW region`;
  let hdl;
  if (lang === 'vhdl') {
    const conv = (s, sw, dw) => (sw === dw ? s : dw === 1 ? `${s}(0)` : `${s}(${dw - 1} downto 0)`);
    hdl = [`-- ${head}`, 'library ieee;', 'use ieee.std_logic_1164.all;', 'use ieee.numeric_std.all;', '', `entity ${module} is`, '  port (',
      ...ports.map((p, k) => `    ${p.name} : ${p.dir} ${T(p.w)}${k < ports.length - 1 ? ';' : ''}`), '  );', `end ${module};`, '', `architecture behav of ${module} is`,
      ...bb.inner.map((s) => `  signal ${s.name} : ${T(s.w)};`), ...bb.decls.vhdl, 'begin',
      `  ${P}_go <= ap_start;`, `  ap_done <= ${P}_done;`, `  ap_ready <= ${P}_done;`, `  ap_idle <= not ${P}_started;`,
      ...ties.map(([dst, dw, s, sw]) => `  ${dst} <= ${conv(s, sw, dw)};`), ...bb.vhdl, 'end behav;', ''].join('\n');
  } else {
    const conv = (s, sw, dw) => (sw === dw ? s : `${s}[${dw - 1}:0]`);
    hdl = [`// ${head}`, `module ${module} (`, ...ports.map((p, k) => `  ${p.dir === 'in' ? 'input' : 'output'} ${V(p.w)}${p.name}${k < ports.length - 1 ? ',' : ''}`), ');',
      ...bb.inner.map((s) => `  wire ${V(s.w)}${s.name};`), ...bb.decls.verilog,
      `  assign ${P}_go = ap_start;`, `  assign ap_done = ${P}_done;`, `  assign ap_ready = ${P}_done;`, `  assign ap_idle = ~${P}_started;`,
      ...ties.map(([dst, dw, s, sw]) => `  assign ${dst} = ${conv(s, sw, dw)};`), ...bb.verilog, 'endmodule', ''].join('\n');
  }
  const latency = { min: d.latency ?? 0, max: d.latency };
  return { ok: true, module, hdl, top: module, ports, diagnostics: [], sequential: true, states: 0, memories, fifos, blackboxes: [d],
    report: { sequential: true, blackbox: d.module, states: 0, registerBits: 0, latency, loops: [], memories: [], units: [] } };
}
