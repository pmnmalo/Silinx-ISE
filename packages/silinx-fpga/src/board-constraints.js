// Silinx toolchain - a board's constraints file, made from its pin table (ucf.js boardAutoAssign), in the format of its
// device's family (#2468): UCF, PCF on the iCE40 (pcf.js), LPF on the ECP5 (lpf.js, #2302), CST on the Gowin (cst.js, #2303), XDC on
// the 7-series (xdc.js, #3142).
import { generateUcf } from './ucf.js';
import { PCF } from './pcf.js';
import { LPF } from './lpf.js';
import { CST } from './cst.js';
import { writeXdc } from './xdc.js';
import { constraintsFormatOf } from './family.js';

// the formats that name a bit as nextpnr does: led<0> (UCF) -> led[0]
const NEXTPNR_FORMATS = { pcf: PCF, lpf: LPF, cst: CST };
const pcfName = net => net.replace(/<(\d+)>$/, '[$1]');

/** The text of the constraints of these ports on a device: generateUcf's arguments; the header's leading "UCF" says the format.
 *  board: the XDC's (its pins' I/O standards and its configuration's properties, xdc.js writeXdc). */
// a board's pins' I/O standards: { pin: standard }
const pinStandards = board => Object.fromEntries((board?.resources || []).flatMap(r => r.pins.map(p => [p, r.pinIostandards?.[p] || r.iostandard])).filter(([, s]) => s));

export function boardConstraintsText({ device, ports, assignments = {}, clocks = [], header, board }) {
  const format = constraintsFormatOf(device);
  if (format === 'ucf') return generateUcf({ ports, assignments, clocks, header });
  const head = (header ?? 'Generated by Silinx').replace(/^UCF\b/, format.toUpperCase());
  if (format === 'xdc') return writeXdc({ assignments, clocks }, { ports, board, header: head }).text;
  // (a CST: each pin's I/O standard the board's, as the XDC's: the Gowin's banks of 1.8 V, #2303)
  const standard = format === 'cst' ? pinStandards(board) : {};
  const pins = Object.fromEntries(Object.entries(assignments).map(([net, a]) => [pcfName(net), standard[a.loc] && !a.iostandard ? { ...a, iostandard: standard[a.loc] } : a]));
  const comment = NEXTPNR_FORMATS[format].comment || '#';
  return `${head.split('\n').map(h => `${comment} ${h}`.trimEnd()).join('\n')}\n\n${NEXTPNR_FORMATS[format].write({ assignments: pins, clocks: clocks.map(c => ({ ...c, net: pcfName(c.net) })) })}`;
}
