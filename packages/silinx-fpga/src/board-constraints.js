// Silinx toolchain - a board's constraints file, made from its pin table (ucf.js boardAutoAssign), in the format of its
// device's family (#2468): UCF, or PCF on the iCE40 (pcf.js).
import { generateUcf } from './ucf.js';
import { PCF } from './pcf.js';
import { FAMILY_INFO, deviceFamily } from './family.js';

// a bit as nextpnr names it: led<0> (UCF) -> led[0]
const pcfName = net => net.replace(/<(\d+)>$/, '[$1]');

/** The text of the constraints of these ports on a device: generateUcf's arguments; the header's leading "UCF" says the format. */
export function boardConstraintsText({ device, ports, assignments = {}, clocks = [], header }) {
  if (FAMILY_INFO[deviceFamily(device)]?.constraints !== 'pcf') return generateUcf({ ports, assignments, clocks, header });
  const pins = Object.fromEntries(Object.entries(assignments).map(([net, a]) => [pcfName(net), a]));
  const head = (header ?? 'Generated by Silinx').replace(/^UCF\b/, 'PCF').split('\n').map(h => `# ${h}`.trimEnd()).join('\n');
  return `${head}\n\n${PCF.write({ assignments: pins, clocks: clocks.map(c => ({ ...c, net: pcfName(c.net) })) })}`;
}
