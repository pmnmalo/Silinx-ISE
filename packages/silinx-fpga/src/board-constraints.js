// Silinx toolchain - a board's constraints file, made from its pin table (ucf.js boardAutoAssign), in the format of its
// device's family (#2468): UCF, PCF on the iCE40 (pcf.js), XDC on the 7-series (xdc.js, #3142).
import { generateUcf } from './ucf.js';
import { PCF } from './pcf.js';
import { writeXdc } from './xdc.js';
import { constraintsFormatOf } from './family.js';

// a bit as nextpnr names it: led<0> (UCF) -> led[0]
const pcfName = net => net.replace(/<(\d+)>$/, '[$1]');

/** The text of the constraints of these ports on a device: generateUcf's arguments; the header's leading "UCF" says the format.
 *  board: the XDC's (its pins' I/O standards and its configuration's properties, xdc.js writeXdc). */
export function boardConstraintsText({ device, ports, assignments = {}, clocks = [], header, board }) {
  const format = constraintsFormatOf(device);
  if (format === 'ucf') return generateUcf({ ports, assignments, clocks, header });
  const head = (header ?? 'Generated by Silinx').replace(/^UCF\b/, format.toUpperCase());
  if (format === 'xdc') return writeXdc({ assignments, clocks }, { ports, board, header: head }).text;
  const pins = Object.fromEntries(Object.entries(assignments).map(([net, a]) => [pcfName(net), a]));
  return `${head.split('\n').map(h => `# ${h}`.trimEnd()).join('\n')}\n\n${PCF.write({ assignments: pins, clocks: clocks.map(c => ({ ...c, net: pcfName(c.net) })) })}`;
}
