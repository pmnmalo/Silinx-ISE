// Night 1 of the Spartan-6 measurements (stage S6-0, #733): the work folder that ise-s6.sh implements.
// For each board (nexys3: XC6SLX16-3CSG324, atlys: XC6SLX45-3CSG324):
//   impl-<board>/<example>/   the example's HDL, top.ucf (the board's pin assignment, as the New Project
//                             wizard writes it), top.txt (the top's name): ISE implements it from the HDL
//   edif-<board>/<example>/   top.edf, the open synthesis's netlist for the Spartan-6 (Yosys xc6s), top.ucf:
//                             ISE implements Silinx's netlist (the packer's comparison, #721)
// and empty/<part>.xdl (an empty design of each part: the bitstream format, #724), manifest.json.
// Nothing here runs ISE; the folder stays outside the repository (ISE's outputs are never committed).
//
//   node research/s6/night1.mjs <work folder> [--only gates,blinky] [--boards nexys3] [--no-edif]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile, elaborate } from '../../../../core/compile.js';
import { boardAutoAssign, generateUcf } from '../../src/ucf.js';
import { resolveBoard } from '../../../../server/devices.js';
import { EXAMPLE_ORDER } from '../../../../core/examples.js';
import { synthesizeOpen } from '../../../../core/synth-front.js';
import { yosysNode } from '../../src/synth-open-node.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');
/** The boards of night 1 and their parts as ISE names them. */
export const BOARDS = { nexys3: 'xc6slx16-csg324-3', atlys: 'xc6slx45-csg324-3' };

/** An example's sources (examples/<name>/silinx.json): { project, design: [{ path, lang, text }] }. */
export function exampleSources(name) {
  const dir = path.join(ROOT, 'examples', name);
  const project = JSON.parse(fs.readFileSync(path.join(dir, 'silinx.json'), 'utf8'));
  const design = project.files.filter(f => (f.role || 'design') === 'design').map(f => ({ path: f.path, lang: f.lang, text: fs.readFileSync(path.join(dir, f.path), 'utf8') }));
  return { project, design };
}

/** The UCF of an example's top on a board: { text, unmatched: [port names the board has no pins for] }. */
export function boardUcf(design, board) {
  const r = resolveBoard(board);
  const b = { name: r.board.name, device: r.device, resources: r.resources };
  const ports = design.top.ports.map(p => {
    const t = p.sig.t, bus = t.w > 1 || (t.kind === 'logic' && !t.scalar);
    return { name: p.name, dir: p.dir, width: t.w, msb: bus ? t.left : null, lsb: bus ? t.right : null };
  });
  const { assignments, clocks, unmatched } = boardAutoAssign(ports, b);
  const text = generateUcf({ ports, assignments, clocks, header: `UCF for top '${design.top.name}' on ${r.board.name} (${r.device.part}${r.device.speed}-${r.device.package}), generated by Silinx` });
  return { text, unmatched: (unmatched || []).map(u => u.name ?? u) };
}

/** The part as XDL names it: xc6slx16-csg324-3 -> xc6slx16csg324-3. */
export const xdlPart = part => part.replace(/-(?=[a-z])/, '');
/** The empty design of a part in XDL (no instance, no net). */
export const emptyXdl = part => `design "empty" ${xdlPart(part)} v3.2 ,\n  cfg "";\n`;

/** The open synthesis's EDIF of a design for the Spartan-6 (Yosys's write_edif from its JSON netlist). */
export async function openEdif(design, run = yosysNode) {
  const r = await synthesizeOpen(design, { family: 'spartan6', run });
  const top = r.top, json = r.files[`${top}.json`];
  const out = await run(['-q', '-p', `read_json ${top}.json; write_edif -pvector bra top.edf`], { [`${top}.json`]: json });
  const edf = out['top.edf'];
  return { edif: typeof edf === 'string' ? edf : new TextDecoder().decode(edf), cells: r.cells };
}

/** Writes the work folder; returns the manifest. */
export async function writeNight1(work, { only = EXAMPLE_ORDER, boards = Object.keys(BOARDS), edif = true, run = yosysNode } = {}) {
  const manifest = { stage: 'S6-0', boards: {}, empty: [] };
  fs.mkdirSync(path.join(work, 'empty'), { recursive: true });
  for (const board of boards) {
    const part = BOARDS[board];
    fs.writeFileSync(path.join(work, 'empty', `${part}.xdl`), emptyXdl(part));
    manifest.empty.push(part);
    manifest.boards[board] = { part, examples: {} };
    for (const name of only) {
      const { project, design: srcs } = exampleSources(name);
      const design = elaborate(compile(srcs), project.top);
      const ucf = boardUcf(design, board);
      const dir = path.join(work, `impl-${board}`, name);
      fs.mkdirSync(dir, { recursive: true });
      for (const s of srcs) fs.writeFileSync(path.join(dir, path.basename(s.path)), s.text);
      fs.writeFileSync(path.join(dir, 'top.ucf'), ucf.text);
      fs.writeFileSync(path.join(dir, 'top.txt'), `${project.top}\n`);
      const entry = { top: project.top, unmatched: ucf.unmatched };
      if (edif) {
        const e = await openEdif(design, run);
        const d2 = path.join(work, `edif-${board}`, name);
        fs.mkdirSync(d2, { recursive: true });
        fs.writeFileSync(path.join(d2, 'top.edf'), e.edif);
        fs.writeFileSync(path.join(d2, 'top.ucf'), ucf.text);
        fs.writeFileSync(path.join(d2, 'top.txt'), `${project.top}\n`);
        entry.openCells = e.cells;
      }
      manifest.boards[board].examples[name] = entry;
    }
  }
  fs.writeFileSync(path.join(work, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const opt = k => { const i = args.indexOf(k); return i < 0 ? null : args.splice(i, 2)[1]; };
  const only = opt('--only')?.split(','), boards = opt('--boards')?.split(',');
  const noEdif = args.includes('--no-edif');
  const work = path.resolve(args.find(a => !a.startsWith('--')) || '');
  if (!args.length) { console.error('usage: node research/s6/night1.mjs <work folder> [--only a,b] [--boards nexys3,atlys] [--no-edif]'); process.exit(2); }
  const m = await writeNight1(work, { ...(only && { only }), ...(boards && { boards }), edif: !noEdif });
  for (const [b, e] of Object.entries(m.boards)) console.log(`${b} (${e.part}): ${Object.keys(e.examples).length} examples${Object.entries(e.examples).filter(([, x]) => x.unmatched.length).map(([n, x]) => `; ${n} unmatched ${x.unmatched.join(' ')}`).join('')}`);
  console.log(`-> ${work}`);
}
