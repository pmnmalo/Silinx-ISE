// Stage S6-G (#731, #732): the Spartan-6's timing model for the Silinx toolchain, fitted on routed designs: the arcs
// by trce's types and by site class, the wires by class, load pin, fanout and wire type, the clock's arrival through
// its global buffer and from its pad, the pads' Tiopi and Tioop (sta6.mjs's fitTiming), written as
// packages/silinx-fpga/src/fpga/s6/timing-model.js (S6_SPEED_3), which fpga/s6/timing.js's analyzeTimingS6 reads.
//   node research/s6/fit-model6.mjs <dir> …   (each with top.xdl, top.twr and top.dly: night 1's impl-* and edif-*)
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadDesigns, fitTiming } from './sta6.mjs';
import { CLASSES6, PIN_KINDS } from '../../src/fpga/s6/timing.js';

const r4 = v => Math.round(v * 1e4) / 1e4;
const round = o => (typeof o === 'number' ? r4(o) : Array.isArray(o) ? o.map(round) : o && typeof o === 'object' ? Object.fromEntries(Object.entries(o).map(([k, v]) => [k, round(v)])) : o);

/** The model (S6_SPEED_3's shape) from fitTiming's result: { arcs, pad, wires, clock }. */
export function speedModel({ T, model, cw, cin, cout, tiopi, tioop }) {
  const w = model.weights, n = 1 + CLASSES6.length + 1;
  const wires = {
    base: w[0], classes: Object.fromEntries(CLASSES6.map((c, j) => [c, w[1 + j]])), fanout: w[1 + CLASSES6.length],
    pins: Object.fromEntries(PIN_KINDS.map((k, j) => [k, w[n + j]])),
    types: Object.fromEntries(model.vocab.map((t, j) => [t, w[n + PIN_KINDS.length + j]])), other: w.at(-1),
  };
  const { Tiopi, Tioop, ...arcs } = T;
  return round({ arcs, pad: { Tiopi: tiopi ?? Tiopi, Tioop: tioop ?? Tioop }, wires, clock: { net: cw, early: cin, late: cout, minScale: 1, hold: 0 } });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dirs = process.argv.slice(2);
  if (!dirs.length) { console.error('usage: node research/s6/fit-model6.mjs <dir> …'); process.exit(1); }
  const m = speedModel(fitTiming(loadDesigns(dirs)));
  const text = `// Silinx toolchain - the Spartan-6's timing model (-3 speed grade, #731, #732): generated by research/s6/fit-model6.mjs
// from ${dirs.length} designs routed by ISE (night 1's examples on the Nexys3 and the Atlys), fitted to trce's and reportgen's
// delays. arcs: trce's arc types (ns; types: each type's median, classes: by site class); pad: an input's Tiopi, an
// output's Tioop; wires: a connection's base, per node of each class, per load beyond one, per load pin kind, per
// wire type (other: a type not in the list); clock: the clock net's arrival (a + b × its routed path's nodes), the
// clock from its pad at a flip-flop, earliest and latest (a + b × the net's). Not edited by hand.
export const S6_SPEED_3 = ${JSON.stringify(m, null, 2)};
`;
  fs.writeFileSync(new URL('../../src/fpga/s6/timing-model.js', import.meta.url), text);
  console.log(`${dirs.length} designs: ${Object.keys(m.wires.types).length} wire types, ${Object.keys(m.arcs.types).length} arc types, ${Object.keys(m.arcs.classes).length} site classes; clock net ${m.clock.net.join(' + ')} × nodes`);
}
