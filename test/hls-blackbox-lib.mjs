// The HLS designs with an RTL blackbox (#2341, test/fixtures/hls-blackbox): a VHDL machine calling a Verilog module
// ('vhdl') and a Verilog machine calling a VHDL one ('verilog'), on a board: their sources as the build makes them, and
// each as a project folder for a target (test/hls-blackbox-flow.test.js, test/ise/hls-blackbox.test.js).
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, targetName } from './examples-lib.mjs';
import { compile, elaborate } from '../core/compile.js';
import { boardAutoAssign } from '../packages/silinx-fpga/src/ucf.js';
import { boardConstraintsText } from '../packages/silinx-fpga/src/board-constraints.js';
import { resolveBoard } from '../server/devices.js';
import { viewSources } from '../server/ise.js';

export const DESIGNS = ['vhdl', 'verilog'];
export const FIXTURES = path.join(ROOT, 'test', 'fixtures', 'hls-blackbox');

/** A fixture's sources: the project, its HDL files and the HDL of its C source, as the build makes it. */
export async function blackboxSources(lang, dir = path.join(FIXTURES, lang)) {
  const project = JSON.parse(fs.readFileSync(path.join(dir, 'silinx.json'), 'utf8'));
  const hdl = project.files.map(f => ({ path: f.path, lang: f.lang, text: fs.readFileSync(path.join(dir, f.path), 'utf8') }));
  const views = await viewSources(project, dir, hdl);
  return { project, hdl, views };
}

/** A fixture as a project folder for a target: its board's device and UCF (the board's pins, as the wizard assigns them). */
export async function blackboxProject(lang, target, into) {
  const dir = path.join(into, `hls-blackbox-${lang}-${targetName(target)}`);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.cpSync(path.join(FIXTURES, lang), dir, { recursive: true });
  const { project, hdl, views } = await blackboxSources(lang, dir);
  const r = resolveBoard(target.board, { variant: target.variant });
  const top = elaborate(compile([...hdl, ...views]), project.top).top;
  const ports = top.ports.map(p => { const t = p.sig.t, bus = t.w > 1 || (t.kind === 'logic' && !t.scalar); return { name: p.name, dir: p.dir, width: t.w, msb: bus ? t.left : null, lsb: bus ? t.right : null }; });
  const b = { name: r.board.name, device: r.device, resources: r.resources };
  const { assignments, clocks, unmatched } = boardAutoAssign(ports, b);
  assert.deepEqual(unmatched, []);
  fs.mkdirSync(path.join(dir, 'constraints'), { recursive: true });
  fs.writeFileSync(path.join(dir, project.constraints), boardConstraintsText({ device: r.device, ports, assignments, clocks, header: `UCF for top '${project.top}' on ${r.board.name}, generated by Silinx` }));
  const p = { ...project, device: r.device, board: target.board, boardVariant: target.variant };
  fs.writeFileSync(path.join(dir, 'silinx.json'), `${JSON.stringify(p, null, 2)}\n`);
  return { dir, project: p };
}
