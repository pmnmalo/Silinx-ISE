// The iCEBreaker (#2468): its pins (IceStorm's icebreaker.pcf) in the board data, a project's constraints made from them as
// a PCF, a design built with them by nextpnr-ice40 with no warnings; a Xilinx board's UCF as before
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { resolveBoard, findBoard, validateDevice } from '../server/devices.js';
import { boardConstraints } from '../server/projects.js';
import { boardAutoAssign, boardConstraintsText, generateUcf, PCF, runFlow, nextpnrIce40Node, yosysNode } from '../packages/silinx-fpga/src/node.js';

const TOP = 'module top(input clk, input [2:0] btn, output [4:0] led, output ledr_n);\n  reg [22:0] c = 0;\n  always @(posedge clk) c <= c + 1;\n  assign led = {c[22:20], btn[1:0]};\n  assign ledr_n = ~btn[2];\nendmodule\n';
const PORTS = [{ name: 'clk', dir: 'in', width: 1 }, { name: 'btn', dir: 'in', width: 3, msb: 2, lsb: 0 }, { name: 'led', dir: 'out', width: 5, msb: 4, lsb: 0 },
  { name: 'ledr_n', dir: 'out', width: 1 }];
const PCF_TEXT = `# PCF for top 'top' on 1BitSquared iCEBreaker (ice40up5k-sg48), generated by Silinx

set_io clk 35
set_io btn[0] 20
set_io btn[1] 19
set_io btn[2] 18
set_io led[0] 27
set_io led[1] 25
set_io led[2] 21
set_io led[3] 23
set_io led[4] 26
set_io ledr_n 11
set_frequency clk 12.000048
`;

test('the iCEBreaker in the board data: the UP5K in SG48, IceStorm\'s pins', () => {
  const b = findBoard('icebreaker');
  assert.deepEqual(b.device, { family: 'ice40', part: 'ice40up5k', package: 'sg48', speed: '' });
  assert.deepEqual(validateDevice(b.device), []);
  const pins = Object.fromEntries(b.resources.map(r => [r.name, r.pins]));
  const own = { clk: ['35'], led: ['27', '25', '21', '23', '26'], btn: ['20', '19', '18'], ledr_n: ['11'], ledg_n: ['37'], btn_n: ['10'], rx: ['6'], tx: ['9'] };
  // (#2517) the examples' display and switches on Pmods 1A and 1B: every one of their 16 pins
  assert.deepEqual(pins, { ...own, seg: ['4', '2', '47', '45', '3', '48', '46'], dp: ['44'], sw: ['43', '38', '34', '31'], an: ['42', '36', '32', '28'] });
  for (const n of ['seg', 'dp', 'an']) assert.equal(b.resources.find(r => r.name === n).extra.activeLow, true, n);
  // (the snap-off's LEDs and buttons are Pmod 2's pins: not a resource of their own, a pin on one resource only)
  assert.equal(new Set(Object.values(pins).flat()).size, Object.values(pins).flat().length);
  // the iCEBreaker with a PmodVGA: the same FPGA, its own pins; the colours' most significant bits (R1..R3, G1..G3, B2..B3)
  const v = findBoard('icebreaker-vga');
  assert.deepEqual(v.device, b.device);
  const vpins = Object.fromEntries(v.resources.map(r => [r.name, r.pins]));
  assert.deepEqual(vpins, { ...own, vga_red: ['2', '47', '45'], vga_green: ['38', '34', '31'], vga_blue: ['46', '44'], vga_hsync: ['42'], vga_vsync: ['36'] });
  assert.equal(new Set(Object.values(vpins).flat()).size, Object.values(vpins).flat().length);
  for (const r of [...b.resources, ...v.resources]) assert.equal(r.verified, !/^(seg|dp|sw|an|vga_)/.test(r.name), r.name);
});

test('a board\'s constraints in its family\'s format: a PCF on the iCEBreaker, the UCF as before on a Xilinx board', () => {
  const r = resolveBoard('icebreaker');
  const { assignments, clocks, unmatched } = boardAutoAssign(PORTS, { name: r.board.name, device: r.device, resources: r.resources });
  assert.deepEqual(unmatched, []);
  const header = "UCF for top 'top' on 1BitSquared iCEBreaker (ice40up5k-sg48), generated by Silinx";
  const text = boardConstraintsText({ device: r.device, ports: PORTS, assignments, clocks, header });
  assert.equal(text, PCF_TEXT);
  assert.deepEqual(PCF.read(text).clocks, [{ net: 'clk', period: 83.333 }]);
  const basys = resolveBoard('basys2');
  const x = boardAutoAssign(PORTS, { name: basys.board.name, device: basys.device, resources: basys.resources });
  const args = { ports: PORTS, assignments: x.assignments, clocks: x.clocks, header: 'UCF for top' };
  assert.equal(boardConstraintsText({ device: basys.device, ...args }), generateUcf(args));
});

test('a project on the iCEBreaker: its constraints/top.pcf from the board, a bitstream at those pins with no warnings', async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'silinx-icebreaker-'));
  try {
    await fs.mkdir(path.join(dir, 'src'));
    await fs.writeFile(path.join(dir, 'src/top.v'), TOP);
    const pj = { name: 'ice', board: 'icebreaker', device: findBoard('icebreaker').device, top: 'top', files: [{ path: 'src/top.v', lang: 'verilog', role: 'design' }], constraints: 'constraints/top.pcf' };
    await boardConstraints(dir, pj);
    const pcf = await fs.readFile(path.join(dir, 'constraints/top.pcf'), 'utf8');
    assert.equal(pcf, PCF_TEXT);
    const log = [], files = {};
    const io = { log: l => log.push(l), sources: () => [{ path: 'top.v', lang: 'verilog', text: TOP }], ucf: pcf, ucfName: 'top.pcf',
      yosys: yosysNode, nextpnr: { ice40: nextpnrIce40Node() }, write: (n, d) => { files[n] = d; return `build/${n}`; }, read: n => files[n] ?? null, save: () => {} };
    const r = await runFlow({ top: 'top', family: 'ice40', device: 'ice40up5k', pkg: 'sg48', steps: ['synth', 'translate', 'par', 'bitgen'] }, io);
    assert.ok(r.ok, r.error);
    assert.deepEqual(log.filter(l => /^WARNING/.test(l)), []);
    assert.equal(files['top.bin'].length, 104090);
    assert.ok(r.report.par.constraintsMet);
    // (every pin of the PCF read, and nextpnr refuses a pin the package does not have: test/ice40.test.js)
    assert.ok(log.includes('Netlist of <top> read; constraints: top.pcf, 10 pin location(s), 1 PERIOD constraint(s).'));
  } finally {
    await fs.rm(dir, { recursive: true, force: true });
  }
});
