// UI: the boards in the browser edition. The Silinx toolchain's Spartan-6 flow (#2103): the site built (test/ui/site-lib.js) and
// served over HTTP; a new project from the blinky example on the Nexys3 (its UCF made for the board, #2430), Generate
// Programming File in the browser: the device description and the bit databases of the XC6SLX16 fetched from the site's
// assets (bitdb/s6), Map's lines as ISE's MAP names the Spartan-6's resources, the PERIOD met, no warning, and the
// bitstream downloaded: the XC6SLX16's, its frame data the same as the local server's flow writes for the same design
// (server/open-flow.js). A new project from an example on another board than the example's Basys2 gets that board's
// pins, as the server writes them (#2430); on the Basys2, the example's UCF as it is.
import { before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { setupUi, uiTest, waitDownload, ROOT } from './harness.js';
import { buildSite } from './site-lib.js';
import { resolveBoard } from '../../server/devices.js';
import { runOpenImplementation } from '../../server/open-flow.js';
import { readBit6 } from '../../packages/silinx-fpga/src/fpga/s6/bitstream.js';

let env, site;
before(async () => {
  env = await setupUi({ server: false });
  if (env.skip) return;
  site = await buildSite(env.tmp);
});
after(async () => { site?.close?.(); await env?.teardown?.(); });
const E = () => (site?.skip ? { skip: site.skip } : env);

// the local server's flow on the same project (the example, the UCF the wizard wrote for the Nexys3): its bitstream
async function serverBit(ucf) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'silinx-s6-web-'));
  try {
    const project = JSON.parse(fs.readFileSync(path.join(ROOT, 'examples/blinky/silinx.json'), 'utf8'));
    for (const f of project.files) { fs.mkdirSync(path.join(dir, path.dirname(f.path)), { recursive: true }); fs.copyFileSync(path.join(ROOT, 'examples/blinky', f.path), path.join(dir, f.path)); }
    fs.mkdirSync(path.join(dir, path.dirname(project.constraints)), { recursive: true });
    fs.writeFileSync(path.join(dir, project.constraints), ucf);
    const lines = [];
    await runOpenImplementation({ log: (l) => lines.push(l), procs: new Set(), cancelled: false }, { project: { ...project, name: 'Web6', board: 'nexys3', device: resolveBoard('nexys3').device }, projectDir: dir, steps: ['bitgen'] });
    return readBit6(fs.readFileSync(path.join(dir, `build/${project.top}.bit`)));
  } finally { fs.rmSync(dir, { recursive: true, force: true }); }
}

// File ▸ New Project… from an example on a board (the wizard's board select)
async function newProject(page, name, template, board) {
  await page.menu('File', 'New Project…');
  await page.waitDialog('New Project Wizard');
  await page.fill('.dlg-overlay .wiz-main input[type=text]', name);
  await page.fill('.dlg-overlay .wiz-main select', template, { index: 0 });
  await page.dialogButton('Next >');
  await page.fill('.dlg-overlay .wiz-main select', board, { index: 0 });
  await page.dialogButton('Next >');
  await page.dialogButton('Finish');
  await page.waitNoDialog();
  await page.waitFor((n) => window.Silinx.project?.name === n && window.Silinx.project.top, [name]);
}
// the project's UCF, as its editor shows it
const ucfText = (page) => page.eval(async () => {
  const f = window.Silinx.project.constraints;
  await window.SilinxApp.openFile(f);
  return window.SilinxApp.findDoc(`file:${f}`)?.editor.getValue();
});

uiTest('#2103 browser edition: Generate Programming File of blinky on the Nexys3 runs the Silinx toolchain\'s Spartan-6 flow in the browser, no warnings', E, async (page) => {
  await page.goto(site.url);
  await page.waitFor(() => window.SilinxApp && document.querySelector('#menubar .item') && window.Silinx.devices, [], { what: 'site boot' });
  await newProject(page, 'Web6', 'blinky', 'nexys3');
  assert.deepEqual(await page.eval(() => window.Silinx.project.device), { family: 'spartan6', part: 'xc6slx16', package: 'csg324', speed: '-3' });
  assert.match(await page.consoleText(), /Browser edition: projects are stored in this browser .*run the Silinx toolchain here \(the Spartan-3E, and the Spartan-6 of the Nexys3 and the Atlys\)/);
  // the example's UCF (the Basys2's pins) made again for the Nexys3 when the project is made, as the server does (#2430)
  await page.waitConsole(/^constraints\/top\.ucf regenerated for Digilent Nexys3: /m);
  const ucf = await ucfText(page);
  assert.match(ucf, /^\W*UCF for top 'top' on Digilent Nexys3 \(xc6slx16-3-csg324\), generated by Silinx/m);
  await page.setView('impl');
  const served = site.served.length;
  await page.treeRow('#procs', 'Generate Programming File', { dbl: true, exact: true });
  // (the console with the failure: where the flow stopped)
  await page.waitConsole(/=== SILINX (DONE|FAILED)/, { timeout: 240000 }).catch(async (e) => { throw new Error(`${e.message}\n${(await page.consoleText()).slice(-3000)}`); });
  await page.waitFor(() => !window.Silinx.busy, [], { what: 'flow finished', timeout: 30000 });
  const log = await page.consoleText();
  assert.doesNotMatch(log, /SILINX FAILED|Process failed/, log);
  for (const re of [/device=xc6slx16csg324-3/, /Loading the device description of xc6slx16csg324-3 and its bit database…/,
    /=== SILINX STEP synth ===/, /=== SILINX STEP map ===/, / {2}Number of Slice LUTs: \d+ out of 9112 \d+%/, / {2}Number of occupied Slices: \d+ out of 2278 \d+%/,
    /=== SILINX STEP par ===/, /constraint PERIOD 10 ns on clk: met \(period \d+\.\d{3} ns, slack \d+\.\d{3} ns\)/, /All constraints were met\./,
    /=== SILINX STEP bitgen ===/, /Bitstream: build\/top\.bit/, /=== SILINX DONE ===/, /Process "Generate Programming File" completed successfully/])
    assert.match(log, re);
  // no warnings: none in the flow's lines, none in the Errors and Warnings
  assert.deepEqual(log.split('\n').filter((l) => /^\s*(WARNING|ERROR)/.test(l)), []);
  assert.deepEqual(await page.eval(() => window.Silinx.diags.filter((d) => d.severity !== 'info').map((d) => d.message)), []);
  // the part's assets from the site: its device description, its bit databases in bitdb/s6, no Spartan-3E database
  const asked = site.served.slice(served);
  assert.ok(asked.some((p) => /\/devices\/xc6slx16csg324-3\.json\.gz$/.test(p)), asked.join('\n'));
  for (const f of ['xc6slx16-lut.json', 'xc6slx16-iob.json', 'xc6slx16-int.json', 's6-pips-flow.json', 's6-ologic.json']) assert.ok(asked.some((p) => p.endsWith(`/bitdb/s6/${f}`)), f);
  assert.deepEqual(asked.filter((p) => /\/bitdb\/(xc3s|s3e-)/.test(p) || /xc6slx45/.test(p)), []);
  // the bitstream: the XC6SLX16's, CRC checked, its frame data the local server's for the same design
  const bit = readBit6(fs.readFileSync(await waitDownload(page, 'top.bit')));
  assert.equal(bit.header.b, '6slx16csg324');
  assert.ok(bit.crc && bit.crcChecks.length && bit.crcChecks.every((c) => c.expected === c.computed));
  const ref = await serverBit(ucf);
  assert.equal(bit.fdri.length, ref.fdri.length);
  assert.ok(bit.fdri.every((w, i) => w === ref.fdri[i]), 'the frame data of the local server\'s flow');
}, { url: () => 'about:blank', timeout: 400000 });

uiTest('#2430 browser edition: a new project from an example on the Nexys2 gets the Nexys2\'s pins; on the Basys2, the example\'s UCF as it is', E, async (page) => {
  await page.goto(site.url);
  await page.waitFor(() => window.SilinxApp && document.querySelector('#menubar .item') && window.Silinx.devices, [], { what: 'site boot' });
  const example = fs.readFileSync(path.join(ROOT, 'examples/gates/constraints/gates.ucf'), 'utf8');
  await newProject(page, 'Gates2', 'gates', 'nexys2');
  await page.waitConsole(/^constraints\/gates\.ucf regenerated for Digilent Nexys2: /m);
  const ucf = await ucfText(page);
  assert.match(ucf, /^\W*UCF for top 'gates' on Digilent Nexys2 \(xc3s500e-4-fg320\), generated by Silinx/m);
  assert.notEqual(ucf, example);
  // its pins all on the board: Implement's check asks nothing
  const { parseUcf, locsNotOnBoard } = await import('../../packages/silinx-fpga/src/parts.js');
  const board = await page.eval(() => window.SilinxApp.projectBoard());
  assert.deepEqual(locsNotOnBoard(parseUcf(ucf).assignments, board), []);
  const before = (await page.consoleText()).length;
  await newProject(page, 'Gates1', 'gates', 'basys2');
  assert.equal(await ucfText(page), example);
  assert.doesNotMatch((await page.consoleText()).slice(before), /regenerated for|WARNING|ERROR/);
}, { url: () => 'about:blank', timeout: 120000 });
