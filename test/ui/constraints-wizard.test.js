// UI: the Constraints Wizard of the other families (#2296), New Source ▸ Implementation Constraints File ▸ Wizard > on a
// board of theirs: the CST Wizard on the Tang Nano 9K (each bit on a pin of the board, its I/O standard its bank's, its pull
// and drive; a LED of the 1.8 V bank at LVCMOS33 refused, Check Constraints' message; the file written, the project's), the
// PCF Wizard on the iCEBreaker (a pull-up only), I/O Pin Planning's columns of a PCF; in Portuguese.
import { before, after } from 'node:test';
import assert from 'node:assert/strict';
import { setupUi, uiTest, makeProject, readWs } from './harness.js';
import { TEXTS, untranslated } from './i18n-check.js';
import { newSourceWizardOf } from './new-source-helpers.js';

let env;
before(async () => { env = await setupUi(); });
after(async () => { await env?.teardown?.(); });
const E = () => env;

const BLINK = 'module blink(input clk, input [1:0] btn_n, output [1:0] led_n);\n  assign led_n = btn_n ^ {2{clk}};\nendmodule\n';
const TANGNANO = { family: 'gowin', part: 'gw1nr-9c', package: 'qn88', speed: '-6' };
const UP5K = { family: 'ice40', part: 'ice40up5k', package: 'sg48', speed: '' };
const steps = (page) => page.eval(() => [...document.querySelectorAll('.dlg-overlay .wiz-side .step')].map((e) => e.textContent));
const errText = (page) => page.eval(() => document.querySelector('.dlg-overlay .wiz-main').nextElementSibling.textContent);
const heads = (page) => page.eval(() => [...document.querySelectorAll('.dlg-overlay .uw-pins th')].map((x) => x.textContent));
// the table's rows: net, direction, pin and the attributes' values
const rows = (page) => page.eval(() => [...document.querySelectorAll('.dlg-overlay .uw-pins tr')].slice(1)
  .map((r) => [...r.cells].map((c) => c.querySelector('select, input')?.value ?? c.textContent).join(' ')));
const logWarnings = (page) => page.eval(() => [...document.querySelectorAll('#console-log .ln')].map((l) => l.textContent).filter((t) => /^(WARNING|ERROR)/.test(t)));

uiTest('#2296 CST Wizard on the Tang Nano 9K: the bits on its pins with their banks\' I/O standards, a drive and a pull; a 1.8 V LED at LVCMOS33 refused; the project\'s CST', E, async (page) => {
  await makeProject(env, { name: 'CwTang', board: 'tangnano9k', device: TANGNANO, top: 'blink', constraints: 'constraints/top.cst', files: { 'src/blink.v': BLINK } });
  await page.openProject('CwTang');
  await newSourceWizardOf(page, 'Implementation Constraints File', 'pins', 'CST Wizard');
  assert.deepEqual(await steps(page), ['Ports and Pins', 'Summary']);
  assert.deepEqual(await heads(page), ['Signal', 'Direction', 'Pin', 'I/O Std.', 'Pull', 'Drive']);
  assert.deepEqual(await rows(page), ['clk in 52 LVCMOS33  ', 'btn_n<1> in 4 LVCMOS18  ', 'btn_n<0> in 3 LVCMOS18  ', 'led_n<1> out 11 LVCMOS18  ', 'led_n<0> out 10 LVCMOS18  ']);
  // a LED of the bank at 1.8 V at 3.3 V: Check Constraints' error, on Next >
  await page.fill('.dlg-overlay .uw-iostandard[data-net="led_n<0>"]', 'LVCMOS33');
  await page.dialogButton('Next >');
  await page.waitFor(() => /in a bank at/.test(document.querySelector('.dlg-overlay .wiz-main').nextElementSibling.textContent), [], { what: 'the bank\'s voltage refused' });
  assert.equal(await errText(page), 'IO_TYPE=LVCMOS33 of led_n[0]: the pin 10 (led_n<0>) is in a bank at 1.8 V on the Sipeed Tang Nano 9K (LVCMOS18), not 3.3 V.');
  // (in Portuguese)
  await page.eval(async () => (await import('/js/i18n.js')).setLanguage('pt'));
  try {
    await page.waitFor(() => /está num banco a 1\.8 V/.test(document.querySelector('.dlg-overlay .wiz-main').nextElementSibling.textContent), [], { what: 'the message in Portuguese' });
    assert.equal(await errText(page), 'IO_TYPE=LVCMOS33 de led_n[0]: o pino 10 (led_n<0>) está num banco a 1.8 V na Sipeed Tang Nano 9K (LVCMOS18), não a 3.3 V.');
    assert.deepEqual(await heads(page), ['Sinal', 'Direção', 'Pino', 'Norma de E/S', 'Pull', 'Corrente']);
  } finally { await page.eval(async () => (await import('/js/i18n.js')).setLanguage('en')); }
  await page.fill('.dlg-overlay .uw-iostandard[data-net="led_n<0>"]', 'LVCMOS18');
  await page.fill('.dlg-overlay .uw-drive[data-net="led_n<0>"]', '8');
  await page.fill('.dlg-overlay .uw-pull[data-net="btn_n<1>"]', 'up');
  // a pin moved: its I/O standard its new bank's
  await page.fill('.dlg-overlay .uw-pin[data-net="led_n<1>"]', '25');
  await page.waitFor(() => document.querySelector('.dlg-overlay .uw-iostandard[data-net="led_n<1>"]')?.value === 'LVCMOS33', [], { what: 'the moved pin\'s standard' });
  await page.dialogButton('Next >');
  await page.waitFor(() => document.querySelector('.dlg-overlay .wiz-main h3')?.textContent === 'Summary', [], { what: 'the Summary' });
  const preview = await page.eval(() => document.querySelector('.dlg-overlay .uw-preview').textContent);
  assert.equal(preview, "// CST generated by the Silinx CST Wizard for 'blink' (gw1nr-9c-6-qn88, Sipeed Tang Nano 9K)\n\n"
    + 'IO_LOC "clk" 52;\nIO_PORT "clk" IO_TYPE=LVCMOS33;\nIO_LOC "btn_n[0]" 3;\nIO_PORT "btn_n[0]" IO_TYPE=LVCMOS18;\nIO_LOC "btn_n[1]" 4;\nIO_PORT "btn_n[1]" IO_TYPE=LVCMOS18 PULL_MODE=UP;\n'
    + 'IO_LOC "led_n[0]" 10;\nIO_PORT "led_n[0]" IO_TYPE=LVCMOS18 DRIVE=8;\nIO_LOC "led_n[1]" 25;\nIO_PORT "led_n[1]" IO_TYPE=LVCMOS33;\n'
    + '// create_clock -name clk -period 37.037 [get_ports {clk}]\n');
  assert.match(await page.eval(() => document.querySelector('.dlg-overlay .wiz-main').innerText), /^Summary\nThe wizard will create constraints\/pins\.cst, the project's constraints file:/);
  await page.dialogButton('Finish');
  await page.waitNoDialog();
  await page.waitFor(() => window.Silinx.project.constraints === 'constraints/pins.cst', [], { what: 'the project\'s constraints file' });
  assert.equal(await readWs(env, 'CwTang', 'constraints/pins.cst'), preview);
  assert.deepEqual(await logWarnings(page), []);
  // read back by Check Constraints: no warnings
  const diags = await page.eval(async () => (await import('/js/implement.js')).ucfDiagnostics(await (await import('/js/api.js')).api.readFile('CwTang', 'constraints/pins.cst'), 'constraints/pins.cst'));
  assert.deepEqual(diags, []);
});

uiTest('#2296 PCF Wizard on the iCEBreaker: a pull-up only; I/O Pin Planning\'s columns of a PCF; in Portuguese', E, async (page) => {
  await makeProject(env, { name: 'CwIce', board: 'icebreaker', device: UP5K, top: 'blink', constraints: 'constraints/top.pcf', files: { 'src/blink.v': BLINK } });
  await page.openProject('CwIce');
  await newSourceWizardOf(page, 'Implementation Constraints File', 'pins', 'PCF Wizard');
  assert.deepEqual(await heads(page), ['Signal', 'Direction', 'Pin', 'Pull']);
  assert.deepEqual(await page.eval(() => [...document.querySelector('.dlg-overlay .uw-pull').options].map((o) => o.value)), ['', 'up']);
  // (btn_n<1>: no pin on the board, left without one)
  await page.fill('.dlg-overlay .uw-pull[data-net="clk"]', 'up');
  await page.eval(TEXTS);
  const setLang = (l) => page.eval(async (x) => { (await import('/js/i18n.js')).setLanguage(x); }, l);
  const missing = [];
  const compare = async (where) => {
    await setLang('en'); const en = await page.eval(() => window.__uiTexts(document.querySelector('.dlg-overlay')));
    await setLang('pt'); const pt = await page.eval(() => window.__uiTexts(document.querySelector('.dlg-overlay')));
    for (const s of untranslated(en, pt, [/^(clk|in|out)$/, /^\(none\)$/, /·/, /^(Pull|up)$/])) missing.push(`${where}: ${s}`);
    await setLang('en');
  };
  await compare('Ports and Pins');
  await setLang('pt');
  try {
    await page.waitDialog('Assistente de PCF');
    assert.deepEqual(await heads(page), ['Sinal', 'Direção', 'Pino', 'Pull']);
  } finally { await setLang('en'); }
  await page.dialogButton('Next >');
  await page.waitFor(() => document.querySelector('.dlg-overlay .wiz-main h3')?.textContent === 'Summary', [], { what: 'the Summary' });
  await compare('Summary');
  assert.deepEqual(missing, []);
  assert.equal(await page.eval(() => document.querySelector('.dlg-overlay .uw-preview').textContent),
    "# PCF generated by the Silinx PCF Wizard for 'blink' (ice40up5k-sg48, 1BitSquared iCEBreaker)\n\nset_io -pullup yes clk 35\nset_io btn_n[0] 10\nset_io led_n[0] 27\nset_io led_n[1] 25\n"
    + 'set_frequency clk 12.000048\n');
  await page.dialogButton('Finish');
  await page.waitNoDialog();
  await page.waitFor(() => window.Silinx.project.constraints === 'constraints/pins.pcf', [], { what: 'the project\'s constraints file' });
  // I/O Pin Planning on the PCF: its pull read back; no I/O standard, drive nor slew (a PCF has none)
  await page.eval(() => window.SilinxApp.openPinPlanner());
  await page.waitFor(() => document.querySelectorAll('.pp-table tr').length > 1, [], { what: 'I/O Pin Planning' });
  const cells = await page.eval(() => [...document.querySelectorAll('.pp-table tr')].slice(1).map((r) => [r.cells[0].textContent, ...[4, 5, 6, 7].map((i) => `${r.cells[i].querySelector('select').value}${r.cells[i].querySelector('select').disabled ? '(off)' : ''}`)].join(' ')));
  assert.deepEqual(cells, ['clk (off) (off) (off) up', 'btn_n<0> (off) (off) (off) ', 'btn_n<1> (off) (off) (off) ', 'led_n<0> (off) (off) (off) ', 'led_n<1> (off) (off) (off) ']);
});
