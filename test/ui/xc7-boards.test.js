// UI: the 7-series' boards (#3142): the Basys 3 and the Nexys A7 in Design Properties, marked experimental, their family
// too; choosing one offers AMD Vivado as its synthesis tool (or the Silinx toolchain, #3146) and writes the board's pins as constraints/top.xdc; the process tree and the
// toolbar are AMD Vivado's (#1649: its synthesis, implementation and programming; the Board Emulator's Emulate, #3704), a run without Vivado
// configured says so; Check Constraints reads XDC, its warnings exact; in Portuguese. Both interfaces.
import { before, after } from 'node:test';
import assert from 'node:assert/strict';
import { setupUi, uiTest, makeProject, readWs } from './harness.js';

let env;
before(async () => { env = await setupUi(); });
after(async () => { await env?.teardown?.(); });
const E = () => env;

const TOP = 'module top(input clk, input [3:0] sw, output reg [7:0] led);\n  always @(posedge clk) led <= {sw, sw};\nendmodule\n';
const BASYS2 = { family: 'spartan3e', part: 'xc3s250e', package: 'cp132', speed: '-4' };

// the Design Properties dialog's fields
const fields = page => page.eval(() => {
  const sel = l => [...document.querySelectorAll('.dlg-overlay label')].find(x => x.textContent === l)?.nextElementSibling;
  const opts = s => [...s.options].map(o => o.textContent);
  return { boards: opts(sel('Evaluation Development Board:') || sel('Placa de Desenvolvimento:')), families: opts(sel('Family:') || sel('Família:')) };
});

uiTest('#3142 #1649 Design Properties: the Basys 3, experimental; the pins as an XDC, AMD Vivado\'s processes, Check Constraints of the XDC', E, async (page) => {
  await makeProject(env, { name: 'Xc7Pick', board: 'basys2', device: BASYS2, files: { 'src/top.v': TOP }, top: 'top' });
  await page.openProject('Xc7Pick');
  await page.menu('Project', 'Design Properties…');
  await page.waitDialog('Design Properties');
  const f = await fields(page);
  assert.ok(f.boards.includes('Digilent Basys 3 (experimental)') && f.boards.includes('Digilent Nexys A7 (experimental)'), String(f.boards));
  assert.deepEqual(f.boards.filter(b => /experimental/.test(b)), ['Digilent Basys 3 (experimental)', 'Digilent Nexys A7 (experimental)']);
  assert.ok(f.families.includes('Artix-7 (experimental)') && f.families.includes('Spartan-3E'), String(f.families));
  // the board chosen: its device, the synthesis tool locked
  const chosen = await page.eval(() => {
    const sel = l => [...document.querySelectorAll('.dlg-overlay label')].find(x => x.textContent === l).nextElementSibling;
    const b = sel('Evaluation Development Board:'); b.value = 'basys3'; b.dispatchEvent(new Event('change'));
    return { part: sel('Device:').value, pkg: sel('Package:').value, speed: sel('Speed:').value, synth: sel('Synthesis Tool:').value, synthOff: sel('Synthesis Tool:').disabled };
  });
  assert.deepEqual(chosen, { part: 'xc7a35t', pkg: 'cpg236', speed: '-1', synth: 'vivado', synthOff: false });   // (AMD Vivado, or the Silinx toolchain's experimental back end, #3146)
  await page.dialogButton('OK');
  await page.waitDialog('Update Constraints');
  await page.dialogButton('Yes');
  await page.waitNoDialog();
  await page.waitFor(() => window.Silinx.project.constraints === 'constraints/top.xdc', [], { what: 'the XDC the project\'s' });
  await page.waitConsole(/top\.xdc regenerated for Digilent Basys 3/);
  const lines = (await page.consoleText()).split('\n').filter(l => /WARNING|ERROR|Device set|regenerated/.test(l));
  // (an empty project: no constraints file yet, none to convert)
  // (no "no flow" warning: the local server's AMD Vivado implements it, #1649)
  assert.deepEqual(lines, ['Device set to xc7a35t-1-cpg236 (board basys3).', 'constraints/top.xdc regenerated for Digilent Basys 3: clk, sw, led']);
  const xdc = await readWs(env, 'Xc7Pick', 'constraints/top.xdc');
  assert.match(xdc, /^# XDC for top 'top' on Digilent Basys 3 \(xc7a35t-1-cpg236\), generated by Silinx\n\nset_property -dict \{ PACKAGE_PIN W5 IOSTANDARD LVCMOS33 \} \[get_ports \{clk\}\]\n/);
  assert.match(xdc, /\[get_ports \{led\[7\]\}\]\n\n# Timing constraints\ncreate_clock -add -name clk -period 10\.000 -waveform \{0\.000 5\.000\} \[get_ports \{clk\}\]\n/);

  // the processes: AMD Vivado's (#1649): its synthesis, the implementation, the programming file and the board; no
  // simulation model, no technology view, no FPGA view; Emulate on Board (#3704)
  await page.setView('impl');
  await page.treeRow('#hier', 'top');
  const labels = await page.eval(() => [...document.querySelectorAll('#procs .row')].map(x => x.textContent.trim().replace(/^▾/, '')));
  for (const absent of ['Synthesize - Yosys', 'Synthesize - XST', 'View Technology Schematic', 'Generate Post-Synthesis Simulation Model', 'View Implemented Design (FPGA)']) assert.ok(!labels.some(l => l.startsWith(absent)), `${absent}: ${labels}`);
  for (const present of ['User Constraints', 'Synthesize - Vivado', 'View RTL Schematic', 'Check Syntax', 'Implement Design', 'Map', 'Place & Route', 'Generate Post-Place & Route Static Timing', 'Generate Programming File', 'Configure Target Device'])
    assert.ok(labels.includes(present), `${present}: ${labels}`);
  // Emulate on Board (#3704): the HDL on the board's pins; its RTL model only (the flow makes no simulation model)
  for (const present of ['Emulate on Board', 'Emulate Behavioral Model (RTL)']) assert.ok(labels.includes(present), `${present}: ${labels}`);
  assert.ok(!labels.some(l => /^Emulate Post-/.test(l)), String(labels));
  // the Silinx toolbar's steps (the Silinx interface's): every one on, Emulate too (#3704)
  const steps = await page.eval(() => { window.SilinxApp.select?.(window.Silinx.sel); return Object.fromEntries([...document.querySelectorAll('#toolbar .m-step')].map(b => [b.dataset.step, b.disabled])); });
  assert.deepEqual(steps, { check: false, simulate: false, implement: false, emulate: false, program: false });
  // Synthesize with no Vivado configured: said so, the scripts generated all the same (run.tcl and run.sh in build/)
  await page.eval(async () => (await import('/js/implement.js')).runImpl('top', ['synth']));
  await page.waitConsole(/AMD Vivado not available \(docker mode\): no Vivado docker image configured \(vivado\.image\)/);
  await page.waitConsole(/run\.tcl and run\.sh are still generated so they can be run on a machine with Vivado 2025\.2/);
  await page.waitFor(() => !window.Silinx.busy, [], { what: 'the run\'s end' });
  assert.match(await readWs(env, 'Xc7Pick', 'build/run.tcl'), /synth_design -top top -part \$part/);

  // Check Constraints of the XDC: a port the top has not, its warning; a line Vivado stops at, its error
  const ports = [{ name: 'clk', width: 1 }, { name: 'sw', width: 4, msb: 3, lsb: 0 }, { name: 'led', width: 8, msb: 7, lsb: 0 }];
  const r = await page.eval(async (p) => {
    const { xdcDiagnostics, readPins, writePins, constraintsExt } = await import('/js/constraints-format.js');
    const device = { part: 'xc7a35t' };
    const read = readPins(device, 'set_property -dict { PACKAGE_PIN W5 IOSTANDARD LVCMOS33 } [get_ports clk]\nset_property PACKAGE_PIN U16 [get_ports {led[0]}]\ncreate_clock -period 10 [get_ports clk]\n');
    return {
      ext: [constraintsExt(device), constraintsExt({ part: 'xc7a100t' }), constraintsExt({ part: 'xc3s250e' })],
      read: read.assignments,
      written: writePins(device, { assignments: read.assignments, clocks: read.clocks, header: 'H' }),
      good: xdcDiagnostics(await (await import('/js/api.js')).api.readFile('Xc7Pick', 'constraints/top.xdc'), p),
      unknown: xdcDiagnostics('set_property -dict { PACKAGE_PIN W5 IOSTANDARD LVCMOS33 } [get_ports clk]\n\nset_property -dict { PACKAGE_PIN U18 IOSTANDARD LVCMOS33 } [get_ports { btnC }]; # a button\nset_property PACKAGE_PIN W2 [get_ports {sw[12]}]\n', p),
      bad: xdcDiagnostics('set_property PACKAGE_PIN W5 [get_ports clk]\nset_property SLEW quick [get_ports clk]\n', p),
    };
  }, ports);
  assert.deepEqual(r.ext, ['.xdc', '.xdc', '.ucf']);
  assert.deepEqual(r.read, { clk: { loc: 'W5', iostandard: 'LVCMOS33' }, 'led<0>': { loc: 'U16' } });
  assert.equal(r.written, '# H\nset_property -dict { PACKAGE_PIN W5 IOSTANDARD LVCMOS33 } [get_ports {clk}]\nset_property -dict { PACKAGE_PIN U16 } [get_ports {led[0]}]\n\n# Timing constraints\ncreate_clock -add -name clk -period 10.000 -waveform {0.000 5.000} [get_ports {clk}]\n');
  assert.deepEqual(r.good, []);
  assert.deepEqual(r.unknown, [{ severity: 'warning', message: 'get_ports btnC: the top has no such port', line: 3 }, { severity: 'warning', message: 'get_ports sw[12]: the top has no such port', line: 4 }]);
  assert.deepEqual(r.bad, [{ severity: 'error', line: 2, message: 'SLEW quick: SLOW or FAST' }]);
  // Check Constraints on the project's XDC: completed, no warning
  await page.eval(async () => (await import('/js/implement.js')).checkUcfFile());
  await page.waitConsole(/Process "Check Constraints" completed successfully/);
  assert.deepEqual((await page.consoleText()).split('\n').filter(l => /ConstraintSystem/.test(l)), []);
});

uiTest('#3142 #1649 in Portuguese: the boards and the family marked experimental in Design Properties, the labels translated, Vivado\'s processes', E, async (page) => {
  await makeProject(env, { name: 'Xc7Pt', board: 'basys3', files: { 'src/top.v': TOP }, top: 'top' });
  await page.eval(async () => (await import('/js/i18n.js')).setLanguage('pt'));
  try {
    await page.openProject('Xc7Pt');
    await page.menu('Projeto', 'Propriedades do Projeto…');
    await page.waitDialog('Propriedades do Projeto');
    const r = await page.eval(() => {
      const labels = [...document.querySelectorAll('.dlg-overlay label')].map(x => x.textContent);
      const sel = l => [...document.querySelectorAll('.dlg-overlay label')].find(x => x.textContent === l)?.nextElementSibling;
      return { labels, board: sel('Placa de Desenvolvimento:')?.selectedOptions[0]?.textContent, family: sel('Família:')?.selectedOptions[0]?.textContent, synthOff: sel('Ferramenta de Síntese:')?.disabled };
    });
    assert.ok(r.labels.includes('Placa de Desenvolvimento:') && r.labels.includes('Família:'), String(r.labels));
    assert.deepEqual([r.board, r.family, r.synthOff], ['Digilent Basys 3 (experimental)', 'Artix-7 (experimental)', false]);
    await page.dialogButton('Cancelar');
    // AMD Vivado's processes in Portuguese (#1649)
    await page.setView('impl');
    await page.treeRow('#hier', 'top');
    const procs = await page.eval(() => [...document.querySelectorAll('#procs .row')].map(x => x.textContent.trim().replace(/^▾/, '')));
    for (const l of ['Sintetizar - Vivado', 'Implementar Projeto', 'Gerar Ficheiro de Programação']) assert.ok(procs.includes(l), `${l}: ${procs}`);
  } finally {
    await page.eval(async () => (await import('/js/i18n.js')).setLanguage('en'));
  }
});
