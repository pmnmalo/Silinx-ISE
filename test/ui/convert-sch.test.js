// UI: Convert to Schematic (editable) of any HDL module (#225): a behavioural module in a file that
// holds another module too, a VHDL module whose file holds a package; the [Schematic] badge on the
// module's row (the base), its HDL generated from it at once, the other design units kept in a file
// of their own; the console says what was done; a module that does not elaborate is not converted
// (the dialog says why, in English and in Portuguese); an escaped internal wire (\\t[0] ) is a wire of the drawing
// (#1809).
import { before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { setupUi, uiTest, makeProject, readWs } from './harness.js';
import { CASES } from '../fixtures/hdl-to-sch-cases.js';
import { netlist } from '../../core/schdoc.js';

let env;
before(async () => { env = await setupUi(); });
after(async () => { await env?.teardown?.(); });
const E = () => env;

// the badges of the row `label`: "[Schematic*] [Verilog]" (* the base)
const badgesOf = (page, label) => page.eval((l) => {
  const r = [...document.querySelectorAll('#hier .row')].find((x) => x.querySelector('.lbl').textContent === l);
  return r ? [...r.querySelectorAll('.badge')].map((x) => `[${x.textContent}${x.classList.contains('base') ? '*' : ''}]`).join(' ') : null;
}, label);
const exists = (pj, p) => fs.access(path.join(env.server.workspace, pj, p)).then(() => true, () => false);
const convert = async (page, row) => {
  await page.treeRow('#hier', row, { right: true, exact: true });
  await page.click('body > .menu-popup .mi', { text: 'Convert to Schematic (editable)…' });
};
// the console's lines from the conversion on
const linesFrom = async (page, re) => { const l = (await page.consoleText()).split('\n'); return l.slice(l.findIndex((x) => re.test(x))); };

uiTest('Convert to Schematic of a behavioural Verilog module whose file holds another module: [Schematic] on its row, its HDL generated, the other module in a file of its own', E, async (page) => {
  const c = CASES.find((x) => x.name === 'verilog-multi');
  await makeProject(env, { name: 'Conv_v', files: c.files, top: 'proc', simTop: 'tb_proc' });
  await page.openProject('Conv_v');
  assert.equal(await badgesOf(page, 'proc'), '[Verilog*]');
  await convert(page, 'proc');
  await page.waitFor(() => window.Silinx.hdlToSch?.['src/proc.v'] === 'src/proc.sch.json' && window.Silinx.active?.id === 'sch:src/proc.sch.json', [], { what: 'converted, linked, open', timeout: 20000 });
  // the module's row: the schematic its base, its HDL generated from it; adder a plain module in adder.v
  await page.waitFor(() => [...document.querySelectorAll('#hier .row')].some((r) => r.querySelector('.lbl').textContent === 'proc' && r.querySelector('.badge.base')?.textContent === 'Schematic'), [], { what: 'the [Schematic] badge' });
  assert.equal(await badgesOf(page, 'proc'), '[Schematic*] [Verilog]');
  assert.equal(await badgesOf(page, 'u_add - adder'), '[Verilog*]');
  assert.equal(await page.eval(() => [...document.querySelectorAll('#hier .row')].find((r) => r.querySelector('.lbl').textContent === 'u_add - adder').querySelector('.meta').textContent), '(adder.v)');
  // the files
  assert.equal(await readWs(env, 'Conv_v', 'src/adder.v'), '`timescale 1ns / 1ps\n`define WORD 8\nmodule adder #(parameter N = 4) (input [N-1:0] a, b, output [N:0] s);\n  assign s = a + b;\nendmodule\n');
  const gen = await readWs(env, 'Conv_v', 'src/proc.v');
  assert.match(gen, /^\/\/ Generated by Silinx from proc\.sch\.json/);
  assert.match(gen, /^ {2}\/\/ REG_3: HDL block \(always\)$/m);
  assert.equal(JSON.parse(await readWs(env, 'Conv_v', 'src/proc.sch.json')).generatedFile, 'src/proc.v');
  assert.deepEqual((await env.server.api('GET', '/api/projects/Conv_v')).files.map((f) => `${f.path}:${f.role}`).sort(), ['sim/tb_proc.v:sim', 'src/adder.v:design', 'src/proc.v:design']);
  // the console
  assert.deepEqual((await linesFrom(page, /^'proc' converted/)).slice(0, 2), [
    "'proc' converted to the schematic src/proc.sch.json (2 symbols drawn, 6 HDL blocks keeping the HDL that is not drawn): it is now the module's base, src/proc.v generated from it.",
    'The other design units of src/proc.v moved to src/adder.v.',
  ]);
  assert.doesNotMatch(await page.consoleText(), /WARNING|ERROR/);
});

uiTest('Convert to Schematic of a VHDL module whose file holds its package: the package stays, the module in a file of its own; a module that does not elaborate is refused (English, Portuguese)', E, async (page) => {
  const c = CASES.find((x) => x.name === 'vhdl-pkg-same-file');
  const bad = 'library ieee; use ieee.std_logic_1164.all;\nentity bad is port (a : in std_logic; y : out std_logic); end bad;\narchitecture rtl of bad is begin y <= a and nosuch; end rtl;\n';
  await makeProject(env, { name: 'Conv_vhd', files: { ...c.files, 'src/bad.vhd': bad }, top: 'alu_mem', simTop: 'tb_alu' });
  await page.openProject('Conv_vhd');
  await convert(page, 'alu_mem');
  await page.waitFor(() => window.Silinx.hdlToSch?.['src/alu_mem.vhd'] === 'src/alu_mem.sch.json', [], { what: 'converted, linked', timeout: 20000 });
  await page.waitFor(() => [...document.querySelectorAll('#hier .row')].some((r) => r.querySelector('.lbl').textContent === 'alu_mem' && r.querySelector('.badge.base')?.textContent === 'Schematic'), [], { what: 'the [Schematic] badge' });
  assert.equal(await badgesOf(page, 'alu_mem'), '[Schematic*] [VHDL]');
  assert.match(await readWs(env, 'Conv_vhd', 'src/alu.vhd'), /^package alu_pkg is$/m);
  assert.doesNotMatch(await readWs(env, 'Conv_vhd', 'src/alu.vhd'), /entity alu_mem/);
  assert.match(await readWs(env, 'Conv_vhd', 'src/alu_mem.vhd'), /^-- Generated by Silinx from alu_mem\.sch\.json/);
  assert.deepEqual(await linesFrom(page, /^'alu_mem' converted/).then((l) => l.slice(0, 2)), [
    "'alu_mem' converted to the schematic src/alu_mem.sch.json (0 symbols drawn, 10 HDL blocks keeping the HDL that is not drawn): it is now the module's base, src/alu_mem.vhd generated from it.",
    "'alu_mem' taken out of src/alu.vhd into src/alu_mem.vhd: the other design units of that file stay there.",
  ]);
  // the package is listed as before
  assert.ok(await page.eval(() => [...document.querySelectorAll('#hier .row .lbl')].some((e) => e.textContent === 'alu_pkg')));
  // a module that does not elaborate: refused, nothing written
  await page.eval(() => window.SilinxApp.showLeftPage('design'));
  await convert(page, 'bad');
  await page.waitDialog('Convert to Schematic');
  assert.match(await page.eval(() => [...document.querySelectorAll('.dlg-overlay')].pop().querySelector('.msg-text').textContent), /^'bad' does not elaborate \(.*nosuch.*\): correct it first\.$/);
  await page.dialogButton('OK');
  await page.waitNoDialog();
  assert.equal(await exists('Conv_vhd', 'src/bad.sch.json'), false);
  // in Portuguese: the menu, the dialog
  await page.eval(async () => { (await import('/js/i18n.js')).setLanguage('pt'); });
  try {
    await page.treeRow('#hier', 'bad', { right: true, exact: true });
    await page.click('body > .menu-popup .mi', { text: 'Converter para Esquemático (editável)…' });
    await page.waitDialog('Converter para Esquemático');
    assert.match(await page.eval(() => [...document.querySelectorAll('.dlg-overlay')].pop().querySelector('.msg-text').textContent), /^'bad' não é elaborado \(.*nosuch.*\): corrija-o primeiro\.$/);
    await page.dialogButton('OK');
    await page.waitNoDialog();
  } finally {
    await page.eval(async () => { (await import('/js/i18n.js')).setLanguage('en'); });
  }
});

uiTest('#1809 Convert to Schematic of a Verilog module with an escaped internal wire (\\t[0] ): its assigns drawn as gates, the wire joining them and the always block', E, async (page) => {
  const v = String.raw`module esc (clk, \a[0] , \b[0] , \r[0] , \q[0] );
  input clk, \a[0] , \b[0] ;
  output \r[0] ;
  output reg \q[0] ;
  wire \t[0] ;
  assign \t[0]  = \a[0]  & ~\b[0] ;
  assign \r[0]  = \t[0]  | \b[0] ;
  always @(posedge clk) \q[0]  <= \t[0]  ^ \b[0] ;
endmodule
`;
  await makeProject(env, { name: 'Conv_esc', files: { 'src/esc.v': v }, top: 'esc' });
  await page.openProject('Conv_esc');
  await convert(page, 'esc');
  await page.waitFor(() => window.Silinx.hdlToSch?.['src/esc.v'] === 'src/esc.sch.json' && window.Silinx.active?.id === 'sch:src/esc.sch.json', [], { what: 'converted, linked, open', timeout: 20000 });
  assert.deepEqual((await linesFrom(page, /^'esc' converted/)).slice(0, 1), [
    "'esc' converted to the schematic src/esc.sch.json (2 symbols drawn, 1 HDL block keeping the HDL that is not drawn): it is now the module's base, src/esc.v generated from it.",
  ]);
  assert.doesNotMatch(await page.consoleText(), /WARNING|ERROR/);
  const doc = JSON.parse(await readWs(env, 'Conv_esc', 'src/esc.sch.json'));
  assert.deepEqual(doc.symbols.map((s) => s.type).sort(), ['and2b1', 'hdlblock', 'or2']);
  const t = netlist(doc).nets.find((n) => n.name === '\\t[0]');
  assert.deepEqual(t.endpoints.map((e) => `${doc.symbols.find((s) => s.id === e.sym).type}.${e.pin}`).sort(), ['and2b1.O', 'hdlblock.\\t[0]', 'or2.I0']);
  // the schematic open in its editor: the block's pin \t[0] drawn
  await page.waitFor(() => document.querySelector('.doc:not([hidden]) .sch-editor g.sym'), [], { what: 'the schematic drawn' });
  assert.ok(await page.eval(() => document.querySelector('.doc:not([hidden]) .sch-editor').textContent.includes('\\t[0]')), 'the pin \\t[0] drawn');
  assert.equal((await readWs(env, 'Conv_esc', 'src/esc.v')).match(/^ {2}wire \\t\[0\] ;$/gm)?.length, 1);
});
