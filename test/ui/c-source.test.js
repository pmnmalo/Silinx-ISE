// UI (#1531): a C source in the project (Silinx HLS): its HDL made in memory from its top function, so that it is a
// module of the project as a drawing without an HDL file is (#177): its Design row (the C the base, its HDL
// generated, read-only), the top, the RTL schematic, its HDL made again when the C is saved; New Source ▸ C Function
// (HLS) makes one from a template; Portuguese; both interfaces. No warnings.
import { before, after } from 'node:test';
import assert from 'node:assert/strict';
import { setupUi, uiTest, makeProject } from './harness.js';
import { pickSourceType, waitNewSourcePage } from './new-source-helpers.js';

let env;
before(async () => { env = await setupUi(); });
after(async () => { await env?.teardown?.(); });
const E = () => env;

const SRC = `#include "ap_int.h"
int mac(ap_int<8> a, ap_int<8> b, int *acc) {
  int p = a * b;
  *acc = *acc + p;
  return p;
}
`;
const row = (page, name) => page.eval((n) => {
  const r = [...document.querySelectorAll('#hier .row')].find((x) => x.querySelector('.lbl')?.textContent.trim() === n);
  return r ? { badges: [...r.querySelectorAll('.badge')].map((b) => `${b.textContent}${b.classList.contains('base') ? '*' : ''}`), meta: r.querySelector('.meta')?.textContent } : null;
}, name);

uiTest('#1531 Silinx HLS: a .c file a module of the project (its Design row, its HDL generated and read-only, the top, the RTL schematic, made again on a save); New Source ▸ C Function (HLS); Portuguese', E, async (page) => {
  await makeProject(env, { name: 'CMod', top: '', files: { 'src/mac.c': SRC } });
  await page.openProject('CMod');
  await page.leftTab('design');
  // the module, from its top function: the C its base, its VHDL generated
  await page.waitFor(() => window.SilinxApp.S.modules.some((m) => m.name === 'mac'), [], { what: 'the module mac' });
  assert.deepEqual(await row(page, 'mac'), { badges: ['C*', 'VHDL'], meta: '(mac.c)' });
  assert.deepEqual(await page.eval(() => window.SilinxApp.S.lib.modules.get('mac').ports.map((p) => p.name)),
    ['ap_start', 'ap_done', 'ap_idle', 'ap_ready', 'a', 'b', 'acc_i', 'acc_o', 'acc_o_ap_vld', 'ap_return']);
  // its VHDL, read-only, from the badge
  await page.click('#hier .row .badge', { text: 'VHDL' });
  await page.waitFor(() => window.Silinx.active?.id === 'chdl:src/mac.c' && window.Silinx.active.editor, [], { what: 'the generated VHDL' });
  const doc = await page.eval(() => ({ ro: window.Silinx.active.editor.view.state.readOnly, text: window.Silinx.active.editor.getValue(), banner: document.querySelector('.doc:not([hidden]) .gen-banner')?.textContent }));
  assert.equal(doc.ro, true);
  assert.match(doc.text, /^-- Generated by Silinx from mac\.c/);
  assert.match(doc.text, /entity mac is/);
  assert.equal(doc.banner, 'Read-only, generated from mac.c');
  // the C from its badge; the top; its RTL schematic
  await page.click('#hier .row .badge', { text: 'C' });
  await page.waitFor(() => window.Silinx.active?.id === 'file:src/mac.c', [], { what: 'the C' });
  await page.eval(() => window.SilinxApp.setTop('mac', false));
  await page.waitFor(() => window.Silinx.project.top === 'mac');
  await page.eval(() => window.SilinxApp.openSchematic ? window.SilinxApp.openSchematic('mac') : import('/js/viewers.js').then((v) => v.openSchematic('mac')));
  await page.waitFor(() => /^rtl:/.test(window.Silinx.active?.id || ''), [], { what: 'the RTL schematic', timeout: 30000 });
  // the C edited and saved: its module made again (a renamed function, a new port)
  await page.eval(() => window.SilinxApp.openFile('src/mac.c'));
  await page.waitFor(() => window.Silinx.active?.id === 'file:src/mac.c' && window.Silinx.active.editor);
  await page.eval(() => { const ed = window.Silinx.active.editor; ed.setValue(ed.getValue().replace('int mac(ap_int<8> a, ap_int<8> b, int *acc)', 'int mac2(ap_int<8> a, ap_int<8> b, ap_int<8> c, int *acc)').replace('a * b', 'a * b + c')); });
  await page.eval(() => window.SilinxApp.saveAll());
  await page.waitFor(() => window.SilinxApp.S.modules.some((m) => m.name === 'mac2') && !window.SilinxApp.S.modules.some((m) => m.name === 'mac'), [], { what: 'mac2 made again' });
  assert.ok((await page.eval(() => window.SilinxApp.S.lib.modules.get('mac2').ports.map((p) => p.name))).includes('c'));
  // New Source ▸ C Function (HLS): a .c from the template, a module at once, opened in the editor
  await page.menu('Project', 'New Source…');
  await page.waitDialog('New Source Wizard');
  await pickSourceType(page, 'C Function (HLS)');
  await page.dialogButton('Next >');
  await waitNewSourcePage(page, 'File Name and Location');
  await page.fill('.dlg-overlay .wiz-main input[type=text]', 'adder4');
  await page.dialogButton('Next >');
  await waitNewSourcePage(page, 'Summary');
  await page.dialogButton('Finish');
  await page.waitNoDialog();
  await page.waitFor(() => window.Silinx.project && window.SilinxApp.S.fileTree.includes('src/adder4.c') && window.SilinxApp.S.modules.some((m) => m.name === 'adder4'), [], { what: 'adder4.c and its module' });
  await page.waitFor(() => window.Silinx.active?.id === 'file:src/adder4.c', [], { what: 'adder4.c opened' });
  assert.match(await page.eval(() => window.Silinx.active.editor.getValue()), /void adder4\(ap_uint<4> a, ap_uint<4> b, ap_uint<5> \*sum, bool \*carry\)/);
  // in Portuguese: the type in New Source
  await page.eval(async () => (await import('/js/i18n.js')).setLanguage('pt'));
  await page.menu('Projeto', 'Nova Fonte…');
  await page.waitDialog();
  assert.ok((await page.eval(() => [...document.querySelectorAll('.dlg-overlay .src-types .st')].map((e) => e.lastChild.textContent.trim()))).includes('Função C (HLS)'));
  await page.eval(() => document.querySelector('.dlg-overlay .dlg-x').click());
  await page.eval(async () => (await import('/js/i18n.js')).setLanguage('en'));
  assert.deepEqual(page.console.filter((c) => c.type === 'warning' || c.type === 'warn' || c.type === 'error').map((c) => c.text), []);
});
