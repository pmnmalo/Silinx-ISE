// place a symbol and return helpers to get its (sheet) pin positions
function sym(doc, type, x, y, params = {}, name, extra = {}) {
  const s = { id: `S${doc.symbols.length + 1}`, type, x, y, rot: 0, mirror: false, name: name || `U${doc.symbols.length + 1}`, params: { ...params }, ...extra };
  doc.symbols.push(s);
  return s;
}
const pinAt = (doc, s, pin, modules) => { const p = symbolPins(normalizeDoc({ ...doc, symbols: [s] }).symbols[0], modules).find(q => q.name === pin); assert.ok(p, `pin ${pin} of ${s.type}`); return { x: p.x, y: p.y }; };
let wid = 0;
const wire = (doc, ...pts) => doc.wires.push({ id: `W${++wid}`, points: pts.map(p => ({ ...p })) });
const port = (doc, name, dir, x, y, width = 1, type) => { const p = { id: `P${doc.ports.length + 1}`, name, dir, width, x, y }; if (type) p.type = type; doc.ports.push(p); return p; };
// orthogonal wire between two points (horizontal first)
const conn = (doc, a, b, mx = Math.round((a.x + b.x) / 20) * 10) => { if (a.y === b.y || a.x === b.x) wire(doc, a, b); else wire(doc, a, { x: mx, y: a.y }, { x: mx, y: b.y }, b); };

function runSim(files, top, until = 5e6) {
  const srcs = Object.entries(files).map(([path, text]) => ({ path, text }));
  const r = simulate(srcs, top, { until });
  assert.deepEqual(r.errors.map(e => `${e.file}:${e.line} ${e.message}`), [], 'compile/elaboration errors');
  return r;
}
// waveform of each signal of the testbench instance, deltas collapsed
function waves(r) {
  const out = {};
  const inst = r.design.top;
  for (const s of [...inst.signals, ...inst.ports.map(p => p.sig)]) {
    if (!s.wave) continue;
    const pts = [];
    for (let i = 0; i < s.wave.t.length; i++) {
      const t = s.wave.t[i], v = V.toBin(s.wave.v[i]);
      if (pts.length && pts[pts.length - 1][0] === t) pts[pts.length - 1][1] = v;
      else pts.push([t, v]);
    }
    const dedup = pts.filter((p, i) => i === 0 || p[1] !== pts[i - 1][1]);
    out[s.name] = dedup.map(([t, v]) => `${t}:${v}`).join(' ');
  }
  return out;
}
const logOf = r => r.sim.log.map(l => `${l.kind}:${l.text}`);

// HDL -> schematic -> HDL, then simulate both designs with the same testbench
async function roundTrip({ files, module, file, tb, until = 5e6, lang, cutModule, minSymbols = 1, expect }) {
  const srcs = Object.entries(files).map(([path, text]) => ({ path, text }));
  const lib = compile(srcs);
  const d = elaborate(lib, module);
  assert.deepEqual(d.diags.filter(x => x.severity === 'error'), []);
  const modules = modulesFromLibrary(lib, { sources: files });
  const doc = await schematicFromHdl(d.top, { sources: files, modules });
  assert.ok(doc.symbols.length >= minSymbols);
  // the imported schematic is self-consistent
  const nl = netlist(doc, { modules });
  assert.deepEqual(nl.diagnostics.filter(x => x.severity === 'error').map(x => x.message), []);
  if (expect) expect(doc, nl);
  // JSON round trip of the document itself
  const doc2 = normalizeDoc(JSON.parse(JSON.stringify(doc)));
  const gen = generateHdl(doc2, { lang, modules });
  assert.deepEqual(gen.diagnostics.filter(x => x.severity === 'error').map(x => x.message), []);
  assert.match(gen.code, /Generated by XAIlinx from .*\.sch\.json — kept in sync with the schematic/);
  // regenerated sources: replace the module
  const regen = { ...files };
  if (cutModule) regen[file] = files[file].replace(new RegExp(`module\\s+${module}\\b[\\s\\S]*?endmodule`), '');
  else delete regen[file];
  regen[`gen/${gen.filename}`] = gen.code;
  // the generated design parses and elaborates cleanly
  const lib2 = compile(Object.entries(regen).map(([path, text]) => ({ path, text })));
  assert.deepEqual(lib2.errors.filter(e => e.severity === 'error').map(e => `${e.file}:${e.line} ${e.message}`), [], gen.code);
  const d2 = elaborate(lib2, module);
  assert.deepEqual(d2.diags.filter(e => e.severity === 'error').map(e => e.message), [], gen.code);
  // simulate both
  const a = runSim(files, tb, until), b = runSim(regen, tb, until);
  const wa = waves(a), wb = waves(b);
  assert.ok(Object.keys(wa).length > 0);
  assert.ok(Object.values(wa).some(w => w.split(' ').length > 4), 'testbench produces activity');
  assert.deepEqual(wb, wa, `waveforms differ for ${module}\n${gen.code}`);
  assert.deepEqual(logOf(b), logOf(a));
  return { doc, gen, a, b };
}

// ------------------------------------------------------------------ netlist
test('netlist: pins, T-junctions, labels and I/O markers', () => {
  const doc = newDoc('nl', 'vhdl');
  const g = sym(doc, 'and2', 200, 100);
  const n = sym(doc, 'inv', 400, 110);
  port(doc, 'a', 'in', 100, 110);
  port(doc, 'b', 'in', 100, 300);
  port(doc, 'y', 'out', 600, 120);
  const I0 = pinAt(doc, g, 'I0'), I1 = pinAt(doc, g, 'I1'), O = pinAt(doc, g, 'O');
  conn(doc, { x: 100, y: 110 }, I0);
  // b goes to I1 through a T-junction on a vertical wire
  wire(doc, { x: 100, y: 300 }, { x: 150, y: 300 }, { x: 150, y: 200 });
  wire(doc, { x: 150, y: 200 }, { x: 150, y: 130 }, I1);
  conn(doc, O, pinAt(doc, n, 'I'));
  // inverter output: wire with a label "nx", the output marker is connected through another label "nx"
  const nO = pinAt(doc, n, 'O');
  wire(doc, nO, { x: nO.x + 40, y: nO.y });
  doc.labels.push({ id: 'L1', x: nO.x + 20, y: nO.y, net: 'nx' });
  wire(doc, { x: 560, y: 120 }, { x: 600, y: 120 });
  doc.labels.push({ id: 'L2', x: 570, y: 120, net: 'nx' });
  // dangling wire + an unconnected label
  wire(doc, { x: 800, y: 800 }, { x: 900, y: 800 });
  const nl = netlist(doc);
  const pn = (s, p) => nl.pinNet.get(`${s.id}/${p}`);
  assert.equal(pn(g, 'I0').name, 'a');
  assert.equal(pn(g, 'I1').name, 'b');
  assert.equal(pn(n, 'I'), pn(g, 'O'));
  assert.ok(pn(n, 'I').auto);
  assert.equal(pn(n, 'O').name, 'y', 'label joins the output marker net (marker name wins)');
  assert.ok(nl.diagnostics.some(d => /dangling/.test(d.message)));
  assert.ok(nl.diagnostics.some(d => /also named 'nx'/.test(d.message)));
  // T junction: one dot where three branches meet? (b wire corner is a 2-way corner, not a junction)
  assert.equal(nl.junctions.length, 0);
});

test('netlist: multiple drivers, width mismatch, unconnected input, junction dots', () => {
  const doc = newDoc('nl2', 'verilog');
  const a = sym(doc, 'inv', 100, 100);
  const b = sym(doc, 'inv', 100, 200);
  const c = sym(doc, 'buf', 300, 300, { width: 4 });
  const oa = pinAt(doc, a, 'O'), ob = pinAt(doc, b, 'O');
  wire(doc, oa, { x: 200, y: oa.y }, { x: 200, y: ob.y }, ob);
  wire(doc, { x: 200, y: 150 }, { x: 250, y: 150 });   // T on the vertical part
  const ci = pinAt(doc, c, 'I');
  wire(doc, { x: 250, y: 150 }, { x: 250, y: ci.y }, ci);
  const nl = netlist(doc);
  const msgs = nl.diagnostics.map(d => d.message).join('\n');
  assert.match(msgs, /has 2 drivers/);
  assert.match(msgs, /width mismatch/);
  assert.match(msgs, /input pin I of U1 .* not connected/);
  assert.equal(nl.pinNet.get(`${a.id}/O`), nl.pinNet.get(`${c.id}/I`));
  assert.deepEqual(nl.junctions, [{ x: 200, y: 150 }]);
});

test('netlist: rotation and mirroring move the pins', () => {
  const s = normalizeDoc({ symbols: [{ id: 'S1', type: 'and2', x: 100, y: 100, rot: 90 }] }).symbols[0];
  const pins = symbolPins(s);
  const def = symbolDef(s);
  // rotated 90° clockwise: inputs on top, output at the bottom
  assert.ok(pins.filter(p => p.dir === 'in').every(p => p.y === 100 && p.side === 'N'));
  assert.equal(pins.find(p => p.name === 'O').y, 100 + def.w);
  const m = normalizeDoc({ symbols: [{ id: 'S1', type: 'and2', x: 0, y: 0, mirror: true }] }).symbols[0];
  assert.equal(symbolPins(m).find(p => p.name === 'O').x, 0);
  assert.equal(symbolPins(m).find(p => p.name === 'O').side, 'W');
});

