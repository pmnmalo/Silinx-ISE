test('schematicFromHdl uses a supplied ELK-style layout function', async () => {
  const files = { 'glv.vhd': GATES_VHD.split('library ieee; use ieee.std_logic_1164.all; use ieee.numeric_std.all;\nentity tb_glv')[0] };
  const lib = compile([{ path: 'glv.vhd', text: files['glv.vhd'] }]);
  const d = elaborate(lib, 'glv');
  let called = 0;
  // fake layout: place nodes in a diagonal, no routes (forces the fallback for wires)
  const layout = async g => { called++; return { children: g.children.map((c, i) => ({ id: c.id, x: 100 + i * 150, y: 100 + i * 90 })), edges: [] }; };
  const doc = await schematicFromHdl(d.top, { sources: files, layout });
  assert.equal(called, 1);
  const nl = netlist(doc);
  assert.deepEqual(nl.diagnostics.filter(x => x.severity === 'error').map(x => x.message), []);
  const g = generateHdl(doc);
  assert.deepEqual(g.diagnostics.filter(x => x.severity === 'error'), []);
});

