function gateDoc(lang) {
  // y = (a and b) or not c ; z = a xor b (4-bit buses through a mux)
  const doc = newDoc('gates', lang);
  const and = sym(doc, 'and2', 200, 100);
  const inv = sym(doc, 'inv', 200, 200);
  const or = sym(doc, 'or2', 400, 120);
  const mx = sym(doc, 'mux2', 400, 300, { width: 4 });
  port(doc, 'a', 'in', 100, 110); port(doc, 'b', 'in', 100, 130); port(doc, 'c', 'in', 100, 210);
  port(doc, 'd0', 'in', 100, 320, 4); port(doc, 'd1', 'in', 100, 340, 4);
  port(doc, 'y', 'out', 600, 140); port(doc, 'q', 'out', 600, 330, 4);
  conn(doc, { x: 100, y: 110 }, pinAt(doc, and, 'I0'));
  conn(doc, { x: 100, y: 130 }, pinAt(doc, and, 'I1'));
  conn(doc, { x: 100, y: 210 }, pinAt(doc, inv, 'I'));
  conn(doc, pinAt(doc, and, 'O'), pinAt(doc, or, 'I0'));
  conn(doc, pinAt(doc, inv, 'O'), pinAt(doc, or, 'I1'));
  conn(doc, pinAt(doc, or, 'O'), { x: 600, y: 140 });
  conn(doc, { x: 100, y: 320 }, pinAt(doc, mx, 'D0'));
  conn(doc, { x: 100, y: 340 }, pinAt(doc, mx, 'D1'));
  conn(doc, pinAt(doc, mx, 'O'), { x: 600, y: 330 });
  // select = the 'or' output via a label
  const s = pinAt(doc, mx, 'S0');
  wire(doc, s, { x: s.x, y: s.y + 30 });
  doc.labels.push({ id: 'L1', x: s.x, y: s.y + 30, net: 'y' });
  return doc;
}

