test('new_project, new_project_from_example and new_source on the 7-series: XDC files; the XDC Wizard', async () => {
  const e = await ok('new_project', { name: 'a7', board: 'nexys-a7' });
  assert.match(e.text, /^Empty project 'a7' made: nexys-a7 \(xc7a100tcsg324-1\)\. /);
  assert.deepEqual([(await P.readProject('a7')).constraints, (await P.readProject('a7')).device.family], ['constraints/top.xdc', 'artix7']);
  const ex = await ok('new_project_from_example', { name: 'v3', example: 'vga', board: 'basys3' });
  assert.match(ex.text, /^Project 'v3' made from the example vga: top vga, basys3 \(xc7a35tcpg236-1\)\. /);
  const dir = P.projectDir('v3');
  assert.deepEqual(fs.readdirSync(path.join(dir, 'constraints')), ['top.xdc']);
  assert.match(fs.readFileSync(path.join(dir, 'constraints/top.xdc'), 'utf8'), /\nset_property -dict \{ PACKAGE_PIN N19 IOSTANDARD LVCMOS33 \} \[get_ports \{vga_red\[2\]\}\]\n/);
  const s = await ok('new_source', { project: 'v3', type: 'constraints', name: 'extra' });
  assert.equal(s.text, 'Created Implementation Constraints File \'constraints/extra.xdc\'.');
  assert.match(fs.readFileSync(path.join(dir, 'constraints/extra.xdc'), 'utf8'), /^# Xilinx Design Constraints for v3\n# Target: xc7a35t-1-cpg236\n/);
  // (the XDC Wizard, #2296: the board's pins and their I/O standards, as the project's own)
  const w = await ok('constraints_wizard', { project: 'v3', module: 'vga', name: 'c2' });
  assert.match(w.text, /^XDC Wizard: created constraints\/c2\.xdc for vga: /);
  assert.match(fs.readFileSync(path.join(dir, 'constraints/c2.xdc'), 'utf8'), /^# XDC generated by the Silinx XDC Wizard for 'vga' \(xc7a35t-1-cpg236, Digilent Basys 3\)\n[\s\S]*\nset_property -dict \{ PACKAGE_PIN N19 IOSTANDARD LVCMOS33 \} \[get_ports \{vga_red\[2\]\}\]\n/);
  await fails('constraints_wizard', { project: 'v3', module: 'vga', name: 'c3', attributes: { 'vga_red<2>': { drive: '8' } } }, 'attributes: an XDC\'s are I/O Pin Planning\'s (write_file), not the wizard\'s');
});

// (#3146) the Silinx toolchain's 7-series back end, asked for (toolchain silinx): from HDL to the .bit as the interface runs
// it, its reports the Design Summary's; no trust needed (it runs in Silinx's own process, as the other open flows)
test('run_process with the Silinx toolchain on the Basys 3: synth_xilinx, nextpnr, the .bit from its FASM; the reports, the timing nextpnr\'s estimate', async () => {
  await ok('new_project_from_example', { name: 'o3', example: 'blinky', board: 'basys3' });
  const r = await ok('run_process', { project: 'o3', process: 'bitstream', toolchain: 'silinx' });
  assert.deepEqual([r.data.toolchain, r.data.ok, r.data.errors, r.data.warnings], ['silinx', true, [], []]);
  assert.match(r.text, /\nProcess "bitstream" of <top> completed successfully \(Silinx toolchain\)\.$/);
  assert.ok(r.data.log.some(l => /^Bitstream: build\/top\.bit \(\d+ bytes, from nextpnr's FASM on Project X-Ray's database\)$/.test(l)), r.data.log.join('\n'));
  assert.ok(fs.existsSync(path.join(P.projectDir('o3'), 'build/top.bit')));
  const par = await ok('get_report', { project: 'o3', report: 'par' });
  assert.match(par.text, /^Place and route \(Silinx toolchain\) of top: all signals are completely routed\.\nTiming constraints: all met; minimum period [\d.]+ ns \([\d.]+ MHz\), nextpnr's estimate \(optimistic against Vivado, #3146\)\.$/);
  const map = await ok('get_report', { project: 'o3', report: 'map' });
  assert.match(map.text, /\n {2}Number of bonded IOBs: 27 out of 106 25%\n/);
  const timing = await ok('get_report', { project: 'o3', report: 'timing' });
  assert.equal(timing.data.path, 'build/open/timing.txt');
  assert.match(timing.text, /^Timing of xc7a35tcpg236-1 after Place & Route: nextpnr's estimate .*\n.*\n\nClock clk: [\d.]+ MHz \([\d.]+ ns\), constraint 100 MHz: met\n/);
  // (a simulation model, which the 7-series flows do not make: refused before the back end, as simulate refuses it, #3707)
  await fails('run_process', { project: 'o3', process: 'post_par_model', toolchain: 'silinx' }, 'the Artix-7 flow makes no post-place & route simulation model (only the Spartan flows make them): simulate the behavioral model');
  // (AMD Vivado stays the project's own when no toolchain is asked: the project made through the MCP server, not trusted)
  const untrusted = 'project \'o3\' was made through the MCP server (by an assistant): AMD Vivado runs only once you trust it (Trust Project, in the console when the project opens)';
  await fails('run_process', { project: 'o3', process: 'synthesize' }, untrusted);
});

// (#3146, #2674: what Design Properties offers) the Artix-7's synthesis tool: AMD Vivado, its default, or the Silinx toolchain,
// whose 7-series back end its processes then run, as the interface's; Vivado not for another family
test('set_design_properties: the Artix-7\'s synthesis tool, vivado or silinx; run_process then runs the project\'s', async () => {
  await ok('new_project_from_example', { name: 'c3', example: 'gates', board: 'basys3' });
  const s = await ok('set_design_properties', { project: 'c3', synth_tool: 'silinx' });
  assert.equal(s.text, 'Device set to xc7a35t-1-cpg236 (board basys3); synthesis tool silinx.');
  const r = await ok('run_process', { project: 'c3', process: 'implement' });
  assert.deepEqual([r.data.toolchain, r.data.ok, r.data.warnings], ['silinx', true, []]);
  assert.match(r.text, /\nProcess "implement" of <gates> completed successfully \(Silinx toolchain\)\.$/);
  // (the choice kept when the board changes within the family; Vivado's again when asked)
  assert.equal((await ok('set_design_properties', { project: 'c3', board: 'nexys-a7' })).data.synthTool, 'silinx');
  assert.equal((await ok('set_design_properties', { project: 'c3', synth_tool: 'vivado' })).data.synthTool, 'vivado');
  // (another family: no Vivado; from the Artix-7's Vivado, the Silinx toolchain)
  await fails('set_design_properties', { project: 'c3', board: 'basys2', synth_tool: 'vivado' }, 'AMD Vivado implements the Artix-7 devices, not the XC3S250E');
  assert.equal((await ok('set_design_properties', { project: 'c3', board: 'basys2' })).data.synthTool, 'silinx');
});
