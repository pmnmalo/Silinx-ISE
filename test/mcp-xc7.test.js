// The MCP server on the 7-series' boards (#3142, #2674: what the interface does): list_devices marks the experimental
// family and its boards, set_design_properties makes the constraints an XDC and says no flow runs it yet, new_project and
// new_source write XDC, and the processes are refused with the interface's message; every result's text.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { scratchEnv } from './server-helpers.js';

let tmp;
before(async () => { tmp = await scratchEnv('silinx-mcp-xc7-'); });
after(() => fs.rmSync(tmp, { recursive: true, force: true }));

const { handle } = await import('../server/mcp.js');
const P = await import('../server/projects.js');
let id = 0;
async function call(name, args = {}) {
  const r = (await handle({ jsonrpc: '2.0', id: ++id, method: 'tools/call', params: { name, arguments: args } })).result;
  return { text: r.content[0].text, data: r.structuredContent, isError: r.isError };
}
const ok = async (name, args) => { const r = await call(name, args); assert.equal(r.isError, false, r.text); return r; };
const fails = async (name, args, message) => { const r = await call(name, args); assert.equal(r.isError, true); assert.equal(r.text, `${name}: ${message}`); };

test('list_devices: the Basys 3 and the Nexys A7, Artix-7 and its XC7A35T, marked experimental; the others not', async () => {
  const all = await ok('list_devices');
  assert.match(all.text, /\n {2}basys3: Digilent Basys 3 \(xc7a35tcpg236-1\) \[experimental: no implementation flow yet\]\n {2}nexys-a7: Digilent Nexys A7 \(xc7a100tcsg324-1\) \[experimental: no implementation flow yet\]\n/);
  assert.match(all.text, /\n {2}Artix-7 \(artix7\) \[experimental: no implementation flow yet\]:\n {4}xc7a35t: cpg236 -1 -2 -3, csg324 -1 -2 -3\n {4}xc7a100t: /);
  assert.deepEqual(all.data.boards.find(b => b.id === 'basys3'), { id: 'basys3', name: 'Digilent Basys 3', device: 'xc7a35tcpg236-1', experimental: true, variants: [] });
  assert.deepEqual(all.data.boards.filter(b => b.experimental).map(b => b.id), ['basys3', 'nexys-a7']);
  assert.deepEqual(all.data.families.filter(f => f.experimental).map(f => f.id), ['artix7']);
  assert.ok(!/basys2.*experimental|Spartan-3E.*experimental/.test(all.text));
  const a7 = await ok('list_devices', { family: 'artix7' });
  assert.deepEqual(a7.data.families.map(f => [f.id, f.experimental]), [['artix7', true]]);
});

test('set_design_properties: the Basys 3, its pins written as an XDC, the example\'s UCF not converted, no flow yet', async () => {
  await ok('new_project_from_example', { name: 'b1', example: 'blinky' });
  const r = await ok('set_design_properties', { project: 'b1', board: 'basys3', update_constraints: true });
  // (no "no flow" warning: the Artix-7 is AMD Vivado's, #1649)
  const warnings = ['WARNING: this device\'s constraints are XDC: constraints/top.xdc is the project\'s now, constraints/top.ucf was not converted.'];
  assert.equal(r.text, `${warnings[0]}\nDevice set to xc7a35t-1-cpg236 (board basys3); synthesis tool vivado; constraints/top.xdc written from the basys3's pins.`);   // (AMD Vivado the Artix-7's default, #3146)
  assert.deepEqual(r.data.warnings, warnings);
  assert.deepEqual([r.data.constraints, r.data.synthTool], ['constraints/top.xdc', 'vivado']);
  const pj = await P.readProject('b1');
  assert.deepEqual(pj.device, { family: 'artix7', part: 'xc7a35t', package: 'cpg236', speed: '-1' });
  const xdc = fs.readFileSync(path.join(P.projectDir('b1'), 'constraints/top.xdc'), 'utf8');
  assert.match(xdc, /^# XDC for top 'top' on Digilent Basys 3 \(xc7a35t-1-cpg236\), generated by Silinx\n\nset_property -dict \{ PACKAGE_PIN W5 IOSTANDARD LVCMOS33 \} \[get_ports \{clk\}\]\n/);
  assert.match(xdc, /\ncreate_clock -add -name clk -period 10\.000 -waveform \{0\.000 5\.000\} \[get_ports \{clk\}\]\n/);
  assert.match(xdc, /\nset_property CFGBVS VCCO \[current_design\]\n/);
  // no XST on it; its processes AMD Vivado's (#1649), which waits until the user trusts the project an assistant made
  await fails('set_design_properties', { project: 'b1', synth_tool: 'xst' }, 'the XC7A35T is implemented by AMD Vivado: no XST');
  const untrusted = 'project \'b1\' was made through the MCP server (by an assistant): AMD Vivado runs only once you trust it (Trust Project, in the console when the project opens)';
  await fails('run_process', { project: 'b1', process: 'synthesize' }, untrusted);
  await fails('run_process', { project: 'b1', process: 'bitstream' }, untrusted);
  // back to the Basys2: its constraints a UCF again, the XDC not converted, no warning of the 7-series
  const back = await ok('set_design_properties', { project: 'b1', board: 'basys2' });
  assert.equal(back.text, 'WARNING: this device\'s constraints are UCF: constraints/top.ucf is the project\'s now, constraints/top.xdc was not converted.\nDevice set to xc3s250e-4-cp132 (board basys2); synthesis tool silinx.');
});

