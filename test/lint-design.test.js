// The later rules of the design checks (#405: core/lint-design.js out of designChecks in core/lint.js), on a design
// made to break each of them: a combinational loop, an unused input, a signal used but never assigned, two names
// differing only in case, a clock made by logic and a clock read as data, a blocking assignment in a clocked block
// (Verilog), an integer without a range (VHDL): their findings, exactly.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { compile, elaborate } from '../core/compile.js';
import { designChecks } from '../core/lint.js';
import { mountDesignRules } from '../core/lint-design.js';

const VERILOG = `module top(input clk, input en, input spare, input [3:0] d, output reg q, output y, output z, output y2);
  wire a, b;
  assign a = b & en;
  assign b = a | d[0];
  assign y = a;
  wire unused_w;
  reg r;
  wire w2;
  assign y2 = w2;
  wire gclk = clk & en;
  always @(posedge gclk) r = d[1];
  always @(posedge clk) q <= r;
  wire Name, name;
  assign Name = d[2]; assign name = d[3];
  assign z = Name ^ name;
endmodule`;
const VHDL = `library ieee; use ieee.std_logic_1164.all;
entity t is port (clk : in std_logic; o : out std_logic); end;
architecture r of t is signal n : integer; signal u : std_logic; begin
  process (clk) begin if rising_edge(clk) then n <= n + 1; end if; end process;
  o <= '1' when n = 3 else '0';
end;`;

const findings = (lang, text, top, path, o) => {
  const lib = compile([{ path, lang, text }]);
  return designChecks(lib, elaborate(lib, top), o).map(f => `${f.check} ${f.severity} ${f.line}: ${f.message}`);
};

test('#405 design checks, the later rules: the module\'s mount', () => {
  assert.equal(typeof mountDesignRules, 'function');
});

test('#405 design checks, the later rules: each one found, exactly (Verilog)', () => {
  assert.deepEqual(findings('verilog', VERILOG, 'top', 't.v'), [
    'comb-loop warning 3: Unit <top> : the following signal(s) form a combinatorial loop: <a>, <b>.',
    'unused-input warning 1: Input <spare> is never used.',
    'unassigned-signal warning 8: Signal <w2> is used but never assigned. This sourceless signal will be automatically connected to value GND.',
    'name-case warning 13: Name conflict (<name> and <Name>, renaming name as name_rnm0)',
    'data-as-clock warning 11: Signal <gclk> is used as a clock but it is generated by logic (line 10), not by a clock input.',
    'clock-as-data warning 10: Clock signal <clk> is used as data (in logic), not only as a clock edge.',
    'blocking warning 11: Blocking assignment (=) to <r> in a clocked always block; use a non-blocking assignment (<=).',
  ]);
});

test('#405 design checks, the later rules: an integer without a range (VHDL)', () => {
  assert.deepEqual(findings('vhdl', VHDL, 't', 't.vhd'), ['integer-range info 3: Signal <n> is an integer without a range: synthesis makes it 32 bits wide.']);
});

// #1759: the HDL Silinx HLS makes of a C source is elaborated under the C file's name; its design checks (registers
// synthesis trims: a delay line's last element, the loops' variables) are not said there: their lines are the HDL's,
// not the C's, and the C's author cannot act on them
test('#1759 a C source\'s HDL: no design check warnings under the C file\'s name (its lines are the HDL\'s)', async () => {
  const { viewHdl } = await import('../core/view-hdl.js');
  const { compile, elaborate } = await import('../core/compile.js');
  const { designChecks } = await import('../core/lint.js');
  const c = 'int fir(int x) {\n  static int d[4];\n  int y = 0;\n  for (int i = 3; i > 0; i--) {\n#pragma HLS UNROLL\n    d[i] = d[i - 1];\n  }\n'
    + '  d[0] = x;\n  for (int i = 0; i < 4; i++) {\n#pragma HLS UNROLL\n    y += (i + 1) * d[i];\n  }\n  return y;\n}\nint main(void) { return fir(1) == 1 ? 0 : 1; }\n';
  const h = viewHdl('src/fir.c', c);
  const lib = compile([{ path: h.path, text: h.text, lang: h.lang }]);
  const d = elaborate(lib, h.module);
  assert.deepEqual([h.module, lib.errors, d.diags], ['fir', [], []]);
  assert.deepEqual(designChecks(lib, d, { lint: true }), []);
  // (the same HDL under an HDL file's name: its checks said, as for any HDL)
  const lib2 = compile([{ path: 'src/fir.vhd', text: h.text, lang: h.lang }]);
  assert.ok(designChecks(lib2, elaborate(lib2, h.module), { lint: true }).some((x) => /Signal <ap_r_d_3> is assigned but never used/.test(x.message)));
});

// #2716: the feedback of a Clocking Wizard module feeds the primitive's input (a DCM_SP's CLKFB, a PLL_BASE's CLKFBIN),
// which its simulation model does not read: it is used, no "assigned but never used"
test('#2716 a signal that only feeds a primitive\'s input is used: the Clocking Wizard\'s feedback, in VHDL and in Verilog', async () => {
  const { clockModule } = await import('../core/clocking.js');
  const { primitiveSources } = await import('../core/unisim.js');
  const base = { wizard: 'clock', version: 1, inMHz: 50, input: 'clk_in', ibufg: true, reset: 'rst', locked: 'locked' };
  const specs = [
    // a DCM with no CLK0 output: its CLK0 only the feedback (the case that warned)
    { ...base, family: 'spartan3e', speed: '-4', div2: false, phaseShift: 0, outputs: [{ pin: 'CLKFX', port: 'f', mhz: 100 }] },
    { ...base, family: 'spartan3e', speed: '-4', div2: false, phaseShift: 0, outputs: [{ pin: 'CLK2X', port: 'fast' }] },
    // a PLL: its CLKFBOUT to CLKFBIN
    { ...base, family: 'spartan6', speed: '-3', inMHz: 100, outputs: [{ port: 'c200', mhz: 200, phase: 0 }] },
  ];
  for (const s of specs) {
    for (const lang of ['vhdl', 'verilog']) {
      const spec = { ...s, name: 'clkgen', lang };
      const { code } = clockModule(spec);
      assert.ok(code, `${s.family} ${lang}`);
      const srcs = [{ path: `src/clkgen.${lang === 'vhdl' ? 'vhd' : 'v'}`, lang, text: code }];
      const lib = compile([...primitiveSources(srcs), ...srcs]);
      const d = elaborate(lib, 'clkgen');
      assert.deepEqual(designChecks(lib, d, { lint: true }).map(x => x.message), [], `${s.family} ${lang} ${s.outputs[0].pin || s.outputs[0].port}`);
    }
  }
});

test('#2716 a signal no primitive and no process reads is still unused', () => {
  const lib = compile([{ path: 'a.v', lang: 'verilog', text: 'module a(input clk, output q);\n  wire w;\n  assign w = clk;\n  assign q = clk;\nendmodule\n' }]);
  assert.deepEqual(designChecks(lib, elaborate(lib, 'a'), { lint: true }).map(x => x.message), ['Signal <w> is assigned but never used. This unconnected signal will be trimmed during the optimization process.']);
});
