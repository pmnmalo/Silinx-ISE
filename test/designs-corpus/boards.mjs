#!/usr/bin/env node
// Board versions of designs of the corpus (test/designs-corpus/manifest.json) for the Digilent
// Basys2-250: a top of our own (test/designs-corpus/boards/*.v) around the fetched design, the
// board's pins (server/devices.js basys2), its testbench in Silinx's simulator when it has one, and
// the fully open flow (research/s3e-route/open-flow.mjs: no Xilinx tool) to a bitstream.
//
//   node test/designs-corpus/boards.mjs <projects dir> [<bit dir>] [--filter name]
//
// writes one Silinx project per board design into <projects dir> and, with <bit dir>, runs the
// open flow and copies <name>.bit there. A design with cells the packer does not support yet (SERV's
// register file: block or distributed RAM) is synthesized with synth_xilinx options that avoid them
// (synthFlags) into <project>/netlist.json, given to the open flow with --json. The check against
// ISE (scripts/check-open-flow.mjs) takes the same projects, with `--json <project>/netlist.json`
// after those that have one (printed at the end).
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { BOARDS } from '../../server/devices.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..', '..');

// each board design: the corpus design it wraps, its top (boards/<file>), its ports on the board's
// resources (port -> [resource, first bit, count]), what to look for on the board
export const BOARD_DESIGNS = [
  { name: 'corpus-int2float', design: 'epfl-int2float', top: 'int2float_basys2', file: 'boards/int2float_basys2.v',
    pins: { sw: ['sw', 0, 8], btn: ['btn', 0, 3], led: ['led', 0, 8] },
    look: 'LD3..LD0 show the mantissa and LD6..LD4 the exponent of the 11-bit integer {BTN2, BTN1, BTN0, SW7..SW0} as a 7-bit float; LD7 is on. All switches off: only LD7; SW0 alone: LD0 (mantissa 1); SW7 alone (128): LD6 and LD3 (exponent 4, mantissa 8); BTN2 held (1024): LD6..LD3 (exponent 7, mantissa 8).' },
  { name: 'corpus-prbs', design: 'verilog-lfsr-prbs', top: 'prbs_basys2', file: 'boards/prbs_basys2.v',
    pins: { mclk: ['mclk', 0, 1], reset: ['btn', 0, 1], freeze: ['sw', 0, 1], led: ['led', 0, 8] }, clock: 'mclk',
    look: 'LD7..LD0 change to a new pseudo-random pattern about 3 times a second; SW0 on freezes it; BTN0 restarts the sequence (the same patterns again in the same order).' },
  { name: 'corpus-spi', design: 'nandland-spi-verilog', top: 'spi_basys2', file: 'boards/spi_basys2.v',
    pins: { mclk: ['mclk', 0, 1], btn: ['btn', 0, 2], sw: ['sw', 0, 8], led: ['led', 0, 8] }, clock: 'mclk',
    look: 'LEDs off after configuration; set the switches and press BTN1: the byte goes out through the SPI master and comes back on MISO (looped to MOSI), and LD7..LD0 show it. Changing the switches without pressing BTN1 changes nothing; BTN0 is the SPI master\'s reset.' },
  { name: 'corpus-serv', design: 'serv', top: 'serv_basys2', file: 'boards/serv_basys2.v', synthFlags: '-nobram -nolutram -nosrl',
    tb: { top: 'serv_basys2_tb', file: 'boards/serv_basys2_tb.v', pass: /^PASS/, until: 5e9 },
    pins: { mclk: ['mclk', 0, 1], reset: ['btn', 0, 1], led: ['led', 0, 8] }, clock: 'mclk',
    look: 'the SERV RISC-V CPU runs its 8-instruction program: LD7..LD0 count in binary, about one step a second (LD0 toggles about every second); BTN0 held stops the CPU (reset), released the count starts again from 1.' },
];

/** The UCF of a board design: its ports on the Basys2's pins. */
export function boardUcf(bd, board = BOARDS.find(b => b.id === 'basys2')) {
  const lines = [`# ${bd.name} on the Digilent Basys2 (generated by test/designs-corpus/boards.mjs)`];
  for (const [port, [res, first, count]] of Object.entries(bd.pins)) {
    const r = board.resources.find(x => x.name === res);
    if (!r) throw new Error(`basys2 has no resource ${res}`);
    for (let i = 0; i < count; i++) {
      const net = count === 1 ? port : `${port}<${i}>`;   // one pin: a scalar port
      lines.push(`NET "${net}" LOC = "${r.pins[first + i]}" | IOSTANDARD = ${r.iostandard || 'LVCMOS33'} ;`);
    }
  }
  if (bd.clock) {
    lines.push(`NET "${bd.clock}" CLOCK_DEDICATED_ROUTE = FALSE ;`, `NET "${bd.clock}" TNM_NET = "${bd.clock}" ;`, `TIMESPEC "TS_${bd.clock}" = PERIOD "${bd.clock}" 20 ns HIGH 50% ;`);
  }
  return `${lines.join('\n')}\n`;
}

/** The sources of a board design: the corpus design's files and the board top. */
function boardSources(bd, manifest, sourceDir) {
  const d = manifest.designs.find(x => x.name === bd.design);
  const src = manifest.sources[d.source];
  return [...d.files, `local:${bd.file}`].map(f => {
    const abs = f.startsWith('local:') ? path.join(HERE, f.slice(6)) : path.join(sourceDir(src), f);
    return { path: path.basename(abs), lang: /\.vhdl?$/i.test(abs) ? 'vhdl' : 'verilog', text: fs.readFileSync(abs, 'utf8'), role: 'design' };
  });
}

/** Write the Silinx project of a board design into dir/<name>. */
export function writeBoardProject(bd, sources, dir) {
  const pdir = path.join(dir, bd.name);
  fs.rmSync(pdir, { recursive: true, force: true });
  fs.mkdirSync(path.join(pdir, 'src'), { recursive: true });
  for (const s of sources) fs.writeFileSync(path.join(pdir, 'src', s.path), s.text);
  fs.writeFileSync(path.join(pdir, 'top.ucf'), boardUcf(bd));
  const files = sources.map(s => ({ path: `src/${s.path}`, lang: s.lang, role: 'design' }));
  const proj = { name: bd.name, version: 1, device: { family: 'spartan3e', part: 'xc3s250e', package: 'cp132', speed: '-4' }, board: 'basys2', top: bd.top, files, constraints: 'top.ucf', impl: { startupClk: 'JtagClk' } };
  fs.writeFileSync(path.join(pdir, 'silinx.json'), `${JSON.stringify(proj, null, 2)}\n`);
  return pdir;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { compile, elaborate } = await import('../../core/compile.js');
  const { Simulator } = await import('../../core/simulator.js');
  const { toVerilog } = await import('../../core/synth-verilog.js');
  const { flaggedSynth } = await import('./lib.mjs');
  const { yosysNode } = await import('../../packages/silinx-fpga/src/synth-open-node.js');
  const args = process.argv.slice(2);
  const fi = args.indexOf('--filter');
  const filter = fi >= 0 ? args.splice(fi, 2)[1] : '';
  const [projects, bits] = args;
  if (!projects) { console.error('usage: boards.mjs <projects dir> [<bit dir>] [--filter name]'); process.exit(2); }
  const manifest = JSON.parse(fs.readFileSync(path.join(HERE, 'manifest.json'), 'utf8'));
  const { fetchDesignCorpus, sourceDir } = await import(pathToFileURL(path.join(ROOT, 'scripts', 'fetch-design-corpus.mjs')).href);
  const todo = BOARD_DESIGNS.filter(b => b.name.includes(filter));
  await fetchDesignCorpus({ manifest: { ...manifest, designs: manifest.designs.filter(d => todo.some(b => b.design === d.name)) } });
  let failed = 0;
  const check = [];
  for (const bd of todo) {
    const sources = boardSources(bd, manifest, sourceDir);
    const pdir = writeBoardProject(bd, sources, path.resolve(projects));
    console.log(`${bd.name}: ${pdir}`);
    // its testbench, in Silinx's simulator
    if (bd.tb) {
      const all = [...sources, { path: path.basename(bd.tb.file), lang: 'verilog', text: fs.readFileSync(path.join(HERE, bd.tb.file), 'utf8'), role: 'sim' }];
      const lib = compile(all);
      const des = elaborate(lib, bd.tb.top);
      const errs = [...lib.errors, ...des.diags].filter(e => e.severity === 'error');
      const sim = errs.length ? null : new Simulator(des);
      if (sim) sim.run(bd.tb.until);
      const ok = sim && sim.log.some(e => bd.tb.pass.test(e.text));
      console.log(`  testbench: ${ok ? 'pass' : 'FAIL'} ${errs.length ? errs[0].message : (sim.log.find(e => /PASS|FAIL/.test(e.text))?.text || '')}`);
      if (!ok) { failed++; continue; }
    }
    // the netlist, when the packer needs synth_xilinx options
    const flowOpts = [];
    if (bd.synthFlags) {
      const lib = compile(sources);
      const des = elaborate(lib, bd.top);
      const { text, top } = toVerilog(des);
      const { args, files } = flaggedSynth(top, text, bd.synthFlags);
      const out = await yosysNode(args, files, () => {});
      fs.writeFileSync(path.join(pdir, 'netlist.json'), out[`${top}.json`]);
      flowOpts.push('--json', path.join(pdir, 'netlist.json'));
    }
    check.push([pdir, ...flowOpts].join(' '));
    if (!bits) continue;
    const out = path.join(path.resolve(projects), `${bd.name}.out`);
    const r = spawnSync(process.execPath, [path.join(ROOT, 'research/s3e-route/open-flow.mjs'), pdir, out, ...flowOpts], { encoding: 'utf8' });
    process.stdout.write(r.stdout.split('\n').filter(l => /^(synthesis|pack|place|route|timing|bitgen)/.test(l)).map(l => `  ${l}\n`).join(''));
    if (r.status !== 0) { console.log(`  FAILED\n${r.stderr.trim().split('\n').slice(-10).map(l => `  ${l}`).join('\n')}`); failed++; continue; }
    fs.mkdirSync(bits, { recursive: true });
    fs.copyFileSync(path.join(out, `${bd.top}.bit`), path.join(bits, `${bd.name}.bit`));
    console.log(`  ${path.join(bits, `${bd.name}.bit`)}\n  on the board: ${bd.look}`);
  }
  console.log(`\ncheck against ISE: SILINX_ISE_HOST=… node scripts/check-open-flow.mjs ${check.join(' ')}`);
  process.exit(failed ? 1 : 0);
}
