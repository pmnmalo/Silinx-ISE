// The gates example (examples/gates, the first example): a 4-bit prime-number detector drawn as a
// schematic (src/gates.sch.json) with its VHDL (src/gates.vhd) kept in sync. The schematic is clean
// (no check message), the HDL shipped is exactly what the schematic editor writes, the drawing has
// the gates it teaches (NOT, AND, OR; NAND only for the second output) and its test bench really
// checks all 16 inputs on both outputs (a design wrong on any single input, or one wrong gate, fails).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { netlist, generateHdl, normalizeDoc } from '../core/schdoc.js';
import { EXAMPLES, TARGETS, targetName, example, exampleUcf, runTestbench } from './examples-lib.mjs';
import { EXAMPLE_ORDER, orderExamples } from '../core/examples.js';

const ex = example('gates');
const doc = JSON.parse(fs.readFileSync(path.join(ex.dir, 'src/gates.sch.json'), 'utf8'));
const hdl = fs.readFileSync(path.join(ex.dir, 'src/gates.vhd'), 'utf8');
const PRIMES = [2, 3, 5, 7, 11, 13];

test('gates: the first example everywhere the examples are listed', () => {
  assert.deepEqual(EXAMPLE_ORDER, ['gates', 'traffic', 'blinky', 'pong', 'stopwatch', 'clock', 'vga', 'isqrt']);
  assert.equal(EXAMPLES[0], 'gates');
  assert.deepEqual(orderExamples(['stopwatch', 'clock', 'zeta', 'blinky', 'traffic', 'alpha', 'pong', 'gates']), ['gates', 'traffic', 'blinky', 'pong', 'stopwatch', 'clock', 'alpha', 'zeta']);
  // (the example folders, as the server's templates: a folder with a silinx.json; not a Finder's .DS_Store)
  const dirs = fs.readdirSync(path.dirname(ex.dir), { withFileTypes: true }).filter((e) => e.isDirectory() && fs.existsSync(path.join(path.dirname(ex.dir), e.name, 'silinx.json'))).map((e) => e.name);
  assert.deepEqual(orderExamples(dirs), EXAMPLE_ORDER);
});

test('gates: the project, the schematic linked to its HDL (top gates, test bench tb_gates)', () => {
  assert.equal(ex.project.top, 'gates');
  assert.equal(ex.project.simTop, 'tb_gates');
  assert.equal(ex.project.preferredLanguage, 'vhdl');
  assert.equal(ex.project.board, 'basys2');
  assert.deepEqual(ex.project.files.map(f => `${f.path}:${f.role}`), ['src/gates.vhd:design', 'sim/tb_gates.vhd:sim']);
  assert.equal(doc.name, 'gates');
  assert.equal(doc.lang, 'vhdl');
  assert.equal(doc.generatedFile, 'src/gates.vhd');
  assert.deepEqual(normalizeDoc(doc), doc, 'saved as the editor keeps it');
});

test('gates: the schematic is clean and the HDL shipped is the one it generates (in sync)', () => {
  assert.deepEqual(netlist(doc).diagnostics, []);
  const g = generateHdl(doc, { lang: 'vhdl' });
  assert.deepEqual(g.diagnostics, []);
  assert.equal(g.filename, 'gates.vhd');
  assert.equal(hdl, g.code);
  // the comments of the example: the function, the minterms, the board use
  assert.match(hdl, /^-- Generated by Silinx from gates\.sch\.json/);
  assert.match(hdl, /2, 3, 5, 7, 11 or 13/);
  assert.match(hdl, /m\(2, 3, 5, 7, 11, 13\)/);
  assert.match(hdl, /F = A'B'C \+ A'BD \+ BC'D \+ B'CD/);
  assert.match(hdl, /SW3\.\.SW0 are A\.\.D/);
  assert.match(hdl, /entity gates is\n {2}port \(\n {4}sw : in std_logic_vector\(3 downto 0\);\n {4}led : out std_logic_vector\(1 downto 0\)\n {2}\);/);
});

test('gates: 16 gates, NOT / AND / OR for prime_sop (LD0) and NAND only for prime_nand (LD1), named nets', () => {
  const count = {};
  for (const s of doc.symbols) count[s.type] = (count[s.type] || 0) + 1;
  assert.deepEqual(count, { slice: 4, inv: 3, and3: 4, or4: 1, nand2: 3, nand3: 4, nand4: 1, busjoin: 1 });
  const nl = netlist(doc);
  const byName = new Map(nl.nets.map(n => [n.name, n]));
  // every net named (no net_<n>)
  assert.deepEqual(nl.nets.filter(n => n.auto).map(n => n.name), []);
  for (const n of ['a', 'b', 'c', 'd', 'a_n', 'b_n', 'c_n', 'a_nand', 'b_nand', 'c_nand', 'p1', 'p4', 'q1', 'q4', 'prime_sop', 'prime_nand']) assert.ok(byName.has(n), n);
  // the cone of each output: the gate types that feed it
  const sym = new Map(doc.symbols.map(s => [s.id, s]));
  const driver = net => net.endpoints.find(e => e.kind === 'pin' && e.dir === 'out');
  const cone = name => {
    const types = new Set(), todo = [byName.get(name)], seen = new Set();
    while (todo.length) {
      const n = todo.pop();
      if (seen.has(n)) continue;
      seen.add(n);
      const d = driver(n);
      if (!d) continue;
      const s = sym.get(d.sym);
      types.add(s.type);
      for (const [k, m] of nl.pinNet) if (k.startsWith(`${s.id}/`) && m !== n) todo.push(m);
    }
    return [...types].sort();
  };
  assert.deepEqual(cone('prime_sop'), ['and3', 'inv', 'or4', 'slice']);
  assert.deepEqual(cone('prime_nand'), ['nand2', 'nand3', 'nand4', 'slice']);
  // the NOT of a NAND: both inputs tied to the same net
  for (const s of doc.symbols.filter(x => x.type === 'nand2')) assert.equal(nl.pinNet.get(`${s.id}/I0`), nl.pinNet.get(`${s.id}/I1`), s.name);
  // led(0) = prime_sop, led(1) = prime_nand (bus join: I0 is the MSB)
  const join = doc.symbols.find(s => s.type === 'busjoin');
  assert.equal(nl.pinNet.get(`${join.id}/I0`).name, 'prime_nand');
  assert.equal(nl.pinNet.get(`${join.id}/I1`).name, 'prime_sop');
});

test('gates: the board pins, sw(3:0) on the switches and led(1:0) on LD0 / LD1, on every board', () => {
  for (const t of TARGETS) {
    const u = exampleUcf('gates', t);
    assert.deepEqual(u.unmatched, [], `${targetName(t)}`);
    for (const p of ['sw<0>', 'sw<1>', 'sw<2>', 'sw<3>', 'led<0>', 'led<1>']) assert.match(u.text, new RegExp(`NET "${p}" +LOC = "\\w+" ;`), `${targetName(t)} ${p}`);
    assert.doesNotMatch(u.text, /clk|PERIOD|unassigned/);
  }
  // the Basys2: SW0 = P11 ... SW3 = B4, LD0 = M5, LD1 = M11
  const b = exampleUcf('gates', { board: 'basys2', variant: '250' }).text;
  assert.match(b, /NET "sw<3>" +LOC = "B4" ;/);
  assert.match(b, /NET "led<0>" +LOC = "M5" ;/);
  assert.match(b, /NET "led<1>" +LOC = "M11" ;/);
});

test('gates: the test bench passes and checks all 16 inputs on both outputs', { timeout: 120000 }, async () => {
  const ok = await runTestbench('gates');
  assert.ok(ok.passed, ok.log.join('\n'));
  assert.deepEqual(ok.log, ['Simulation finished OK']);
  assert.deepEqual(ok.warnings, []);
  // a design wrong on one input only (both LEDs inverted for that number): the test bench reports it
  const line = '  led <= prime_nand & prime_sop;';
  assert.ok(hdl.includes(line));
  const bin = n => n.toString(2).padStart(4, '0');
  for (let n = 0; n < 16; n++) {
    const mutant = hdl.replace(line, `  led <= not (prime_nand & prime_sop) when sw = "${bin(n)}" else prime_nand & prime_sop;`);
    const r = await runTestbench('gates', { edit: { 'src/gates.vhd': mutant } });
    assert.equal(r.passed, false, `input ${n} not checked`);
    const exp = PRIMES.includes(n) ? ["'0'", "'1'"] : ["'1'", "'0'"];
    assert.deepEqual(r.log.filter(l => /ERROR/.test(l)), [
      `ERROR: prime_sop (LD0) for ${n} is ${exp[0]}, expected ${exp[1]}`,
      `ERROR: prime_nand (LD1) for ${n} is ${exp[0]}, expected ${exp[1]}`,
      'ERROR: 2 wrong output(s)',
    ], `input ${n}`);
  }
});

test('gates: one wrong gate in the schematic makes the test bench fail, on the output it feeds', { timeout: 120000 }, async () => {
  const mutate = (name, type) => {
    const d = structuredClone(doc);
    d.symbols.find(s => s.name === name).type = type;
    const g = generateHdl(d, { lang: 'vhdl' });
    assert.deepEqual(g.diagnostics, []);
    return g.code;
  };
  // the AND of BC'D made an OR: wrong on the AND-OR output only
  let r = await runTestbench('gates', { edit: { 'src/gates.vhd': mutate('and_p3', 'or3') } });
  assert.equal(r.passed, false);
  assert.ok(r.log.some(l => /^ERROR: prime_sop \(LD0\)/.test(l)), r.log.join('\n'));
  assert.ok(!r.log.some(l => /^ERROR: prime_nand/.test(l)), r.log.join('\n'));
  // the NAND of B'CD made an AND: wrong on the NAND-only output only
  r = await runTestbench('gates', { edit: { 'src/gates.vhd': mutate('nand_q4', 'and3') } });
  assert.equal(r.passed, false);
  assert.ok(r.log.some(l => /^ERROR: prime_nand \(LD1\)/.test(l)), r.log.join('\n'));
  assert.ok(!r.log.some(l => /^ERROR: prime_sop/.test(l)), r.log.join('\n'));
});
