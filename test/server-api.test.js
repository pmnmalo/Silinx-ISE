test('devices DB and toolchain configuration', async () => {
  const d = await call('GET', '/devices');
  assert.equal(d.status, 200);
  assert.ok(d.body.parts.length > 5 && d.body.boards.some(b => b.id === 'basys2'));
  assert.ok(d.body.families.some(f => f.id === 'spartan6'));

  let r = await call('GET', '/toolchain');
  assert.equal(r.status, 200);
  assert.equal(r.body.config.mode, 'silinx');   // a new installation: the Silinx toolchain (#27)
  assert.equal(r.body.configPath, path.join(process.env.SILINX_CONFIG_DIR, 'config.json'));
  assert.equal(r.body.platform, process.platform);
  assert.ok('openFPGALoader' in r.body.programmers && 'adepttool' in r.body.programmers);
  r = await call('PUT', '/toolchain', { mode: 'ssh', ssh: { host: 'box.lan', user: 'me' } });
  assert.equal(r.status, 200);
  assert.equal(r.body.config.mode, 'ssh');
  assert.equal(r.body.config.ssh.port, 22);   // merged over the defaults
  assert.equal(JSON.parse(await fs.readFile(path.join(process.env.SILINX_CONFIG_DIR, 'config.json'), 'utf8')).ssh.host, 'box.lan');
  for (const [body, re] of [
    [{ mode: 'cloud' }, /invalid mode 'cloud'/],
    [{ ssh: { host: 'a b' } }, /ssh.host contains invalid characters/],
    [{ ssh: { user: 'me;rm' } }, /ssh.user contains invalid characters/],
    [{ local: { settings: '/tmp/evil.sh' } }, /local.settings must be ISE's settings64.sh/],
    [{ docker: { settings: '/opt/x/run' } }, /docker.settings must be ISE's settings64.sh/],
    // (#1433) the values that go into docker's and the programmers' command lines
    [{ docker: { platform: '--privileged' } }, /^docker.platform must be os\/arch \(linux\/amd64\) or empty$/],
    [{ programmer: { tool: 'sh' } }, /^programmer.tool must be one of openFPGALoader, xc3sprog, djtgcfg, impact, adepttool or empty$/],
    [{ programmer: { cable: '-c evil' } }, /^programmer.cable contains invalid characters$/],
    [{ programmer: { device: 'a;b' } }, /^programmer.device contains invalid characters$/],
  ]) {
    r = await call('PUT', '/toolchain', body);
    assert.equal(r.status, 400, JSON.stringify(body));
    assert.match(r.body.error, re);
  }
  // the settings that run a program (or give it arguments) are set in config.json only, never
  // through the API; sent unchanged (Toolchain Settings sends the whole config) they are accepted
  const cfgFile = path.join(process.env.SILINX_CONFIG_DIR, 'config.json');
  for (const body of [{ docker: { command: '/bin/sh' } }, { docker: { extraArgs: ['-c', 'id'] } }, { ssh: { sshArgs: ['-oProxyCommand=id'] } },
    { ssh: { identity: '/tmp/k' } }, { paths: { djtgcfg: '/tmp/x' } }, { ssh: { sshArgs: '-v' } }]) {
    r = await call('PUT', '/toolchain', body);
    assert.equal(r.status, 403, JSON.stringify(body));
    assert.match(r.body.error, new RegExp(`^${Object.keys(body)[0]}\\.?\\w* can only be set in .*config\\.json$`));
  }
  // a settings script the API itself can write (a file of a project), or a docker image given as an option
  await call('POST', '/projects', { name: 'TcScript' });
  assert.equal((await call('PUT', '/projects/TcScript/file?path=settings64.sh', 'echo hi\n')).status, 200);
  for (const [body, re] of [
    [{ mode: 'local', local: { settings: path.join(process.env.SILINX_WORKSPACE, 'TcScript', 'settings64.sh') } }, /^local.settings cannot be a file of the workspace$/],
    [{ mode: 'ssh', ssh: { settings: '/home/me/silinx-build/TcScript/settings64.sh' } }, /^ssh.settings must be an absolute path outside ssh.remoteDir/],
    [{ mode: 'docker', docker: { image: '--privileged' } }, /^docker.image contains invalid characters$/],
  ]) {
    r = await call('PUT', '/toolchain', body);
    assert.equal(r.status, 400, JSON.stringify(body));
    assert.match(r.body.error, re);
  }
  r = await call('PUT', '/toolchain', { ...(await call('GET', '/toolchain')).body.config, ssh: { host: 'box.lan', user: 'me', sshArgs: [] } });
  assert.equal(r.status, 200);
  assert.equal(r.body.config.docker.command, 'docker');
  assert.equal(r.body.config.local.settings, '');
  if (process.platform !== 'win32') assert.equal((await fs.stat(cfgFile)).mode & 0o777, 0o600);
  r = await call('PUT', '/toolchain');   // no body: nothing changes
  assert.equal(r.status, 200);
  assert.equal(r.body.config.mode, 'ssh');
  await call('PUT', '/toolchain', { mode: 'local' });
});

