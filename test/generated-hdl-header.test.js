// The header of the HDL generated from a drawing (#1186): since #1176 that file is read-only, so the header says it
// is generated from the drawing and edited there, never "kept in sync … (edit either one)": the schematic, the ASM
// chart, the state diagram, the truth table and the Petri net, in VHDL and in Verilog; the shipped examples' HDL is
// what the generators write.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { viewHdl } from '../core/view-hdl.js';
import { newPetri } from '../core/petri.js';

const read = (f) => fs.readFileSync(new URL(`../examples/${f}`, import.meta.url), 'utf8');
const DRAWINGS = {
  'gates.sch.json': read('gates/src/gates.sch.json'),
  'speed_ctrl.asm.json': read('blinky/src/speed_ctrl.asm.json'),
  'traffic.fsm.json': read('traffic/src/traffic.fsm.json'),
  'lamps.bool.json': read('traffic/src/lamps.bool.json'),
  'net.pn.json': JSON.stringify(newPetri('net')),
};
// what each header says of the file
const SAYS = {
  'gates.sch.json': 'Generated by Silinx from gates.sch.json — edit the schematic, not this file',
  'speed_ctrl.asm.json': 'Generator   : Silinx ASM editor (edit the chart, not this file).',
  'traffic.fsm.json': 'Generator   : Silinx FSM editor (edit the diagram, not this file).',
  'lamps.bool.json': 'Edit the table, not this file: the file is generated from it. Inputs: phase2, phase1, phase0, blink (phase2 is the',
  'net.pn.json': 'Generator   : Silinx Petri net editor (edit the net, not this file)',
};
const generate = (name, lang) => {
  const m = { ...JSON.parse(DRAWINGS[name]), lang };
  delete m.generatedFile;
  const r = viewHdl(`src/${name}`, JSON.stringify(m));
  assert.deepEqual(r.errors, [], name);
  return r.text;
};
// the comment lines before the entity / module
const header = (code, c) => {
  const lines = code.split('\n');
  return lines.slice(0, lines.findIndex((l) => /^\s*(library|entity|module|`timescale)\b/.test(l))).filter((l) => l.startsWith(c));
};

for (const name of Object.keys(DRAWINGS)) {
  for (const [lang, c] of [['vhdl', '--'], ['verilog', '//']]) {
    test(`#1186 ${name} in ${lang}: the header says the file is generated from the drawing and edited there`, () => {
      const head = header(generate(name, lang), c);
      assert.ok(head.includes(`${c} ${SAYS[name]}`), head.join('\n'));
      for (const l of head) assert.doesNotMatch(l, /either one|kept in sync|stays synchroni[sz]ed|updates the table/i);
    });
  }
}

test('#1186 the shipped examples\' HDL: what the generators write (the header too)', () => {
  for (const [name, hdl] of [['gates.sch.json', 'gates/src/gates.vhd'], ['speed_ctrl.asm.json', 'blinky/src/speed_ctrl.vhd'],
    ['traffic.fsm.json', 'traffic/src/traffic.vhd'], ['lamps.bool.json', 'traffic/src/lamps.vhd']]) {
    assert.equal(generate(name, 'vhdl'), read(hdl), hdl);
  }
});
