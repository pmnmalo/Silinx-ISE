// The Tang Nano 9K (#2303): its pins (Apicula's tangnano9k.cst, LiteX's headers J6 and J7) in the board data, a project's
// constraints made from them as a CST with each pin's I/O standard (its bank 3 at 1.8 V), placed and routed by
// nextpnr-himbaechel-gowin; the GW1NR-9C in the device database (Gowin's DS117, nextpnr's counts)
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { FAMILIES, findPart, findBoard, resolveBoard, validateDevice, partsOfFamily } from '../server/devices.js';
import { boardConstraints } from '../server/projects.js';
import { boardAutoAssign, boardConstraintsText, resourcesOf, GOWIN_PARTS, CST, runFlow, nextpnrGowinNode, yosysNode } from '../packages/silinx-fpga/src/node.js';

// the headers' pins (LiteX's J6 and J7, but the SD card's 36..39) and the board's own (Apicula's CST)
const J6 = ['25', '26', '27', '28', '29', '30', '33', '34', '40', '35', '41', '42', '51', '53', '54', '55', '56', '57', '68', '69'];
const J7 = ['63', '86', '85', '84', '83', '82', '81', '80', '79', '77', '76', '75', '74', '73', '72', '71', '70', '48', '49', '31', '32'];
const OWN = { clk: ['52'], led_n: ['10', '11', '13', '14', '15', '16'], btn_n: ['3', '4'], rx: ['18'], tx: ['17'] };

test('the Tang Nano 9K in the board data: its own pins, the breadboard\'s on its headers, the VGA on J7', () => {
  const b = findBoard('tangnano9k');
  assert.deepEqual(b.device, { family: 'gowin', part: 'gw1nr-9c', package: 'qn88', speed: '-6' });
  assert.deepEqual(validateDevice(b.device), []);
  const pins = Object.fromEntries(b.resources.map(r => [r.name, r.pins]));
  const breadboard = { led: J6.slice(0, 8), sw: J6.slice(8, 16), btn: J6.slice(16, 20) };
  assert.deepEqual(pins, { ...OWN, ...breadboard, seg: J7.slice(0, 7), dp: [J7[7]], an: J7.slice(8, 12) });
  assert.equal(new Set(Object.values(pins).flat()).size, Object.values(pins).flat().length);
  for (const n of ['led_n', 'btn_n', 'seg', 'dp', 'an']) assert.equal(b.resources.find(r => r.name === n).extra.activeLow, true, n);
  // (its bank 3 at 1.8 V: the LEDs and buttons; the rest 3.3 V)
  assert.deepEqual(b.resources.filter(r => r.iostandard === 'LVCMOS18').map(r => r.name), ['led_n', 'btn_n']);
  const v = findBoard('tangnano9k-vga');
  assert.deepEqual(v.device, b.device);
  const vpins = Object.fromEntries(v.resources.map(r => [r.name, r.pins]));
  assert.deepEqual(vpins, { ...OWN, ...breadboard, vga_red: J7.slice(0, 3), vga_green: J7.slice(3, 6), vga_blue: J7.slice(6, 8), vga_hsync: [J7[8]], vga_vsync: [J7[9]] });
  for (const r of [...b.resources, ...v.resources]) assert.equal(r.verified, !Object.keys({ ...breadboard, seg: 1, dp: 1, an: 1 }).includes(r.name) && !/^vga_/.test(r.name), r.name);
});

test('the Gowin in the device database: after the ECP5, the GW1NR-9C of nextpnr\'s devices here, its figures', () => {
  assert.deepEqual(FAMILIES.slice(-3).map(f => f.id), ['ice40', 'ecp5', 'gowin']);
  assert.deepEqual(partsOfFamily('gowin').map(p => p.part), GOWIN_PARTS);
  const p = findPart('gw1nr-9c');
  assert.deepEqual([p.luts, p.ffs, p.brams, p.multipliers, p.plls, p.packages.qn88.userIo, p.speeds], [8640, 6480, 26, 20, 2, 71, ['-6']]);
  const res = Object.fromEntries(resourcesOf(p, 'qn88').map(r => [r.id, r.count]));
  assert.deepEqual([res.luts, res.ffs, res.ebr, res.mult, res.pll, res.iob], [8640, 6480, 26, 20, 2, 71]);
  assert.deepEqual(validateDevice({ part: 'gw1nr-9c', package: 'qn88', speed: '-5' }), ["speed grade '-5' not available for gw1nr-9c-qn88 (valid: -6)"]);
});

const TOP = 'module top(input clk, input [1:0] btn_n, input [3:0] sw, output [5:0] led_n);\n  reg [23:0] c = 0;\n  always @(posedge clk) c <= c + 1;\n  assign led_n = ~{c[23:22], sw & {2{btn_n}}};\nendmodule\n';
const PORTS = [{ name: 'clk', dir: 'in', width: 1 }, { name: 'btn_n', dir: 'in', width: 2, msb: 1, lsb: 0 }, { name: 'sw', dir: 'in', width: 4, msb: 3, lsb: 0 },
  { name: 'led_n', dir: 'out', width: 6, msb: 5, lsb: 0 }];
const CST_TEXT = name => `// CST for top 'top' on ${name} (gw1nr-9c-6-qn88), generated by Silinx\n\nIO_LOC "clk" 52;\nIO_PORT "clk" IO_TYPE=LVCMOS33;\n`
  + `${['3', '4'].map((p, i) => `IO_LOC "btn_n[${i}]" ${p};\nIO_PORT "btn_n[${i}]" IO_TYPE=LVCMOS18;\n`).join('')}`
  + `${J6.slice(8, 12).map((p, i) => `IO_LOC "sw[${i}]" ${p};\nIO_PORT "sw[${i}]" IO_TYPE=LVCMOS33;\n`).join('')}`
  + `${OWN.led_n.map((p, i) => `IO_LOC "led_n[${i}]" ${p};\nIO_PORT "led_n[${i}]" IO_TYPE=LVCMOS18;\n`).join('')}// create_clock -name clk -period 37.037 [get_ports {clk}]\n`;

test('a board\'s constraints in its family\'s format: a CST on the Tang Nano 9K, each pin\'s I/O standard the board\'s; read back the same', () => {
  const r = resolveBoard('tangnano9k');
  const { assignments, clocks, unmatched } = boardAutoAssign(PORTS, { name: r.board.name, device: r.device, resources: r.resources });
  assert.deepEqual(unmatched, []);
  const text = boardConstraintsText({ device: r.device, board: { ...r.board, resources: r.resources }, ports: PORTS, assignments, clocks, header: "UCF for top 'top' on Sipeed Tang Nano 9K (gw1nr-9c-6-qn88), generated by Silinx" });
  assert.equal(text, CST_TEXT('Sipeed Tang Nano 9K'));
  assert.deepEqual(CST.read(text).clocks, [{ net: 'clk', period: 37.037 }]);
});

test('a project on the Tang Nano 9K: its constraints/top.cst from the board, placed and routed at those pins, nextpnr\'s one warning', async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'silinx-tangnano9k-'));
  try {
    await fs.mkdir(path.join(dir, 'src'));
    await fs.writeFile(path.join(dir, 'src/top.v'), TOP);
    const pj = { name: 'tn', board: 'tangnano9k', device: findBoard('tangnano9k').device, top: 'top', files: [{ path: 'src/top.v', lang: 'verilog', role: 'design' }], constraints: 'constraints/top.cst' };
    await boardConstraints(dir, pj);
    const cst = await fs.readFile(path.join(dir, 'constraints/top.cst'), 'utf8');
    assert.equal(cst, CST_TEXT('Sipeed Tang Nano 9K'));
    const log = [], files = {};
    const io = { log: l => log.push(l), sources: () => [{ path: 'top.v', lang: 'verilog', text: TOP }], ucf: cst, ucfName: 'top.cst',
      yosys: yosysNode, nextpnr: { gowin: nextpnrGowinNode() }, write: (n, d) => { files[n] = d; return `build/${n}`; }, read: n => files[n] ?? null, save: () => {} };
    const r = await runFlow({ top: 'top', family: 'gowin', device: 'gw1nr-9c', pkg: 'qn88', speed: '-6', steps: ['synth', 'translate', 'par', 'bitgen'] }, io);
    assert.equal(files['top.fs'].length, 2069320);
    assert.ok(r.ok, r.error);
    // (nextpnr-himbaechel-gowin routes a net through the general routing where its dedicated routing (a global's) did not reach)
    assert.deepEqual(log.filter(l => /^WARNING/.test(l)), ["WARNING:Place - Failed to route net 'led_n_OBUF_O_4_I_LUT2_F_I1[1]' from X28Y28/F6 to X1Y20/B0 using dedicated routing."]);
    assert.ok(r.report.par.constraintsMet);
    assert.deepEqual(r.report.par.fmax.map(f => [f.clock, f.constraint]), [['clk', 27]]);
    assert.ok(log.includes('Netlist of <top> read; constraints: top.cst, 13 pin location(s), 1 PERIOD constraint(s).'));
  } finally {
    await fs.rm(dir, { recursive: true, force: true });
  }
});
