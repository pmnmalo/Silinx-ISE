// The MCP server on the Gowin (#2303, #2674: what the interface does): list_devices lists the family and the Tang Nano 9K,
// set_design_properties makes the constraints a CST from the board's pins, new_source writes the CST template, the wizards
// that make Xilinx primitives refuse it, run_process builds its .fs (gowin_pack, Silinx's port) and get_report gives its reports;
// every result's text.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { scratchEnv } from './server-helpers.js';

let tmp;
before(async () => { tmp = await scratchEnv('silinx-mcp-gowin-'); });
after(() => fs.rmSync(tmp, { recursive: true, force: true }));

const { handle } = await import('../server/mcp.js');
const P = await import('../server/projects.js');
let id = 0;
async function call(name, args = {}) {
  const r = (await handle({ jsonrpc: '2.0', id: ++id, method: 'tools/call', params: { name, arguments: args } })).result;
  return { text: r.content[0].text, data: r.structuredContent, isError: r.isError };
}
const ok = async (name, args) => { const r = await call(name, args); assert.equal(r.isError, false, r.text); return r; };
const fails = async (name, args, message) => { const r = await call(name, args); assert.equal(r.isError, true); assert.equal(r.text, `${name}: ${message}`); };

test('list_devices: the Gowin GW1N and its GW1NR-9C, the Tang Nano 9K and its VGA board', async () => {
  const all = await ok('list_devices');
  assert.deepEqual(all.data.boards.filter(b => /^tangnano9k/.test(b.id)).map(b => [b.id, b.device, b.experimental]), [['tangnano9k', 'gw1nr-9cqn88-6', undefined], ['tangnano9k-vga', 'gw1nr-9cqn88-6', undefined]]);
  const gowin = await ok('list_devices', { family: 'gowin' });
  assert.equal(gowin.text, 'Devices:\n  Gowin GW1N (gowin):\n    gw1nr-9c: qn88 -6');
});

test('set_design_properties: the Tang Nano 9K, its pins written as a CST with their I/O standards; new_source the CST template; the wizards refuse it', async () => {
  await ok('new_project_from_example', { name: 'b1', example: 'blinky' });
  const r = await ok('set_design_properties', { project: 'b1', board: 'tangnano9k', update_constraints: true });
  assert.equal(r.text, 'WARNING: this device\'s constraints are CST: constraints/top.cst is the project\'s now, constraints/top.ucf was not converted.\n'
    + 'Device set to gw1nr-9c-6-qn88 (board tangnano9k); synthesis tool silinx; constraints/top.cst written from the tangnano9k\'s pins.');
  const cst = fs.readFileSync(path.join(P.projectDir('b1'), 'constraints/top.cst'), 'utf8');
  assert.match(cst, /^\/\/ CST for top 'top' on Sipeed Tang Nano 9K \(gw1nr-9c-6-qn88\), generated by Silinx\n\nIO_LOC "clk" 52;\nIO_PORT "clk" IO_TYPE=LVCMOS33;\n/);
  assert.match(cst, /\n\/\/ create_clock -name clk -period 37\.037 \[get_ports \{clk\}\]\n$/);
  await fails('set_design_properties', { project: 'b1', synth_tool: 'xst' }, 'the GW1NR-9C is the Silinx toolchain\'s only: no XST');
  assert.equal((await ok('new_source', { project: 'b1', type: 'constraints', name: 'pins' })).text, 'Created Implementation Constraints File \'constraints/pins.cst\'.');
  assert.match(fs.readFileSync(path.join(P.projectDir('b1'), 'constraints/pins.cst'), 'utf8'), /^\/\/ Physical constraints for b1\n\/\/ Target: gw1nr-9c-6-qn88\n/);
  await fails('constraints_wizard', { project: 'b1' }, 'the GW1NR-9C\'s constraints are a CST: new_source constraints writes one');
  await fails('clock_manager', { project: 'b1' }, 'The Clocking Wizard makes a DCM for the Spartan-3E and a PLL for the Spartan-6: choose one of them as the target device (set_design_properties).');
});

test('run_process: blinky on the Tang Nano 9K to its .fs, nextpnr\'s warnings; get_report its reports', { timeout: 600000 }, async () => {
  await ok('new_project_from_example', { name: 'bi', example: 'blinky' });
  await ok('set_design_properties', { project: 'bi', board: 'tangnano9k', update_constraints: true });
  const run = await ok('run_process', { project: 'bi', process: 'bitstream' });
  assert.equal(run.data.warnings.length, 8);
  for (const w of run.data.warnings) assert.match(w, /^WARNING:Place - Failed to route net '[^']+' from \S+ to \S+ using dedicated routing\.$/);
  assert.ok(fs.existsSync(path.join(P.projectDir('bi'), 'build', 'open', 'routed.json')));
  const summary = (await ok('get_report', { project: 'bi' })).data.summary;
  assert.deepEqual(summary.par.fmax.map(f => [f.clock, f.constraint]), [['clk', 27]]);
  assert.ok(summary.map.utilization.some(u => u.name === 'LUT4'));
  assert.equal(summary.bit.size, 2069320);
  assert.ok(fs.existsSync(path.join(P.projectDir('bi'), 'build', 'top.fs')));
  await fails('run_process', { project: 'bi', process: 'timing' }, 'no step trce (the steps: synth, translate, par, bitgen)');
});
