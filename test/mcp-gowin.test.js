// The MCP server on the Gowin (#2303, #2674: what the interface does): list_devices lists the family and the Tang Nano 9K,
// set_design_properties makes the constraints a CST from the board's pins, new_source writes the CST template, the wizards
// that make Xilinx primitives refuse it, run_process builds its .fs (gowin_pack, Silinx's port) and get_report gives its reports;
// every result's text.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { scratchEnv } from './server-helpers.js';

let tmp;
before(async () => { tmp = await scratchEnv('silinx-mcp-gowin-'); });
after(() => fs.rmSync(tmp, { recursive: true, force: true }));

const { handle } = await import('../server/mcp.js');
const P = await import('../server/projects.js');
let id = 0;
async function call(name, args = {}) {
  const r = (await handle({ jsonrpc: '2.0', id: ++id, method: 'tools/call', params: { name, arguments: args } })).result;
  return { text: r.content[0].text, data: r.structuredContent, isError: r.isError };
}
const ok = async (name, args) => { const r = await call(name, args); assert.equal(r.isError, false, r.text); return r; };
const fails = async (name, args, message) => { const r = await call(name, args); assert.equal(r.isError, true); assert.equal(r.text, `${name}: ${message}`); };

test('list_devices: the Gowin GW1N and its GW1NR-9C, the Tang Nano 9K and its VGA board', async () => {
  const all = await ok('list_devices');
  assert.deepEqual(all.data.boards.filter(b => /^tangnano9k/.test(b.id)).map(b => [b.id, b.device, b.experimental]), [['tangnano9k', 'gw1nr-9cqn88-6', undefined], ['tangnano9k-vga', 'gw1nr-9cqn88-6', undefined]]);
  const gowin = await ok('list_devices', { family: 'gowin' });
  assert.equal(gowin.text, 'Devices:\n  Gowin GW1N (gowin):\n    gw1nr-9c: qn88 -6');
});

test('set_design_properties: the Tang Nano 9K, its pins written as a CST with their I/O standards; new_source the CST template; the Xilinx primitives\' wizards refuse it', async () => {
  await ok('new_project_from_example', { name: 'b1', example: 'blinky' });
  const r = await ok('set_design_properties', { project: 'b1', board: 'tangnano9k', update_constraints: true });
  assert.equal(r.text, 'WARNING: this device\'s constraints are CST: constraints/top.cst is the project\'s now, constraints/top.ucf was not converted.\n'
    // (its 27 MHz clock as the top's CLK_HZ, #3710)
    + 'src/top.vhd: CLK_HZ = 27_000_000, the Sipeed Tang Nano 9K\'s clock and inputs (the defaults of its generics).\n'
    + 'Device set to gw1nr-9c-6-qn88 (board tangnano9k); synthesis tool silinx; constraints/top.cst written from the tangnano9k\'s pins.');
  const cst = fs.readFileSync(path.join(P.projectDir('b1'), 'constraints/top.cst'), 'utf8');
  assert.match(cst, /^\/\/ CST for top 'top' on Sipeed Tang Nano 9K \(gw1nr-9c-6-qn88\), generated by Silinx\n\nIO_LOC "clk" 52;\nIO_PORT "clk" IO_TYPE=LVCMOS33;\n/);
  assert.match(cst, /\n\/\/ create_clock -name clk -period 37\.037 \[get_ports \{clk\}\]\n$/);
  await fails('set_design_properties', { project: 'b1', synth_tool: 'xst' }, 'the GW1NR-9C is the Silinx toolchain\'s only: no XST');
  assert.equal((await ok('new_source', { project: 'b1', type: 'constraints', name: 'pins' })).text, 'Created Implementation Constraints File \'constraints/pins.cst\'.');
  assert.match(fs.readFileSync(path.join(P.projectDir('b1'), 'constraints/pins.cst'), 'utf8'), /^\/\/ Physical constraints for b1\n\/\/ Target: gw1nr-9c-6-qn88\n/);
  // (the CST Wizard, #2296: test/mcp-constraints.test.js)
  await fails('constraints_wizard', { project: 'b1' }, 'constraints/top.cst already exists: choose another name.');
  await fails('clock_manager', { project: 'b1' }, 'The Clocking Wizard makes a DCM for the Spartan-3E and a PLL for the Spartan-6: choose one of them as the target device (set_design_properties).');
});

test('run_process: blinky on the Tang Nano 9K to its .fs, nextpnr\'s warnings; get_report its reports', { timeout: 600000 }, async () => {
  await ok('new_project_from_example', { name: 'bi', example: 'blinky' });
  await ok('set_design_properties', { project: 'bi', board: 'tangnano9k', update_constraints: true });
  const run = await ok('run_process', { project: 'bi', process: 'bitstream' });
  assert.equal(run.data.warnings.length, 8);
  for (const w of run.data.warnings) assert.match(w, /^WARNING:Place - Failed to route net '[^']+' from \S+ to \S+ using dedicated routing\.$/);
  assert.ok(fs.existsSync(path.join(P.projectDir('bi'), 'build', 'open', 'routed.json')));
  const summary = (await ok('get_report', { project: 'bi' })).data.summary;
  assert.deepEqual(summary.par.fmax.map(f => [f.clock, f.constraint]), [['clk', 27]]);
  assert.ok(summary.map.utilization.some(u => u.name === 'LUT4'));
  assert.equal(summary.bit.size, 2069320);
  assert.ok(fs.existsSync(path.join(P.projectDir('bi'), 'build', 'top.fs')));
  // (its timing nextpnr's, #2300: test/mcp-nextpnr-reports.test.js; no power estimate)
  await fails('run_process', { project: 'bi', process: 'power' }, 'no step xpwr (the steps: synth, translate, par, trce, bitgen)');
});

test('run_process and get_report: a CST with no clock, the clock reported with no constraint, not nextpnr\'s 12 MHz (#3488)', { timeout: 600000 }, async () => {
  await ok('new_project_from_example', { name: 'nc', example: 'blinky' });
  await ok('set_design_properties', { project: 'nc', board: 'tangnano9k', update_constraints: true });
  const file = path.join(P.projectDir('nc'), 'constraints/top.cst');
  const cst = fs.readFileSync(file, 'utf8');
  await ok('write_file', { project: 'nc', path: 'constraints/top.cst', text: cst.replace(/^\/\/ create_clock .*\n/m, '') });
  const run = await ok('run_process', { project: 'nc', process: 'implement' });
  assert.equal(run.data.warnings.length, 8);
  for (const w of run.data.warnings) assert.match(w, /^WARNING:Place - Failed to route net '[^']+' from \S+ to \S+ using dedicated routing\.$/);
  const summary = (await ok('get_report', { project: 'nc' })).data.summary;
  assert.deepEqual(summary.par.fmax.map(f => [f.clock, f.constraint]), [['clk', null]]);
  assert.equal(summary.par.constraintsMet, true);
});

// #3498: a design that instantiates the Gowin's rPLL and OSC elaborates (the Gowin primitives' models, #2299): set_top, Check
// Syntax and the test bench's simulation (the PLL's lock, its clock's and the oscillator's edges counted), its synthesis
const PLL_TOP = `module top(input clk, output lock, output reg [3:0] n = 0, output reg [3:0] m = 0);
  wire fast, slow;
  rPLL #(.FCLKIN("27"), .IDIV_SEL(0), .FBDIV_SEL(1), .ODIV_SEL(8), .DEVICE("GW1NR-9C")) u (.CLKIN(clk), .CLKOUT(fast), .LOCK(lock), .CLKFB(1'b0),
    .RESET(1'b0), .RESET_P(1'b0), .FBDSEL(6'b0), .IDSEL(6'b0), .ODSEL(6'b0), .PSDA(4'b0), .DUTYDA(4'b0), .FDLY(4'b0));
  OSC #(.FREQ_DIV(10), .DEVICE("GW1NR-9C")) o (.OSCOUT(slow));
  always @(posedge fast) n <= n + 1;
  always @(posedge slow) m <= m + 1;
endmodule
`;
const PLL_TB = `\`timescale 1ns / 1ps
module tb_top;
  reg clk = 0;
  wire lock;
  wire [3:0] n, m;
  top dut (.clk(clk), .lock(lock), .n(n), .m(m));
  always #18.5 clk = ~clk;
  initial begin #500; $display("lock %b n %0d m %0d", lock, n, m); end
endmodule
`;
test('a project instantiating an rPLL and an OSC: set_top, check_syntax and simulate, its synthesis (#3498)', { timeout: 600000 }, async () => {
  await ok('new_project', { name: 'pll' });
  await ok('set_design_properties', { project: 'pll', board: 'tangnano9k' });
  await ok('write_file', { project: 'pll', path: 'src/top.v', text: PLL_TOP });
  await ok('write_file', { project: 'pll', path: 'sim/tb_top.v', text: PLL_TB });
  await ok('set_top', { project: 'pll', top: 'top', sim_top: 'tb_top' });
  assert.match((await ok('check_syntax', { project: 'pll' })).text, /^Process "Check Syntax" of <top> completed successfully \(\d+ signals, \d+ processes\)\.$/);
  assert.match((await ok('check_syntax', { project: 'pll', simulation: true })).text, /^Process "Check Syntax" of <tb_top> completed successfully \(\d+ signals, \d+ processes\)\.$/);
  const s = await ok('simulate', { project: 'pll', time_ns: 600, signals: [] });
  // CLKIN rises at 18.5, 55.5 … ns: locked at the third (92.5 ns), CLKOUT (54 MHz) from the fourth (129.5 ns), a rising edge every
  // 18.5 ns: 21 to 499.5 ns, n = 21 mod 16; OSCOUT (25 MHz) rises at 20, 60 … 460 ns: 12
  assert.deepEqual([s.data.log.map(l => l.text), s.data.warnings, s.data.failed], [['lock 1 n 5 m 12'], [], false]);
  const run = await ok('run_process', { project: 'pll', process: 'synthesize' });
  assert.deepEqual(run.data.warnings, []);
  // (the primitives kept as Gowin's cells, their names as Gowin writes them)
  const net = fs.readFileSync(path.join(P.projectDir('pll'), 'build', 'open', 'top_yosys.v'), 'utf8');
  assert.match(net, /^\s*rPLL #\(/m);
  assert.match(net, /^\s*OSC #\(/m);
});
