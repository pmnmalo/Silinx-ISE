// The MCP server on the ECP5 (#2302, #2674: what the interface does): list_devices lists the family and the ULX3S with its
// sizes, set_design_properties makes the constraints an LPF from the board's pins, new_source writes the LPF template, the
// wizards that make Xilinx primitives refuse it, run_process builds its .bit through nextpnr-ecp5 and ecppack and get_report
// gives its reports; every result's text.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { scratchEnv } from './server-helpers.js';

let tmp;
before(async () => { tmp = await scratchEnv('silinx-mcp-ecp5-'); });
after(() => fs.rmSync(tmp, { recursive: true, force: true }));

const { handle } = await import('../server/mcp.js');
const P = await import('../server/projects.js');
let id = 0;
async function call(name, args = {}) {
  const r = (await handle({ jsonrpc: '2.0', id: ++id, method: 'tools/call', params: { name, arguments: args } })).result;
  return { text: r.content[0].text, data: r.structuredContent, isError: r.isError };
}
const ok = async (name, args) => { const r = await call(name, args); assert.equal(r.isError, false, r.text); return r; };
const fails = async (name, args, message) => { const r = await call(name, args); assert.equal(r.isError, true); assert.equal(r.text, `${name}: ${message}`); };

test('list_devices: the ECP5 and its parts, the ULX3S and its four sizes; not experimental', async () => {
  const all = await ok('list_devices');
  const ulx3s = all.data.boards.find(b => b.id === 'ulx3s');
  assert.deepEqual(ulx3s.variants.map(v => [v.id, v.device, !!v.default]), [['12f', 'lfe5u-12fcabga381-6', false], ['25f', 'lfe5u-25fcabga381-6', false], ['45f', 'lfe5u-45fcabga381-6', false], ['85f', 'lfe5u-85fcabga381-6', true]]);
  assert.equal(ulx3s.experimental, undefined);
  assert.ok(all.data.boards.some(b => b.id === 'ulx3s-vga'));
  assert.match(all.text, /\n {2}ulx3s: Radiona ULX3S \(12f lfe5u-12fcabga381-6; 25f lfe5u-25fcabga381-6; 45f lfe5u-45fcabga381-6; 85f lfe5u-85fcabga381-6, the default\)\n/);
  const ecp5 = await ok('list_devices', { family: 'ecp5' });
  assert.deepEqual(ecp5.data.families.map(f => [f.id, f.experimental]), [['ecp5', undefined]]);
  assert.match(ecp5.text, /^Devices:\n {2}ECP5 \(ecp5\):\n {4}lfe5u-12f: cabga256 -6 -7 -8, csfbga285 -6 -7 -8, cabga381 -6 -7 -8, tqfp144 -6 -7 -8\n/);
  assert.match(ecp5.text, /\n {4}lfe5um5g-85f: csfbga285 -8, cabga381 -8, cabga554 -8, cabga756 -8\n?$/);
});

test('set_design_properties: the ULX3S, its pins written as an LPF, the example\'s UCF not converted, no XST', async () => {
  await ok('new_project_from_example', { name: 'b1', example: 'blinky' });
  const r = await ok('set_design_properties', { project: 'b1', board: 'ulx3s', update_constraints: true });
  assert.equal(r.text, 'WARNING: this device\'s constraints are LPF: constraints/top.lpf is the project\'s now, constraints/top.ucf was not converted.\n'
    // (its 25 MHz clock as the top's CLK_HZ, #3710)
    + 'src/top.vhd: CLK_HZ = 25_000_000, the Radiona ULX3S\'s clock and inputs (the defaults of its generics).\n'
    + 'Device set to lfe5u-85f-6-cabga381 (board ulx3s); synthesis tool silinx; constraints/top.lpf written from the ulx3s\'s pins.');
  const pj = await P.readProject('b1');
  assert.deepEqual([pj.device, pj.constraints, pj.synthTool], [{ family: 'ecp5', part: 'lfe5u-85f', package: 'cabga381', speed: '-6' }, 'constraints/top.lpf', 'silinx']);
  const lpf = fs.readFileSync(path.join(P.projectDir('b1'), 'constraints/top.lpf'), 'utf8');
  assert.match(lpf, /^# LPF for top 'top' on Radiona ULX3S \(lfe5u-85f-6-cabga381\), generated by Silinx\n\nLOCATE COMP "clk" SITE "G2";\n/);
  assert.match(lpf, /\nLOCATE COMP "an\[0\]" SITE "C11";\n/);
  assert.match(lpf, /\nFREQUENCY PORT "clk" 25 MHZ;\n$/);
  await fails('set_design_properties', { project: 'b1', synth_tool: 'xst' }, 'the LFE5U-85F is the Silinx toolchain\'s only: no XST');
  // a smaller ULX3S: its variant
  const small = await ok('set_design_properties', { project: 'b1', board: 'ulx3s', variant: '25f' });
  assert.equal(small.text, 'Device set to lfe5u-25f-6-cabga381 (board ulx3s); synthesis tool silinx.');
});

test('new_source constraints: the LPF template; the Xilinx primitives\' wizards refuse the ECP5', async () => {
  await ok('new_project', { name: 'e' });
  await ok('set_design_properties', { project: 'e', board: 'none', part: 'lfe5u-45f', package: 'cabga381', speed: '-8' });
  assert.equal((await ok('new_source', { project: 'e', type: 'constraints', name: 'pins' })).text, 'Created Implementation Constraints File \'constraints/pins.lpf\'.');
  assert.match(fs.readFileSync(path.join(P.projectDir('e'), 'constraints/pins.lpf'), 'utf8'), /^# Logical preference file for e\n# Target: lfe5u-45f-8-cabga381\n#\n# Example:\n# LOCATE COMP "clk" SITE "G2";\n/);
  // (the LPF Wizard, #2296: test/mcp-constraints.test.js; this project has no module yet)
  await fails('constraints_wizard', { project: 'e' }, 'The project has no design module.');
  await fails('clock_manager', { project: 'e' }, 'The Clocking Wizard makes a DCM for the Spartan-3E and a PLL for the Spartan-6: choose one of them as the target device (set_design_properties).');
  await fails('block_memory', { project: 'e' }, 'The Block Memory wizard makes block RAMs of the Spartan-3E and the Spartan-6: choose one of them as the target device (set_design_properties).');
});

test('run_process: blinky on the ULX3S to its .bit through nextpnr-ecp5 and ecppack, no warnings; get_report its reports', { timeout: 600000 }, async () => {
  await ok('new_project_from_example', { name: 'bi', example: 'blinky' });
  await ok('set_design_properties', { project: 'bi', board: 'ulx3s', update_constraints: true });
  const run = await ok('run_process', { project: 'bi', process: 'bitstream' });
  assert.deepEqual(run.data.warnings, []);
  assert.ok(fs.existsSync(path.join(P.projectDir('bi'), 'build', 'top.bit')));
  assert.ok(fs.existsSync(path.join(P.projectDir('bi'), 'build', 'open', 'routed.config')));
  const summary = (await ok('get_report', { project: 'bi' })).data.summary;
  assert.equal(summary.bit.size, 1927725);
  assert.deepEqual(summary.par.fmax.map(f => [f.clock, f.constraint]), [['clk', 25]]);
  assert.ok(summary.map.utilization.some(u => u.name === 'TRELLIS_COMB'));
  // (its timing nextpnr's, #2300: test/mcp-nextpnr-reports.test.js; no power estimate)
  await fails('run_process', { project: 'bi', process: 'power' }, 'no step xpwr (the steps: synth, translate, par, trce, bitgen)');
});
